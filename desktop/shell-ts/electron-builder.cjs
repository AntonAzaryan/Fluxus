/**
 * Упаковка дистрибутивов контейнера (задача 6.2 change'а desktop-shell) —
 * вне гейта: `npm run check` контейнера не собирает и не запускает (DSK-6).
 *
 * Конфиг читает `FLUXUS_APP` и упаковывает каталог, разложенный `bin/pack.mjs`
 * (`build/<app>/`). Один профиль — один дистрибутив: контейнер один и тот же,
 * различает их профиль (DSK-1, DSK-5), и «общий лаунчер против дистрибутива на
 * приложение» — вопрос дистрибуции, оставленный открытым в design.md.
 *
 * Иконок и подписи здесь нет намеренно: и то и другое — часть дистрибуции, а
 * не контракта границы, и заводить их пустыми значениями значило бы делать вид,
 * что вопрос решён.
 */
const app = process.env.FLUXUS_APP ?? 'game';

// Версия Electron берётся у установленного пакета, а не из диапазона в
// манифесте: упаковщику нужна точная — он по ней качает платформенные бинари.
// Диапазон в devDependencies при этом остаётся диапазоном: гейт контейнера не
// собирает, и пинить версию ради упаковки значило бы пинить её всем.
const electronVersion = require('electron/package.json').version;

module.exports = {
  appId: `dev.fluxus.${app}`,
  electronVersion,
  // Имя берётся у ПРОФИЛЯ, разложенного `bin/pack.mjs`, а не у списка имён здесь:
  // профилей три и будет больше, а перечисление, о котором забывают при
  // добавлении четвёртого, выпускает дистрибутив под чужим именем (DSK-1).
  productName: require(`./build/${app}/package.json`).productName,
  directories: {
    app: `build/${app}`,
    output: `dist/${app}`,
  },
  // Каталог уже разложен `bin/pack.mjs`: бандл, дерево контента, профиль и
  // исходники контейнера. Ставить сюда фильтры значило бы описывать раскладку
  // дважды.
  files: ['**/*'],
  asar: true,
  // Публикации нет: дистрибуция, автообновление и магазины — не этот change
  // (design.md, Non-Goals). Без явного `null` упаковщик пытается собрать
  // метаданные обновления и падает на их отсутствии.
  publish: null,
  win: { target: ['nsis', 'zip'] },
  mac: { target: ['dmg', 'zip'], category: 'public.app-category.developer-tools' },
  linux: { target: ['AppImage', 'tar.gz'], category: 'Development' },
};
