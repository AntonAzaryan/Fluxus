/**
 * Отпечаток предъявленного сертификата (DSK-8, решение D4).
 *
 * Закрепление сервиса — строка, которую написал САМ сервис (`detached.ts`,
 * `readPinFile`); чтобы сверить её с сертификатом, предъявленным в соединении,
 * контейнеру нужен ровно один счёт: PEM → SHA-256 его DER в шестнадцатеричном
 * нижнем регистре без разделителей. Тот же счёт, тем же алгоритмом, делает и
 * сервис, когда пишет закрепление, — два разных способа посчитать один
 * отпечаток были бы способом им разойтись.
 *
 * Считать здесь, а не в клее Electron, — требование DSK-6: клей вне гейта, и
 * проверяемая логика обязана жить на чистом Node. Клей передаёт сюда
 * `certificate.data` события `certificate-error` и больше ничего не решает.
 *
 * Импорта из пакета агента здесь нет и быть не может: контейнер не зависит от
 * пакетов игры (DSK-3) — он повторяет АЛГОРИТМ, а не тянет чужой код.
 */
import { createHash } from 'node:crypto';

/** Форма отпечатка: SHA-256 в шестнадцатеричном нижнем регистре без разделителей. */
const FINGERPRINT = /^[0-9a-f]{64}$/;

/**
 * Первый блок сертификата PEM. Именно ПЕРВЫЙ, а не всё содержимое файла: в
 * соединении закрепляется лист цепочки, и склеенный DER нескольких блоков не
 * является сертификатом ни одной из сторон — его отпечаток не совпал бы ни с
 * чем и молча превратил бы сверку в вечный отказ.
 */
const CERTIFICATE = /-----BEGIN CERTIFICATE-----([\s\S]*?)-----END CERTIFICATE-----/;

/** Похожа ли строка на отпечаток: ровно 64 hex-знака нижнего регистра (решение D1). */
export function isFingerprint(text: string): boolean {
  return FINGERPRINT.test(text);
}

/**
 * Отпечаток PEM-сертификата; пустая строка — «это не сертификат».
 *
 * Пустой ответ здесь безопасен по построению: закрепления пустыми не бывают
 * (`isFingerprint`), и нераспознанный PEM поэтому не совпадёт ни с одним из
 * них — сверка отказывает, а не принимает неизвестное.
 */
export function certificateFingerprint(pem: string): string {
  const block = CERTIFICATE.exec(pem);
  if (block === null) return '';
  const body = block[1]!.replace(/\s+/g, '');
  if (body === '') return '';
  return createHash('sha256').update(Buffer.from(body, 'base64')).digest('hex');
}
