/**
 * Материал фикстурной рабочей области набора тестов.
 *
 * Жил в `src/areas/material.{ts,json}` — как материал-заглушка настоящей
 * области систем. Настоящей области систем нужен открытый проект, а тесты
 * каркаса не должны зависеть от того, нашлась ли сцена, поэтому «вторая
 * непохожая область» стала фикстурой набора (`stubArea.ts`), а материал уехал
 * вместе с ней. Ни `src/`, ни `app/` его больше не читают.
 *
 * Лежит данными, а не литералами в коде области, по той же причине, по какой
 * данными лежит контрольный случай визуального языка: строки, приходящие в
 * интерфейс из документа, обязаны приходить из документа (ED-27), и проверка
 * `strings.test.ts` ищет их именно здесь. Подписи интерфейса сюда попасть не
 * могут — им место в бандле локали.
 */
import { jsonStrings } from '../../src/i18n/corpus.js';
import material from './material.json';

export const MATERIAL = material;

/** Корпус строк материала — по нему проверка ED-27 отличает значение от подписи. */
export function materialStrings(): ReadonlySet<string> {
  const strings = jsonStrings(material);
  // Имена полей документа — тоже его содержимое: инспектор показывает их как
  // есть и не локализует (ED-27). Значениями обхода они не являются, поэтому
  // добавлены явно.
  for (const name of Object.keys(material.systems.document.flags)) strings.add(name);
  return strings;
}
