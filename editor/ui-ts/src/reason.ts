/**
 * Причина отказа текстом — одна на весь пакет.
 *
 * Отказ авторинга структурен (ED-30): у него есть правило, место и полученное
 * значение, и интерфейс показывает их маркером и подсказкой (ED-22). Строка
 * нужна там, где показывать больше нечего — в баннере области, в состоянии
 * загрузки ассета, в записи о сорвавшемся кадре, — и это ровно одно
 * преобразование: `Error` отдаёт своё сообщение, всё остальное приводится к
 * строке.
 *
 * Отдельным модулем, а не копией в каждом файле: пятнадцать написаний одного
 * преобразования разошлись бы по одному месту за раз, и «причина» в двух
 * соседних баннерах перестала бы значить одно и то же.
 */
export function reasonOf(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}
