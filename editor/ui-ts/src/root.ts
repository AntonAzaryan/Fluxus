/**
 * Точка монтирования приложения редактора: единственное место, где интерфейс
 * встречается с документом среды. Идентификатор корня — константа, а не
 * литерал в разметке и коде по отдельности: `test/root.test.ts` пиннит, что
 * страница приложения содержит именно его.
 *
 * Каркас областей (ED-23) вырастет внутри этого элемента; сейчас монтируется
 * пустая поверхность — доменных имён редактируемого здесь нет и не появится
 * (ED-25: каркас не знает про «террейн» и «префаб»).
 */
export const EDITOR_ROOT_ID = 'editor-root';

/**
 * Готовит корневой элемент к монтированию: находит его в документе и очищает.
 * Возвращает элемент — владение поверхностью переходит к вызывающему.
 */
export function mountEditorRoot(doc: Document): HTMLElement {
  const root = doc.getElementById(EDITOR_ROOT_ID);
  if (root === null) {
    throw new Error(`editor-ui: в документе нет элемента #${EDITOR_ROOT_ID}`);
  }
  root.replaceChildren();
  return root;
}
