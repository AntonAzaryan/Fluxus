/**
 * @contribution Модуль ассетов редактора — один на всю сборку, и это решение, а
 * не экономия.
 *
 * ## Что здесь решено
 *
 * Кадров в редакторе два и будет больше: вьюпорт сцены и кадр просмотрщика
 * (ED-20) — разные рабочие области, каждая со своим холстом. Развилка стояла
 * так: один контекст рендера (`RenderContext` — сцена THREE, модуль ассетов,
 * конфиг), которым владеет каркас и раздаёт областям, — или контекст на область,
 * а общим делается только модуль ассетов. Выбрано второе, по трём причинам.
 *
 * 1. **ED-23.** Состояние области — поза камеры в первую очередь — обязано
 *    пережить уход в другую область и возврат. Контекст рендера состоянием не
 *    является только на вид: в нём висит `PresentationStage`, а её продюсеры
 *    взаимоисключающи (REND-11). Один контекст на двоих означал бы, что вход в
 *    соседнюю область отбирает presentation-состояние у первой и наполняет его
 *    своим набором, а возврат — собирает всё заново. Это ровно та потеря
 *    состояния, которую ED-23 запрещает; переживание переключения пришлось бы
 *    возвращать сохранением и восстановлением сцены — то есть той же парой
 *    контекстов, только выраженной снимками.
 * 2. **ED-25.** Каркас не содержит доменных имён редактируемого, и «сервис
 *    рендера» в каркасе — первое место, куда они протекают: у контекста есть
 *    сцена, у сцены подсистемы, у подсистем террейн и модели. Каркас, который
 *    держит контекст, начинает решать, что такое вьюпорт и у кого он бывает, —
 *    а область для документов без вьюпорта продолжала бы за него платить.
 * 3. Цена второго контекста мала и названа: второй `WebGLRenderer` и второй
 *    цикл кадров. Цикл невидимой области не рисует ничего — кадр начинается с
 *    поиска своего узла на странице, а узел есть только у активной области
 *    (`sceneStage.ts`, `attach`).
 *
 * ## Что при этом общее
 *
 * Модуль ассетов. Он общий не ради экономии, а по требованию: ASSET-2 говорит о
 * кэше на ID — «повторный запрос возвращает тот же handle и тот же разделяемый
 * ассет», — и два сервиса над одним деревом означали бы два ответа на вопрос
 * «что это за ассет и загрузился ли он». Просмотрщик показывает состояние
 * ассета автору (ED-20, ASSET-4), вьюпорт рисует им же загруженное; разойдись
 * они — просмотрщик показывал бы «загружен» рядом с пустым местом в кадре.
 *
 * Поэтому здесь заводится ровно один сервис на сборку, и загрузчики
 * регистрируются здесь же: набор форматов — свойство редактора, а не отдельного
 * кадра.
 */
import {
  AssetService,
  curvatureLoader,
  gltfLoader,
  manifestLoader,
  mdxLoader,
  pngTextureLoader,
} from '@game-mvp/assets';
import { createHostAssetSource, type EnvironmentHost } from '@game-mvp/editor-core';

/**
 * Модуль ассетов поверх дерева контента хоста среды (ED-12, ASSET-2): байты
 * приходят тем же швом, которым читаются документы, и ID ассета есть путь в
 * дереве.
 */
export function createAssetModule(host: EnvironmentHost): AssetService {
  const assets = new AssetService(createHostAssetSource(host.content));
  assets.registerLoader(mdxLoader);
  assets.registerLoader(gltfLoader);
  assets.registerLoader(pngTextureLoader);
  assets.registerLoader(manifestLoader);
  assets.registerLoader(curvatureLoader);
  return assets;
}
