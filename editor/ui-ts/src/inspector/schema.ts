/**
 * Что инспектор знает о редактируемом — и чего он о нём не знает (ED-24).
 *
 * ED-24: «Инспектор SHALL строиться из схемы редактируемого (ED-2, ED-6):
 * набор полей, их типы и допустимые значения берутся из реестра схем, а не из
 * захардкоженного в редакторе списка». Поэтому здесь нет ни одного имени поля,
 * ни одного имени группы и ни одной таблицы соответствий: есть только форма, в
 * которой вклад приносит прочитанное им из реестра схем.
 *
 * Три вещи, которые эта форма обязана нести, и почему именно они:
 *
 * - **тип поля** — ключ, по которому инспектор ищет редактор поля в реестре
 *   вкладов (ED-25: «новый тип поля в схемах → регистрируется редактор поля, и
 *   он подхватывается инспектором во всех областях сразу»). Строка, а не
 *   перечисление: перечисление означало бы, что новый тип правит каркас;
 * - **путь поля в схеме** — из него вычисляется ключ описания (ED-28). Ключ
 *   инспектор не получает и получить не может: ручной таблицы «поле → ключ» не
 *   существует, а вычисление живёт в одной функции слоя ресурсов
 *   (`descriptionKey`);
 * - **адрес места в документе** — им операция авторинга пишет правку (ED-29) и
 *   по нему же находится находка валидации (`report.at`, ED-8, ED-30).
 *
 * Записи отслеживаемых списков адресуются дескриптором, а не индексом: индекс
 * едет от удаления соседа, и инспектор, собранный по прочитанному списку,
 * записал бы правку не туда (ED-29).
 */
import type { DocumentId, JsonPath, JsonValue, SchemaPath } from '@fluxus/editor-core';
import type { UiText } from '../dom/node.js';

/**
 * Одно поле схемы. Значение поля здесь не лежит: оно читается из документа в
 * момент отрисовки, и второе его состояние рядом с сессией завелось бы ровно
 * для того, чтобы разойтись с первым.
 */
export interface SchemaField {
  /** Имя поля — идентификатор документа, локаль его не касается (ED-27). */
  readonly name: string;
  /** Тип поля из схемы: ключ редактора поля в реестре вкладов (ED-25). */
  readonly type: string;
  /** Путь к месту поля от корня субъекта. */
  readonly path: JsonPath;
  /** Путь поля в схеме — из него вычисляется ключ описания (ED-28). */
  readonly description: SchemaPath;
  /** Допустимые значения, если схема их перечисляет (ED-24). */
  readonly values?: readonly JsonValue[];
  /**
   * Поле правке не подлежит: производная величина, которую считает ядро, или
   * место, у которого своя операция. Показывается недоступным, а не молча не
   * принимающим ввод (ED-26).
   */
  readonly readOnly?: boolean;
}

/** Группа полей — раздел схемы. Имя группы принадлежит документу, а не интерфейсу. */
export interface FieldGroup {
  readonly name: string;
  readonly fields: readonly SchemaField[];
}

/**
 * Адрес субъекта в документах сессии. Или запись отслеживаемого списка
 * (`record`), или место по пути от корня (`root`) — третьего адреса у правки
 * нет, потому что их нет у слоя операций.
 */
export interface SubjectAddress {
  readonly documentId: DocumentId;
  /** Дескриптор записи списка (ED-29); задан — пути полей отсчитываются от записи. */
  readonly record?: string;
  /** Корень субъекта в документе; по умолчанию — сам документ. */
  readonly root?: JsonPath;
}

/** Что инспектор показывает: адрес, набор полей и подпись выбранного. */
export interface InspectorSubject {
  readonly address: SubjectAddress;
  readonly groups: readonly FieldGroup[];
  /**
   * Подпись субъекта — идентификатор редактируемого (имя записи, путь
   * документа), а не подпись интерфейса: локаль его не меняет (ED-27).
   */
  readonly title?: UiText;
}

/**
 * Операции, которыми инспектор пишет правку (ED-29). Имена — те же, под
 * которыми базовые операции зарегистрированы слоем операций; своего пути
 * записи у интерфейса нет и быть не может.
 *
 * Наличие операции в реестре инспектор проверяет перед показом: сборка, не
 * зарегистрировавшая её, получает поля недоступными (ED-26), а не молча
 * не срабатывающими.
 */
export const VALUE_OPERATION = 'document.setValue';

/** Та же правка внутри записи списка: адрес — дескриптор, путь — от записи. */
export const RECORD_VALUE_OPERATION = 'document.list.setValue';
