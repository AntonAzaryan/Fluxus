/**
 * Кирпичи таблицы стилей: тип правила, его роль и имена классов, вокруг
 * которых построена область действия токенов.
 *
 * Вынесены из `stylesheet.ts` не ради порядка, а ради владения. Каркас
 * рабочих областей (ED-23, ED-24) держит свои правила у себя — ширины зон и
 * поведение прокрутки суть свойства скелета, и жить им больше негде. Но
 * `stylesheet.ts` собирает каскад целиком, поэтому он импортирует правила
 * каркаса, а каркас — эти кирпичи. Если бы они лежали в `stylesheet.ts`, цикл
 * импортов замкнулся бы на константах, читаемых на верхнем уровне модуля, то
 * есть на временнóй мёртвой зоне.
 */

/** Класс области действия токенов. Всё, что красит хром, — потомок этого класса. */
export const TOKEN_SCOPE_CLASS = 'fx-tokens';

/** Класс корня приложения: область токенов плюс фон окна. */
export const APP_CLASS = 'fx-app';

/** Класс кадра вьюпорта — области, из которой палитра редактора вычтена. */
export const VIEWPORT_CLASS = 'fx-viewport';

/** Класс слоя служебных наложений внутри кадра. */
export const VIEWPORT_OVERLAY_CLASS = 'fx-viewport__overlay';

/** Префикс селектора хрома: каждое правило действует только внутри области токенов. */
export const SCOPE = `.${TOKEN_SCOPE_CLASS}`;

/**
 * Роль правила. `interactive` — то, что ED-22 отдал акценту; `validation` —
 * состояния данных (ED-8). Правило без роли — нейтральный хром: поверхности,
 * рамки, типографика, плотность.
 */
export type RuleRole = 'interactive' | 'validation';

export interface CssRule {
  readonly selector: string;
  readonly declarations: readonly string[];
  readonly role?: RuleRole;
}
