/**
 * Сведение просьб перерисовать в одну отрисовку.
 *
 * Отрисовка страницы тотальная (`mount.ts`), а оповещений об одной авторской
 * порции работы приходит несколько: пакет по мультивыделению — поворот или
 * удаление — это `beginOperation`, `extend` на каждую запись и `commit` в одном
 * синхронном вызове, и каждое из них сессия объявляет честно, потому что
 * состояние документов между ними действительно разное. Считать их одним
 * применением нельзя (`commit` записал бы в историю состояние, которого не
 * производит ни одна операция целиком, ED-18), и молчать сессии тоже нельзя —
 * её дело говорить правду о состоянии. Значит, сводить обязан тот, кто рисует.
 *
 * ED-15 требует показать правку «не позже следующего кадра» — это и есть тот
 * зазор, в котором сведение законно: N + 1 полных пересборок страницы на одно
 * нажатие автора не показывают ни одного состояния, кроме последнего, а стоят
 * как N + 1.
 *
 * Отсрочка по умолчанию — микрозадача, а не кадр анимации. Микрозадача
 * выполняется до отрисовки браузером, то есть «не позже следующего кадра»
 * держится буквально; кадр же анимации в фоновой вкладке не наступает вовсе, и
 * страница осталась бы несобранной там, где правка пришла без интерфейса
 * (ED-29). Отсрочка при этом ровно одна: пока просьба не исполнена, следующие
 * складываются в неё же.
 */

/** Чем откладывается сведённая отрисовка; подменяется тестом на явную очередь. */
export type RedrawSchedule = (draw: () => void) => void;

export interface CoalescingRedraw {
  /** Просьба перерисовать: сколько бы их ни пришло подряд, отрисовка будет одна. */
  request(): void;
  /** Ждёт ли отрисовка своей очереди. */
  readonly pending: boolean;
  /** Снять запланированное: страницы, которую перерисовывать, больше нет. */
  cancel(): void;
}

const microtask: RedrawSchedule = (draw) => {
  queueMicrotask(draw);
};

export function createCoalescingRedraw(
  draw: () => void,
  schedule: RedrawSchedule = microtask,
): CoalescingRedraw {
  let scheduled = false;
  let cancelled = false;
  return {
    request() {
      if (scheduled || cancelled) return;
      scheduled = true;
      schedule(() => {
        scheduled = false;
        // Снос страницы отменяет и запланированное: отрисовка после него
        // собирала бы дерево в узел, которого уже нет.
        if (!cancelled) draw();
      });
    },
    get pending(): boolean {
      return scheduled;
    },
    cancel() {
      cancelled = true;
    },
  };
}
