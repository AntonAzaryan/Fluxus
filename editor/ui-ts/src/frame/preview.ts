/**
 * Режим правки против режима превью — то, что каркас знает о прогоне (ED-9,
 * ED-26), не зная, ЧТО прогоняется.
 *
 * ED-26 требует трёх вещей сразу, и все три — про каркас, а не про вклад:
 * запуск и выход доступны из ЛЮБОЙ рабочей области и не требуют сохранения на
 * диск; текущий режим виден постоянно; недоступное в превью показано
 * недоступным. Первое и второе выполнимы только там, где живёт верхний бар и
 * переключение областей, — то есть здесь. Держать режим в записи состояния
 * области значило бы, что из соседней области его не видно и не переключить,
 * а это ровно то, что требование запрещает.
 *
 * Чего каркас при этом не знает — что именно прогоняется. Собрать прогон умеет
 * тот вклад, чьи документы прогоняются: у него и настройки проекта, и кадр, в
 * который прогон публикуется. Каркас же видит две операции («готов ли» и
 * «запусти») и одну у идущего прогона («закончи»), и доменного ветвления в нём
 * от этого не заводится (ED-25).
 *
 * Почему прогон отдаётся объектом, а не парой «старт/стоп» на источнике: закончить
 * обязан ровно тот прогон, который был начат. Источник, у которого спрашивают
 * «останови», вынужден помнить, что он начал, — и это второе место, где хранится
 * то же самое.
 */

/** Режим, в котором находится редактор. Третьего не бывает: превью или правка. */
export type EditorMode = 'edit' | 'preview';

/** Идущий прогон: каркасу от него нужно ровно одно — уметь его закончить. */
export interface PreviewRun {
  /**
   * Заканчивает прогон и возвращает вьюпорт документам без потери
   * несохранённых правок (ED-9). Зовётся один раз.
   */
  stop(): void;
}

/**
 * Кто умеет прогнать текущее состояние документов (ED-9). Реализуется вкладом
 * (ED-25); каркас перебирает вклады и берёт первый готовый.
 */
export interface PreviewSource {
  /**
   * Есть ли сейчас что прогонять. `false` — элемент запуска показывается
   * недоступным, а не молча не срабатывает (ED-26).
   */
  ready(): boolean;
  /**
   * Прогон текущего состояния документов, включая несохранённые правки:
   * сохранения на диск ED-26 не требует. Отказ выражается исключением с
   * причиной — её каркас и показывает.
   */
  start(): PreviewRun;
}
