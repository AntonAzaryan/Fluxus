/**
 * Что каркас знает о рабочей области — и чего он о ней не знает.
 *
 * Вклад области (`WorkspaceAreaContribution` из `@game-mvp/editor-core`)
 * описывает область для машинного каталога (ED-30); здесь к нему добавляется
 * ровно то, что нужно интерфейсу: чем область показана в рельсе и что она
 * кладёт в три зоны скелета (ED-24). Больше каркас не спрашивает: доменное
 * знание живёт во вкладе (ED-25).
 *
 * ## Где живёт состояние области
 *
 * ED-23 требует, чтобы поза камеры, выделение, прокрутка и раскрытие узлов
 * переживали уход в другую область и возврат. Состояние заводит область
 * (`createState`), а хранит его каркас — по записи на область на всё время
 * своей жизни (`state.ts`). Не наоборот, и вот почему:
 *
 * - если бы состояние жило полем самого вклада, вклад стал бы одиночкой:
 *   зарегистрировать его во второй сессии или в тесте рядом с первой было бы
 *   нельзя, а «переживает переключение» держалось бы на том, что модуль вклада
 *   не выгрузили, — то есть ни на чём;
 * - каркас, владеющий записью, гарантирует именно живучесть: запись создаётся
 *   один раз и отдаётся той же области при каждом возврате. Смысла записи он
 *   при этом не знает — тип `AreaState` пуст, и ни одна ветка каркаса в него
 *   не заглядывает. Живучесть — от каркаса, смысл — от вклада.
 *
 * Выделение в этот список не входит, хотя ED-23 называет его среди состояния
 * области: оно там же названо сквозным для всех областей, и потому живёт
 * отдельной моделью (`selection.ts`), общей на сессию. Каркас знает форму
 * ссылки на выделенное (непрозрачная строка), но не знает, что ею адресовано.
 */
import type {
  EditorSession,
  StringResources,
  WorkspaceAreaContribution,
} from '@game-mvp/editor-core';
import type { UiNode } from '../dom/node.js';
import type { IconName } from '../widgets/icon.js';
import type { AreaSelection } from './selection.js';

/**
 * Запись состояния области. Пустой тип — не заглушка: каркас обязан уметь
 * хранить запись, не имея права её прочесть, и «объект, о котором ничего не
 * известно» — ровно это в системе типов.
 */
export type AreaState = object;

/** Три зоны скелета (ED-24). Их порядок и положение задаёт каркас, а не область. */
export interface AreaZones {
  /** Навигатор редактируемого. */
  readonly navigator: UiNode;
  /** Поверхность правки. */
  readonly surface: UiNode;
  /** Инспектор выбранного. */
  readonly inspector: UiNode;
}

/**
 * Что область получает при заведении своей записи состояния.
 *
 * Заведение — одно на каркас, а каркас — на окно (ED-23: области переключаются
 * в одном окне). Сессия при этом может быть общей у двух каркасов — в тесте
 * рядом друг с другом, — и тогда `createState` зовётся дважды над одной
 * сессией. Поэтому открытие документа здесь обязано быть идемпотентным:
 * область спрашивает `isOpen` прежде, чем открывать.
 */
export interface AreaSetup {
  /**
   * Сессия: одна история операций на всех (ED-23, ED-18). Область открывает
   * здесь то, что собирается править, и правит только операциями (ED-29).
   */
  readonly session: EditorSession;
}

/** Что область получает на каждую отрисовку. */
export interface AreaContext<S extends AreaState = AreaState> {
  readonly resources: StringResources;
  /** Та самая запись, что была отдана в прошлый раз, — она переживает переключение (ED-23). */
  readonly state: S;
  /** Сквозное выделение, суженное до этой области (ED-23). */
  readonly selection: AreaSelection;
  readonly session: EditorSession;
  /** Просьба перерисовать: область изменила своё состояние и хочет это показать. */
  refresh(): void;
}

/**
 * Рабочая область как вклад интерфейса (ED-25). Методы объявлены методами, а
 * не полями-функциями, сознательно: так `WorkspaceArea<СвоёСостояние>`
 * подставляется в реестр `ContributionRegistry<WorkspaceArea>` без приведения
 * типов у каждого вклада.
 */
export interface WorkspaceArea<S extends AreaState = AreaState>
  extends WorkspaceAreaContribution {
  /** Знак области в рельсе. */
  readonly icon: IconName;
  /** Ключ ресурса подписи (ED-27): текста в коде вклада нет. */
  readonly labelKey: string;
  /** Заводит запись состояния области. Зовётся один раз — при первом заходе в неё. */
  createState(setup: AreaSetup): S;
  /** Содержимое трёх зон. Зовётся на каждую отрисовку активной области. */
  render(context: AreaContext<S>): AreaZones;
}
