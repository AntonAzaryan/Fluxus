/**
 * Что каркас знает о рабочей области — и чего он о ней не знает.
 *
 * Вклад области (`WorkspaceAreaContribution` из `@game-mvp/editor-core`)
 * описывает область для машинного каталога (ED-30); здесь к нему добавляется
 * ровно то, что нужно интерфейсу: чем область показана в рельсе и что она
 * кладёт в три зоны скелета (ED-24). Больше каркас не спрашивает: доменное
 * знание живёт во вкладе (ED-25).
 *
 * ## Где живёт состояние области
 *
 * ED-23 требует, чтобы поза камеры, выделение, прокрутка и раскрытие узлов
 * переживали уход в другую область и возврат. Состояние заводит область
 * (`createState`), а хранит его каркас — по записи на область на всё время
 * своей жизни (`state.ts`). Не наоборот, и вот почему:
 *
 * - если бы состояние жило полем самого вклада, вклад стал бы одиночкой:
 *   зарегистрировать его во второй сессии или в тесте рядом с первой было бы
 *   нельзя, а «переживает переключение» держалось бы на том, что модуль вклада
 *   не выгрузили, — то есть ни на чём;
 * - каркас, владеющий записью, гарантирует именно живучесть: запись создаётся
 *   один раз и отдаётся той же области при каждом возврате. Смысла записи он
 *   при этом не знает — тип `AreaState` пуст, и ни одна ветка каркаса в него
 *   не заглядывает. Живучесть — от каркаса, смысл — от вклада.
 *
 * Выделение в этот список не входит, хотя ED-23 называет его среди состояния
 * области: оно там же названо сквозным для всех областей, и потому живёт
 * отдельной моделью (`selection.ts`), общей на сессию. Каркас знает форму
 * ссылки на выделенное (непрозрачная строка), но не знает, что ею адресовано.
 */
import type {
  ContributionReader,
  EditorSession,
  StringResources,
  WorkspaceAreaContribution,
} from '@game-mvp/editor-core';
import type { UiNode } from '../dom/node.js';
import type { FieldEditor } from '../inspector/editors.js';
import type { SearchHit } from '../palette/palette.js';
import type { IconName } from '../widgets/icon.js';
import type { EditorMode, PreviewSource } from './preview.js';
import type { AreaSelection } from './selection.js';

/**
 * Запись состояния области. Пустой тип — не заглушка: каркас обязан уметь
 * хранить запись, не имея права её прочесть, и «объект, о котором ничего не
 * известно» — ровно это в системе типов.
 */
export type AreaState = object;

/** Три зоны скелета (ED-24). Их порядок и положение задаёт каркас, а не область. */
export interface AreaZones {
  /** Навигатор редактируемого. */
  readonly navigator: UiNode;
  /** Поверхность правки. */
  readonly surface: UiNode;
  /** Инспектор выбранного. */
  readonly inspector: UiNode;
}

/**
 * Что область получает при заведении своей записи состояния.
 *
 * Заведение — одно на каркас, а каркас — на окно (ED-23: области переключаются
 * в одном окне). Сессия при этом может быть общей у двух каркасов — в тесте
 * рядом друг с другом, — и тогда `createState` зовётся дважды над одной
 * сессией. Поэтому открытие документа здесь обязано быть идемпотентным:
 * область спрашивает `isOpen` прежде, чем открывать.
 */
export interface AreaSetup {
  /**
   * Сессия: одна история операций на всех (ED-23, ED-18). Область открывает
   * здесь то, что собирается править, и правит только операциями (ED-29).
   */
  readonly session: EditorSession;
}

/** Что область получает на каждую отрисовку. */
export interface AreaContext<S extends AreaState = AreaState> {
  readonly resources: StringResources;
  /** Та самая запись, что была отдана в прошлый раз, — она переживает переключение (ED-23). */
  readonly state: S;
  /** Сквозное выделение, суженное до этой области (ED-23). */
  readonly selection: AreaSelection;
  readonly session: EditorSession;
  /**
   * Режим редактора (ED-26). Приходит на отрисовку, а не спрашивается у
   * каркаса: область обязана показать недоступным всё, что в превью применить
   * нельзя (ED-9), и решение об этом принимается там же, где строится элемент.
   */
  readonly mode: EditorMode;
  /**
   * Реестр редакторов поля (ED-25) — один на редактор, а не свой у каждой
   * области: «редактор поля подхватывается инспектором во всех областях сразу»
   * держится ровно на том, что реестр области не принадлежит. Она берёт его
   * отсюда и отдаёт инспектору вместе со своей схемой (ED-24).
   */
  readonly fieldEditors: ContributionReader<FieldEditor>;
  /** Просьба перерисовать: область изменила своё состояние и хочет это показать. */
  refresh(): void;
}

/**
 * Что область получает на запрос поиска. Отдельно от `AreaContext`, потому что
 * поиск — не отрисовка: ни режима, ни реестра редакторов поля, ни просьбы
 * перерисовать здесь нет — метод обязан быть дешёвым и без побочных действий.
 */
export interface AreaSearch<S extends AreaState = AreaState> {
  readonly query: string;
  readonly state: S;
  /** Сквозное выделение (ED-23): им находка себя и открывает. */
  readonly selection: AreaSelection;
  readonly session: EditorSession;
}

/**
 * Одна клавиша раскладки области (ED-32). Раскладка — данные вклада, и она же
 * единственный источник для подсказок (ED-31): перечень клавиш в интерфейсе и
 * перечень клавиш, которые работают, — один и тот же перечень.
 *
 * Клавиша названа кодом (`KeyboardEvent.code`), а не символом: раскладка не
 * зависит ни от языка ввода, ни от локали интерфейса. Имя действия приходит
 * ключом ресурса (ED-27) — доменных имён каркас по-прежнему не получает.
 */
export interface AreaKey {
  readonly code: string;
  readonly labelKey: string;
}

/** Фаза нажатия. `blur` — окно потеряло фокус: всё зажатое считается отпущенным. */
export type AreaKeyPhase = 'down' | 'up' | 'blur';

/**
 * Нажатие, дошедшее до активной области (ED-32). Дошедшее означает, что
 * сквозные сочетания каркаса его не забрали, что фокус не в текстовом поле и
 * что виджет под фокусом его не потребил.
 */
export interface AreaKeyInput<S extends AreaState = AreaState> {
  readonly state: S;
  /** `KeyboardEvent.code` — тот же вид, в котором объявлена раскладка. */
  readonly code: string;
  readonly phase: AreaKeyPhase;
  /** Автоповтор удержания: фронты (переключатели) на него не срабатывают. */
  readonly repeat: boolean;
  /**
   * Режим редактора (ED-26) — по тому же основанию, по которому он приходит на
   * отрисовку: клавиша обязана быть недоступна там же, где недоступна кнопка,
   * иначе «недоступно» было бы только надписью (ED-9).
   */
  readonly mode: EditorMode;
}

/**
 * Рабочая область как вклад интерфейса (ED-25). Методы объявлены методами, а
 * не полями-функциями, сознательно: так `WorkspaceArea<СвоёСостояние>`
 * подставляется в реестр `ContributionRegistry<WorkspaceArea>` без приведения
 * типов у каждого вклада.
 */
export interface WorkspaceArea<S extends AreaState = AreaState>
  extends WorkspaceAreaContribution {
  /**
   * Раскладка клавиш области (ED-32) — объявление, а не второй перечень: тем
   * же массивом область собирает подсказки своих элементов (ED-31). Нет поля —
   * своих клавиш у области нет.
   */
  readonly keys?: readonly AreaKey[];
  /**
   * Клавиша области. `true` — область нажатие забрала, и среде оно не
   * достаётся. Зовётся только на те нажатия, которые прошли порядок ED-32
   * целиком; своего порядка разбора область не заводит.
   */
  handleKey?(input: AreaKeyInput<S>): boolean;
  /** Знак области в рельсе. */
  readonly icon: IconName;
  /** Ключ ресурса подписи (ED-27): текста в коде вклада нет. */
  readonly labelKey: string;
  /** Заводит запись состояния области. Зовётся один раз — при первом заходе в неё. */
  createState(setup: AreaSetup): S;
  /**
   * Чем эта область умеет прогонять свои документы (ED-9); нет метода —
   * прогонять ей нечего. Функция от записи состояния, а не поле вклада: в
   * записи живут открытые документы и кадр, а вклад — один на приложение, и
   * складывать в него состояние значило бы делать его одиночкой (см. шапку).
   *
   * Каркас зовёт метод, чтобы узнать, доступен ли запуск (ED-26), поэтому он
   * обязан быть дешёвым и без побочных действий: сам прогон начинает `start`.
   */
  preview?(state: S): PreviewSource;
  /**
   * Что область находит по запросу поиска (ED-24: «поиск вместо дерева»). Нет
   * метода — области нечего искать.
   *
   * Находки приносит область, а не каркас, по той же причине, по которой она
   * приносит содержимое зон: каркас не знает, что за материал она правит, и
   * «открыть найденное напрямую» умеет только она сама (ED-25). Переключение на
   * область при этом делает каркас — поиск сквозной (ED-23), и находка соседней
   * области обязана открываться так же, как своя.
   *
   * Метод зовут на каждый набранный автором символ.
   */
  search?(input: AreaSearch<S>): readonly SearchHit[];
  /** Содержимое трёх зон. Зовётся на каждую отрисовку активной области. */
  render(context: AreaContext<S>): AreaZones;
}
