/**
 * @contribution Привязка позиции и поворота сим-объекта (ED-16) — настройка
 * проекта, а не знание каркаса: доменные имена здесь и должны быть (ED-25).
 *
 * Формат расстановки именованных полей позиции не имеет вовсе (SER-8): позиция и
 * курс записываются переопределением полей компонентов, а какие это компонент и
 * поля — говорит проект. ED-16: «Какие компонент и поля их несут, редактор SHALL
 * брать из настройки проекта, а не из зашитого в редактор имени компонента».
 *
 * Форма живёт здесь, а не у одного из потребителей, потому что потребителей
 * ДВА и оба правят один и тот же слой: инструменты расстановки редактора
 * (`editor/ui-ts`) и импортёр конвейера Blender (`tools/blender-ts`,
 * `blender-pipeline` BLND-3, BLND-5). Пока копий было две, любая правка состава
 * обязана была идти в обе — то есть держалась дисциплиной автора; теперь
 * объявление одно, и разойтись ему не с чем. Пакет интерфейса для общего места
 * не годится: он DOM-ный, а импортёр headless.
 *
 * Умолчание берётся у ядра (`POSITION_COMPONENT`) и только у него: это его
 * собственная конвенция, на которую опираются его же нативные системы, и
 * повторить её строкой значило бы завести вторую (ED-1, CORE-3).
 */
import { POSITION_COMPONENT } from '@game-mvp/core';

/**
 * Где у сим-объекта лежит поворот (ED-16): компонент и имя одного его поля.
 *
 * Конвенции поворота у ядра нет вовсе — ни компонента, ни поля, — поэтому и
 * умолчания у этой половины привязки нет: проект, не назвавший поворот, поворота
 * не хранит. Это честнее выдуманного имени компонента.
 */
export interface RotationBinding {
  readonly component: string;
  readonly field: string;
}

/** Где у сим-объекта лежат позиция и поворот (ED-16). */
export interface PositionBinding {
  readonly component: string;
  readonly x: string;
  readonly y: string;
  /** Где лежит поворот; нет — сцена поворота не хранит, и курс не пишется. */
  readonly rotation?: RotationBinding;
}

/**
 * Привязка по умолчанию — конвенция самого ядра. Проект вправе подать другую:
 * правится настройка, а не редактор и не импортёр.
 */
export const DEFAULT_POSITION_BINDING: PositionBinding = Object.freeze({
  component: POSITION_COMPONENT,
  x: 'x',
  y: 'y',
});
