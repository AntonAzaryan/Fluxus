/**
 * Шов к строковым ресурсам (ED-28). Сами ресурсы, цепочка разрешения «текущая
 * локаль → `en` → сам ключ» и вывод ключа из пути схемы — работа слоя локалей
 * (`../i18n/`); здесь только то, чем каталог (ED-30) их спрашивает.
 *
 * Каталогу подставляется резолвер бандла `en`: описание для машинного
 * потребителя и описание, которое видит человек на английской локали, — один и
 * тот же текст. Второго набора формулировок «для машины» ED-30 не допускает,
 * поэтому ни одной английской строки в реестрах и каталоге нет и быть не должно.
 *
 * Ключи каталог не вычисляет: их приносит сам вклад (`Contribution.descriptionKey`)
 * и сам слой операций (`AuthoringOperation.descriptionKey`). Второй точки
 * вывода ключа в пакете быть не должно — она разошлась бы с первой (ED-28).
 *
 * Готовую реализацию поверх бандлов даёт слой локалей — `catalogDescriptions`.
 * Интерфейс здесь, а не там, потому что спрашивает каталог: слой ресурсов ни о
 * ком не знает, и знать о каталоге ему незачем.
 */
export interface DescriptionResolver {
  /**
   * Описание по ключу. Возвращает всегда строку: отсутствие ресурса —
   * состояние, которое надо видеть, поэтому вместо пустой строки резолвер
   * отдаёт сам ключ (ED-28). Для машинного потребителя это тем более так:
   * по пустому описанию он не отличит недокументированное от пустого.
   */
  describe(key: string): string;
}
