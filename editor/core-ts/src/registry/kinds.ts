/**
 * Пять видов вклада, перечисленных ED-25: рабочая область, инструмент вьюпорта,
 * редактор поля инспектора, команда палитры и правило валидации.
 *
 * Здесь — только описательная часть вклада: то, что каркасу нужно знать о нём,
 * ничего про него не понимая. Доменное знание живёт в самом вкладе и приходит
 * сюда данными (строкой id, ссылкой на схему), а не ветвлением в каркасе.
 *
 * Поведения у этих интерфейсов нет намеренно. Слой, который вклад исполняет,
 * расширяет нужный интерфейс своим типом и подставляет его параметром реестра:
 * `ContributionRegistry<MyArea>` там, где `MyArea extends
 * WorkspaceAreaContribution`. Так headless-ядро (ED-29) не начинает держать
 * типы интерфейса, а слой интерфейса не заводит второй реестр рядом с этим.
 */
import type { Contribution } from './contribution.js';

/**
 * Тип редактируемого материала, который вносит рабочая область (ED-30 требует
 * их набор в каталоге). Отдельного шестого реестра под них нет: ED-25
 * перечисляет пять видов вклада, а тип редактируемого не добавляется сам по
 * себе — он приходит вместе с областью, которая умеет его править.
 */
export interface EditableTypeDescriptor {
  /** Совпадает с `DocumentKind` открытого документа — видом, который несёт вклад. */
  readonly id: string;
  /** Ключ описания (ED-28) — по тем же основаниям, что и у вклада. */
  readonly descriptionKey: string;
  /**
   * Схема редактируемого в реестре схем: из неё инспектор строит набор полей
   * (ED-24), из неё же вычисляются ключи описаний (ED-28). `undefined` —
   * материал, у которого схемы нет.
   */
  readonly schemaId?: string;
}

/** Рабочая область (ED-23, ED-24): вертикальный рельс — представление реестра. */
export interface WorkspaceAreaContribution extends Contribution {
  /** Горячая клавиша переключения (ED-23). Занимается единолично. */
  readonly hotkey?: string;
  readonly editableTypes: readonly EditableTypeDescriptor[];
}

/** Инструмент вьюпорта (ED-17, ED-26): доступен в перечисленных областях. */
export interface ViewportToolContribution extends Contribution {
  /** id областей, в которых инструмент показан. */
  readonly areas: readonly string[];
  /** id операций авторинга, которыми инструмент пишет в документ (ED-29). */
  readonly operations?: readonly string[];
  /**
   * Доступность в превью (ED-26). По умолчанию `false`: инструмент правит
   * документ, а правка во время превью недоступна и обязана быть видимо
   * недоступной, а не молча не срабатывать.
   */
  readonly availableInPreview?: boolean;
}

/**
 * Редактор поля инспектора (ED-25: «новый тип поля в схемах» → регистрируется
 * редактор поля, и его подхватывают все области сразу).
 */
export interface FieldEditorContribution extends Contribution {
  /** Тип поля схемы, который вклад берёт на себя. Занимается единолично. */
  readonly fieldType: string;
}

/** Команда палитры (ED-24): способ добраться до чего угодно мимо дерева. */
export interface PaletteCommandContribution extends Contribution {
  /** Сочетание клавиш. Занимается единолично. */
  readonly keybinding?: string;
  /** id областей, где команда доступна; `undefined` — доступна везде. */
  readonly areas?: readonly string[];
  /**
   * id операции авторинга, которую команда выполняет (ED-29). Команда, правящая
   * документ мимо операции, выпадает из истории — связь объявлена здесь, чтобы
   * это было видно в реестре, а не только в реализации команды.
   */
  readonly operation?: string;
}

/**
 * Правило валидации (ED-8). Структура результата проверки и сама проверка — за
 * слоем валидации; реестру достаточно знать, к каким типам редактируемого
 * правило применимо, чтобы каталог (ED-30) мог это показать.
 */
export interface ValidationRuleContribution extends Contribution {
  /** id типов редактируемого, к которым правило применяется. */
  readonly appliesTo: readonly string[];
}
