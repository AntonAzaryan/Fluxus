/**
 * Интерфейс хоста среды (ED-12). Один интерфейс, три группы: дерево контента,
 * выбор файлов и каталогов, оконная интеграция — ровно то, чем ED-12 перечисляет
 * различия веба и десктопа. Всё остальное в редакторе о среде не знает.
 *
 * Почему форма именно такая:
 *
 * - **Байты, а не строки.** `read`/`write` работают с байтами по той же причине,
 *   по которой на байтах работает `Serializer` ядра (SER-2): текст — частный
 *   случай, и появление бинарного документа не должно менять подпись шва.
 *   Заодно `read` совпадает по форме с `AssetSource` (ASSET-2), поэтому модуль
 *   ассетов и редактор читают одно дерево через один шов, а не через два.
 * - **Флагов возможностей здесь нет.** Соблазн завести `capabilities` и ветвить
 *   поведение — это и есть зависимость кода редактора от среды, которую ED-12
 *   называет дефектом. Хост, который не умеет наблюдать за деревом, возвращает
 *   из `watch` отписку и не уведомляет никогда; хост без диалога выбора отвечает
 *   `undefined`. Вызывающий в обоих случаях пишется один раз.
 * - **Перечисление каталога — часть шва.** Просмотрщик ассетов (ED-20) обязан
 *   ходить по дереву, и до этого интерфейса такой возможности в репозитории не
 *   существовало ни у одного слоя: `AssetSource` умеет только прочитать
 *   известный ID.
 * - **Удаления файла в шве нет.** Ни одно требование ED его не просит: создание
 *   документа — это `write`, а переименование префаба и переезд декорации в prop
 *   (ED-19) — правки внутри документов, а не операции над файлами. Разрушающая
 *   операция, которую обязана реализовать каждая среда, без требования не
 *   заводится.
 */
import type { ContentPath } from './paths.js';

/** Что лежит по пути: файл или каталог. */
export type ContentEntryKind = 'file' | 'directory';

export interface ContentEntry {
  /** Путь от корня дерева контента — он же ID ассета для файлов (ASSET-2). */
  readonly path: ContentPath;
  /** Последний сегмент пути; интерфейсу он нужен без повторного разбора. */
  readonly name: string;
  readonly kind: ContentEntryKind;
}

export type ContentChangeKind = 'created' | 'modified' | 'removed';

/** Изменение в дереве. Хост сообщает и о чужих правках, и о собственных `write`. */
export interface ContentChange {
  readonly path: ContentPath;
  readonly kind: ContentChangeKind;
}

export type ContentWatcher = (change: ContentChange) => void;

/**
 * Чтение, запись, перечисление и наблюдение — дерево контента целиком.
 * Реализация на среду одна; ничего, кроме дерева, через неё не проходит
 * (CONT-1: контент живёт одним корневым деревом вне пакетов).
 */
export interface ContentTreeHost {
  /** Байты файла. Отсутствие файла — брошенная ошибка, называющая путь. */
  read(path: ContentPath): Promise<ArrayBuffer>;
  /** Запись файла; недостающие каталоги создаёт среда. Наблюдатели уведомляются. */
  write(path: ContentPath, bytes: Uint8Array): Promise<void>;
  /** Что лежит по пути; `undefined` — ничего. */
  stat(path: ContentPath): Promise<ContentEntry | undefined>;
  /**
   * Содержимое каталога, ровно на один уровень. Порядок нормирован —
   * лексикографический по имени (`compareContentNames`), одинаковый во всех
   * средах: см. основание в `paths.ts`. Рекурсивный обход строится поверх
   * (`walkContentTree`) и в шов не входит — он одинаков в обеих средах, а
   * значит, средой не различается.
   */
  list(path: ContentPath): Promise<readonly ContentEntry[]>;
  /**
   * Подписка на изменения дерева (ED-12: «реакция на его изменение извне»).
   * Хост, у которого наблюдения нет, отдаёт отписку и молчит: корректность
   * редактора от уведомления зависеть не должна — только свежесть картинки.
   */
  watch(listener: ContentWatcher): () => void;
}

/**
 * Корень открытого проекта. Наружу выходит только показываемое имя: в вебе
 * пути файловой системы не существует, и вынести его в общий тип значило бы
 * описать шов по одной из двух сред.
 */
export interface ContentRootInfo {
  readonly label: string;
}

/** Запрос к диалогу выбора. Всё в нём — подсказка среде, а не проверка. */
export interface ChoiceRequest {
  /** Каталог, с которого открывается диалог. */
  readonly startIn?: ContentPath;
  /** Расширения с точкой: `['.mdx']`. */
  readonly extensions?: readonly string[];
  /** Ключ строкового ресурса заголовка: текста интерфейса вне ресурсов не бывает (ED-27). */
  readonly titleKey?: string;
}

/**
 * Выбор файлов и каталогов средствами среды. Отказ пользователя и отсутствие
 * диалога у среды выражаются одинаково — `undefined`; вызывающему различать их
 * незачем, а различение было бы ветвлением по среде.
 *
 * Выбор ассета для записи манифеста делается не отсюда, а просмотрщиком (ED-20:
 * ручной ввод пути MUST NOT быть обязательным) — эти методы нужны открытию
 * проекта и импорту файла извне дерева.
 */
export interface ContentPicker {
  /** Просит среду выбрать корень дерева контента. */
  chooseRoot(): Promise<ContentRootInfo | undefined>;
  /** Выбор файла внутри дерева; результат — путь от корня. */
  chooseFile(request?: ChoiceRequest): Promise<ContentPath | undefined>;
  /** Выбор каталога внутри дерева. */
  chooseDirectory(request?: ChoiceRequest): Promise<ContentPath | undefined>;
}

/** Ответ редактора на запрос закрытия: `true` — закрывать безопасно. */
export type CloseRequestHandler = () => boolean;

/**
 * Оконная интеграция. Сознательно узкая: заголовок, признак несохранённого и
 * запрос на закрытие — то, что среда обязана показать снаружи окна. Всё, что
 * рисуется внутри окна, средой не различается и в шов не входит.
 */
export interface WindowHost {
  setTitle(title: string): void;
  /** Есть ли несохранённые правки (ED-21): вкладка вешает `beforeunload`, десктоп — метку и вопрос. */
  setUnsaved(unsaved: boolean): void;
  /** Среда спрашивает, редактор отвечает. Синхронно: у вкладки браузера асинхронного ответа нет. */
  onCloseRequest(handler: CloseRequestHandler): () => void;
}

/**
 * Хост среды целиком. Реализаций две — веб (`@game-mvp/editor-ui`) и десктоп;
 * третья, `createMemoryHost`, служит тестовым дублем и подложкой несохранённого.
 */
export interface EnvironmentHost {
  /**
   * Имя реализации — для диагностики и сообщений об ошибке. Ветвление по нему —
   * ровно тот дефект, который ED-12 описывает сценарием «обращение к файловой
   * системе в обход хоста»: код, знающий, где он исполняется, перестаёт быть
   * проверяемым на паритет.
   */
  readonly name: string;
  /** Открытый корень; `undefined` — проект не открыт. */
  readonly root: ContentRootInfo | undefined;
  readonly content: ContentTreeHost;
  readonly picker: ContentPicker;
  readonly window: WindowHost;
}
