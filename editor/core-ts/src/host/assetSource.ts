/**
 * Переходник «хост среды → источник байтов ассетов». Модуль ассетов оставляет
 * ровно один шов ввода-вывода — `AssetSource.read(id)` (ASSET-2), реализации в
 * пакете нет, и до сих пор её писал каждый потребитель сам (демо клиента —
 * поверх `fetch`, тесты — поверх файловой системы). Редактор своей писать не
 * может: файловой системы у него нет по ED-12. Поэтому источником служит тот же
 * хост, через который редактор читает документы, — дерево одно (CONT-2), и шов
 * к нему тоже один.
 *
 * Тип источника объявлен здесь структурно, а не импортирован из
 * `@fluxus/assets`: `AssetSource` — интерфейс из одного метода, и зависимость
 * headless-каркаса редактора от пакета ассетов ради него была бы платой за
 * ничто. Совместимость держится подписью, а не импортом; расхождение поймает
 * компилятор в первом же месте, где источник передают в `new AssetService(...)`.
 *
 * ## Инвалидация кэша: решение и его основание
 *
 * `AssetService` кэширует по ID и не имеет ни вытеснения, ни инвалидации
 * (ASSET-2 требует, чтобы повторный запрос отдавал тот же разделяемый ассет, —
 * и сервис это выполняет буквально). Для редактора это значит: текстура,
 * которую автор поправил в дереве, сама собой не перезагрузится.
 *
 * Решение — **выбрасывать сервис целиком, а не изобретать вытеснение**:
 *
 * - Точечное `evict(id)` — это новая нормативная поверхность capability
 *   `assets`. Дописать её в редакторе значило бы реализовать в редакторе
 *   правило, чей источник — движок (ED-1, CORE-3): «когда закэшированный ассет
 *   считается устаревшим» — вопрос модуля ассетов, а не инструмента.
 * - Пересоздание сервиса даёт наблюдаемо верный результат без нового правила:
 *   новый кэш пуст, и следующий запрос читает свежие байты через тот же
 *   источник. Плата — перезагрузка ассетов, которые не менялись, и платится она
 *   ровно тогда, когда автор правил дерево, а не каждый кадр.
 * - Presentation-ассет на симуляцию не влияет (ASSET-1), поэтому ни сброс кэша,
 *   ни его отсутствие не могут разойтись с `TickResult`: цена вопроса —
 *   исключительно свежесть картинки.
 *
 * Отсюда форма: источник сам ничего не выбрасывает (кэша у него нет), но
 * называет момент, когда сброс нужен, — `generation` и `onStale`. Кто держит
 * `AssetService`, тот и пересоздаёт его; в headless-каркасе `AssetService` не
 * создаётся вовсе.
 */
import { normalizeContentPath } from './paths.js';
import type { ContentPath } from './paths.js';
import type { ContentTreeHost } from './types.js';

/**
 * Структурный аналог `AssetSource` пакета `@fluxus/assets` (ASSET-2): ID
 * ассета — путь в дереве контента, и другого ввода-вывода у модуля нет.
 */
export interface ContentAssetSource {
  read(id: string): Promise<ArrayBuffer>;
}

export type StaleListener = (path: ContentPath) => void;

export interface HostAssetSource extends ContentAssetSource {
  /**
   * Номер поколения дерева: растёт на каждом изменении, которое увидел хост, —
   * и на чужой правке файла, и на записи самого редактора. Держатель
   * `AssetService` сравнивает его со своим и пересоздаёт сервис при расхождении.
   */
  readonly generation: number;
  /** Путь, чьи байты изменились. Уведомление — подсказка о свежести, а не условие корректности. */
  onStale(listener: StaleListener): () => void;
  /** Отписывает источник от хоста. */
  dispose(): void;
}

export function createHostAssetSource(host: ContentTreeHost): HostAssetSource {
  const listeners = new Set<StaleListener>();
  let generation = 0;

  const stop = host.watch((change) => {
    generation += 1;
    for (const listener of [...listeners]) listener(change.path);
  });

  return {
    read: (id) => host.read(normalizeContentPath(id)),
    get generation() {
      return generation;
    },
    onStale(listener) {
      listeners.add(listener);
      return () => {
        listeners.delete(listener);
      };
    },
    dispose: stop,
  };
}
