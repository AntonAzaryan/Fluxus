/**
 * Правила-вклады, которые слой валидации везёт с собой: вызовы валидаторов
 * движка (`engineRules.ts`) и междокументные правила (`crossDocument.ts`).
 *
 * Набор существует по той же причине, по которой у обоих модулей есть виды
 * документов по умолчанию: обычная сборка редактора должна быть одной строкой,
 * а проект с другой раскладкой зовёт те же две фабрики со своими адресами
 * (ED-25 — раскладку знает собирающий редактор, а не правило).
 *
 * Второе применение важнее первого: по этому же набору считаются ключи строк
 * причин (ED-28, `validationDescriptionPaths`). Перечень правил, поддерживаемый
 * рядом с бандлом, разошёлся бы с реальным набором молча — здесь он один, и
 * правило, добавленное в свой модуль, попадает в него само.
 */
import { crossDocumentRules } from './crossDocument.js';
import { engineValidationRules } from './engineRules.js';
import type { ValidationRule } from './types.js';

/**
 * Правила слоя валидации при раскладке документов по умолчанию. Параметров нет
 * намеренно: раскладка меняет то, где правило ищет вторую сторону, но не его id
 * и не коды его причин — а именно из них выводятся ключи ресурсов.
 */
export function builtinValidationRules(): readonly ValidationRule[] {
  return Object.freeze([...engineValidationRules(), ...crossDocumentRules()]);
}
