/**
 * Колоночная модель пересечений (PHYS-14): высотная полоса участника — отрезок
 * ДИСКРЕТНЫХ уровней террейна `[L, L + h − 1]`, и пара пересекается, только
 * если полосы имеют общий уровень.
 *
 * Модуль намеренно не знает ни форм, ни свипов, ни Command Buffer: здесь только
 * правило уровней и его входные данные — эффективный уровень сущности (TERR-4,
 * ARENA-6) и высота коллайдера. Применяют правило системы физики (`physics.ts`)
 * — рядом с масками `layer`/`blockMask`/`hitMask` и в переборе динамических
 * коллайдеров луча. В `collisionGeometry.ts` ему места нет: тот слой не знает
 * ни ECS, ни террейна, и знать не должен.
 *
 * Непрерывной вертикали от этого не появляется (PHYS-1, DET-8): всё правило —
 * два целочисленных сравнения, переносимых в порт один в один.
 */
import { LEVEL_OVERRIDE_COMPONENT, type EntityId, type Fixed, type TerrainApi } from '../types.js';

/**
 * Поле высоты коллайдера в уровнях (PHYS-14) — НЕОБЯЗАТЕЛЬНАЯ часть компонента
 * коллайдера: колоночный гейт включает сама сцена, объявив это поле у своего
 * компонента. Имя поля фиксировано, как и у пары точки прицела
 * (`INPUT_TARGET_FIELDS`, TICK-4): параметризовать его нечем — имя самого
 * компонента коллайдера сцена уже назвала (PHYS-2).
 */
export const COLLIDER_HEIGHT_FIELD = 'height';

/**
 * Зависимости сборки физики (DI-3). В отличие от `PhysicsOptions`, полями
 * документа прогона они не являются: их считает сборка по уже поднятому миру и
 * по составу сцены, а не читает из JSON.
 */
export interface PhysicsDeps {
  /** Ответ `colliderHeightDeclared`: включён ли колоночный гейт (PHYS-14). */
  readonly height?: boolean;
  /**
   * Запрос уровня сцены (TERR-4) — источник эффективного уровня цели в луче
   * (PHYS-14). `PhysicsSystem` его отсюда НЕ берёт: тот же запрос ей отдаёт
   * контекст тика (`ctx.terrain`).
   *
   * Поэтому на сборщике лежит обязанность: это ОБЯЗАН быть тот же `TerrainApi`,
   * который уходит на `Simulation.terrain`. Два гейта — пары и луча — по PHYS-14
   * стоят на одном эффективном уровне, и помощник у них общий; разойтись они
   * могут только здесь, входом. Сцена с террейном, собранная с пустым
   * `terrain`, дала бы луч, считающий производный уровень нулём для всех, при
   * гейте пары, видящем реальную карту, — молча и только на сценах с высотами.
   * Пропуск оправдан ровно в одном случае: у сцены террейна нет вовсе.
   */
  readonly terrain?: TerrainApi;
}

/**
 * Откуда читается эффективный уровень сущности. `SystemContext` подходит по
 * форме как есть; лучу такой объект собирает `createPhysicsApi` — один раз на
 * симуляцию, а не на вызов.
 */
export interface LevelSource {
  readonly terrain?: TerrainApi;
  readonly has: (entity: EntityId, component: string) => boolean;
  readonly get: (entity: EntityId, component: string, field: string) => number;
}

/** Точка запроса `levelAt`: переиспользуется, поэтому мутабельна (дисциплина аллокаций). */
export interface LevelProbe {
  x: Fixed;
  y: Fixed;
}

/**
 * Эффективный уровень сущности (TERR-4, ARENA-6) — ЕДИНСТВЕННАЯ точка чтения
 * уровня в физике: и полосы пары, и полосы цели луча берут его отсюда, поэтому
 * два гейта не разъезжаются.
 *
 * Порядок тот же, что у `TerrainApi.levelOf`: явный override приоритетнее
 * производного значения. Позиция передаётся явно, а не читается у сущности:
 * полоса заметаемого объёма считается по РАЗРЕШЁННОМУ состоянию тика (PHYS-14),
 * которое до вливания Command Buffer в мир ещё не попало.
 *
 * Сцена без террейна: производный уровень — ноль для всех, override действует и
 * там (PHYS-14).
 */
export function effectiveLevel(
  source: LevelSource,
  probe: LevelProbe,
  entity: EntityId,
  x: Fixed,
  y: Fixed,
): number {
  if (source.has(entity, LEVEL_OVERRIDE_COMPONENT)) {
    return source.get(entity, LEVEL_OVERRIDE_COMPONENT, 'level');
  }
  if (source.terrain === undefined) return 0;
  probe.x = x;
  probe.y = y;
  return source.terrain.levelAt(probe);
}

/**
 * Имеют ли полосы `[L, L + h − 1]` двух участников общий уровень (PHYS-14) —
 * то самое второе условие рядом с масками слоёв, независимое от них.
 *
 * Высота, не большая нуля, — полоса НЕ ОГРАНИЧЕНА: ноль есть умолчание
 * свежеобъявленного поля, и оно обязано значить «гейта нет», иначе объявление
 * поля в схеме молча выключило бы все пересечения сцены. Отрицательные значения
 * ядро толкует так же: собственных чисел высоты у него нет (PHYS-14), а полоса
 * отрицательной длины — не полоса.
 *
 * Луч приходит сюда полосой единичной высоты: у него уровень один (PHYS-13),
 * и правило «полоса коллайдера содержит уровень луча» — тот же тест общего
 * уровня, а не второе правило.
 */
export function bandsMeet(aLevel: number, aHeight: number, bLevel: number, bHeight: number): boolean {
  if (aHeight <= 0 || bHeight <= 0) return true;
  return aLevel <= bLevel + bHeight - 1 && bLevel <= aLevel + aHeight - 1;
}
