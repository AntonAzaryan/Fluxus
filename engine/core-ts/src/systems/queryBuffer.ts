/**
 * Буфер результата запроса, которым владеет САМА система (`ecs-foundation`
 * QUERY-3, `data-driven-systems` SYS-10).
 *
 * `ctx.query` материализует контейнер на каждый вызов — массив размером в число
 * живых сущностей мира (форма SYS-5, ею живут JSON-системы). Нативной системе,
 * зовущей запрос каждый тик, это аллокация, пропорциональная размеру мира, и
 * снимает её `ctx.queryInto`: отбор тот же и порядок тот же (QUERY-2), а
 * результат пишется в буферы, выделенные один раз и переиспользуемые между
 * тиками.
 *
 * Общим переиспользуемым буфером это не является и QUERY-3 не нарушает: буфер
 * принадлежит ОДНОМУ экземпляру системы, и вложенный запрос той же системы
 * берёт СВОЙ буфер — второй экземпляр этого класса, а не этот же. Дисциплина
 * вложенности от этого становится обязанностью системы, и она же — причина не
 * прятать буфер внутрь контекста: спрятанный, он был бы общим на всех.
 *
 * Рост — по ответу самого запроса: `queryInto` возвращает ПОЛНОЕ число
 * совпавших, даже когда в буфер поместилась лишь часть, поэтому промах по
 * ёмкости стоит одного повторного прохода и никогда не теряет сущностей. Мир
 * между двумя проходами не меняется (мутации отложены, CMD-1), поэтому второй
 * ответ равен первому.
 */
import type { QuerySpec, SystemContext } from '../types.js';

const EMPTY_IDS = new Float64Array(0);
const EMPTY_INDICES = new Int32Array(0);

export class QueryBuffer {
  /** Идентификаторы совпавших — первые `count` (QUERY-2). */
  ids: Float64Array = EMPTY_IDS;
  /** Raw-индексы их слотов: адрес чтения по индексу (SYS-10). */
  indices: Int32Array = EMPTY_INDICES;
  /** Сколько записано последним `run` — длина буферов ему не равна. */
  count = 0;

  /**
   * Снимает выборку в собственные буферы и возвращает её размер. Окно
   * валидности результата — тело вызвавшей системы (QUERY-3), как и у `query`:
   * буферы переживают тик, состав мира — нет.
   */
  run(ctx: SystemContext, spec: QuerySpec): number {
    let matched = ctx.queryInto(spec, this.ids, this.indices);
    if (matched > this.ids.length) {
      // Удвоение, но не меньше запрошенного: сцена, выросшая скачком, не должна
      // расти по одному удвоению на тик.
      const size = Math.max(matched, this.ids.length * 2);
      this.ids = new Float64Array(size);
      this.indices = new Int32Array(size);
      matched = ctx.queryInto(spec, this.ids, this.indices);
    }
    this.count = matched;
    return matched;
  }
}
