/**
 * Проекция мира на точку зрения — механизм ядра (NET-12..15, NET-13
 * «Владение»).
 *
 * Граница владения проходит между вычислением и выбором, и она общая у
 * фильтрации снапшота и фильтрации событий: вычисление того, что видно данной
 * точке зрения, живёт здесь; выбор точки зрения для соединения, момент вызова и
 * состав уезжающего на провод — за сетевым слоем (`netcode-transport` NTR-9,
 * NET-18). Своей реализации отбора сетевой слой иметь MUST NOT — второй
 * реализацией он завёл бы второе определение слова «видно», а маска считается
 * симуляцией (FOW-2, FOW-5) и вырезание обязано идти штатным удалением сущности
 * со всеми последствиями для схемы идентификаторов (NET-12, ID-3, ID-6).
 *
 * Отсюда же адрес самого модуля: `viewpoint = ALL` нужен реплеям и golden-файлам
 * (NET-15, CLI-5), которые сетевого слоя не поднимают вовсе, а ядро о сети не
 * знает (DI-6) — зависимость односторонняя (NTR-1).
 *
 * Внешний слой НАД `TickResult`, а не система в scheduler'е (NET-12): сервер
 * тикает мир ОДИН раз, а затем режет из него персональные снапшоты — до 10 штук
 * на тик. Фильтр читает финальное состояние тика и не мутирует ни мир, ни
 * `TickResult`: он работает по копии.
 *
 * Результат — снапшот МИРА, спроецированный на точку зрения. Снапшот на проводе
 * — не он, а его подмножество, перечисленное NET-18 (без состояний стримов RNG):
 * состав кадра строит сетевой слой, потому что «снапшот без rng» осмыслен только
 * относительно провода, о котором ядро не знает.
 *
 * NET-14: отсутствие сущности в результате означает «ушла в туман», и ничем
 * больше. Смерть — только явное событие `EntityDied` от геймплейной системы;
 * фильтр событий не порождает и ни одну сущность мёртвой не помечает.
 *
 * ponytail: результат — полный `Snapshot` с копией мира, а не diff. Копия на
 * клиента на тик — ровно тот профиль нагрузки, который netcode-спека
 * («Стоимость per-client фильтрации») просит замерить; delta-компрессия и
 * per-client baseline — оптимизация потом (NET-8), не сейчас.
 */
import { query } from '../ecs/query.js';
import { cloneWorld, destroy, getField, isAlive, scrubFields } from '../ecs/world.js';
import { teamBit, VISIBILITY_COMPONENT } from '../systems/visibility.js';
import { takeSnapshot } from './tick.js';
import type { EntityId, GameEvent, ReadonlySimulationState, Snapshot } from '../types.js';

/**
 * Без фильтрации: спектейтор, реплей, дебаг, golden-файлы CLI (NET-15, CLI-5).
 * Значение вне диапазона команд `[0, 31]` (FOW-2), поэтому с teamId не спутать.
 */
export const VIEWPOINT_ALL = -1;

/**
 * Предикат видимости события — ПАРАМЕТР механизма (NET-13 «Действующий
 * предикат»). Параметр он потому, что точная политика при разной видимости
 * источника и цели остаётся открытым геймплейным вопросом; действующее значение
 * при этом не умолчание реализации, а норма (`relevantEntityVisible` ниже), и
 * называет его поле конфига матча (NTR-9) — то есть закрытие вопроса будет
 * правкой контента, а не правкой ядра или сетевого слоя.
 */
export type EventVisibility = (event: GameEvent, isVisible: (entity: EntityId) => boolean) => boolean;

/**
 * Имена полей данных события, считающихся ссылками на сущности. Набор ЗАКРЫТ
 * нормой NET-13, а не выбран этим модулем, и поле с именем вне набора видимости
 * событию не добавляет: данные события — плоская карта чисел (OBS-1), в которой
 * ссылку от числа отличает только имя, и догадка о незнакомом имени разошлась бы
 * между двумя реализациями ядра (CLI-6). Расширение набора — правка спеки, как у
 * закрытых наборов действий и операторов (ACT-1, EXPR-6).
 */
export const EVENT_ENTITY_FIELDS: readonly string[] = ['entity', 'other', 'source', 'target'];

/**
 * Действующий предикат, нормированный NET-13: событие уходит клиенту, если
 * видима хотя бы одна названная в его данных сущность; событие, не называющее ни
 * одной сущности (сужение арены, конец раунда), считается общим и уходит всем.
 *
 * Это реализация нормы, а не решение модуля: величина, приезжающая молчанием,
 * была бы политикой, выбранной тем, кто первым написал код, — а норма одинакова в
 * обеих реализациях ядра по построению (CLI-6). Заменяется предикат целиком, а не
 * патчится, и адрес замены один — поле конфига матча (NTR-9).
 */
export const relevantEntityVisible: EventVisibility = (event, isVisible) => {
  let referenced = false;
  for (const field of EVENT_ENTITY_FIELDS) {
    const value = event.data[field];
    if (value === undefined) continue;
    referenced = true;
    if (isVisible(value)) return true;
  }
  return !referenced;
};

/** Состояние от `Snapshot` отличает rng: там реестр, здесь снятый срез. */
function isSnapshot(source: Snapshot | ReadonlySimulationState): source is Snapshot {
  return Array.isArray(source.rng);
}

/**
 * Персональный снапшот для `viewpoint` (NET-12). Из мира вырезаются сущности,
 * чей бит команды не взведён в `Visibility.visibleTo`; сущность БЕЗ компонента
 * `Visibility` считается публичной и остаётся в каждом персональном снапшоте
 * (NET-12) — отсутствие компонента есть отсутствие утверждения о том, кому
 * сущность видна, а не утверждение «никому». Прочитанное как «никому», оно
 * вырезало бы носителя карты пола (TERR-6), носителя арены (ARENA-1) и всю
 * обстановку, то есть отняло бы у клиента данные, которые оболочка обязана
 * получить до первого кадра (SHELL-5). Направление умолчания держится тестом,
 * а не этим комментарием (`test/filter.test.ts`).
 *
 * Своя сущность в собственном снапшоте остаётся даже скрытой любым
 * стелс-каналом (NET-15): бит своей команды `VisibilitySystem` взводит
 * безусловно, до всех фильтров (FOW-3).
 *
 * Шина тика уходит в результат отобранной тем же предикатом и тем же вызовом,
 * что и поток событий (NET-18, NTR-15): разойдись предикат или момент, клиент
 * увидел бы в состоянии факт, которого не было в потоке.
 *
 * `viewpoint = VIEWPOINT_ALL` — фильтрации нет вовсе, ни у мира, ни у шины:
 * фильтр снимается целиком, а не по каналам (NTR-9).
 */
export function filterSnapshot(
  source: Snapshot | ReadonlySimulationState,
  viewpoint: number,
  eventVisibility: EventVisibility = relevantEntityVisible,
): Snapshot {
  // Копия всегда: возвращать чужой снапшот значило бы отдать наружу объект,
  // который вызывающий считает своим, а мы — своим результатом.
  const snapshot: Snapshot = isSnapshot(source)
    ? { ...source, world: cloneWorld(source.world), events: [...source.events] }
    : takeSnapshot(source);
  if (viewpoint === VIEWPOINT_ALL) return snapshot;

  const world = snapshot.world;
  const bit = teamBit(viewpoint);
  // Мир без компонента `Visibility` (сцена без FoW) даёт пустой запрос — фильтр
  // тогда ничего не режет, и это верно: скрывать нечего.
  for (const entity of query(world, { all: [VISIBILITY_COMPONENT] })) {
    if ((getField(world, entity, VISIBILITY_COMPONENT, 'visibleTo') & bit) === 0) {
      destroy(world, entity);
      // Штатного удаления мало: `destroy` гасит живость, маску и теги, а ячейки
      // SoA-массивов хранят прошлое сущности и сериализуются в plain-форму
      // независимо от живости. Данных о скрытой сущности у клиента нет
      // ФИЗИЧЕСКИ (NET-12) — затираются и ячейки, иначе позиция, здоровье и
      // сателлиты способностей читались бы модифицированным клиентом прямо из
      // кадра на проводе (NET-18, wallhack).
      scrubFields(world, entity);
    }
  }

  // Видимость события считается по УЖЕ отфильтрованному миру: «сущность есть в
  // этом снапшоте» и «клиент про неё знает» — одно и то же (NET-13).
  const visible = (entity: EntityId): boolean => isAlive(world, entity);
  return { ...snapshot, events: snapshot.events.filter((event) => eventVisibility(event, visible)) };
}
