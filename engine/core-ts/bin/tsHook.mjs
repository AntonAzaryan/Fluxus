/**
 * Хук резолва для команд поверх ядра: исходники импортируют './x.js', а рядом
 * лежит './x.ts'.
 *
 * Шага сборки нет намеренно (см. шапку `sim.mjs`): типы Node стрипает сам
 * (>=22.18), и хук добавляет единственное, чего ему не хватает. Отдельным
 * модулем — потому что команд поверх ядра стало две (`sim.mjs`, `journal.mjs`),
 * а вторая копия регистрации и есть способ им разойтись.
 *
 * Импортируется РАДИ ПОБОЧНОГО ДЕЙСТВИЯ и обязательно статически: статический
 * граф резолвится целиком до первой строки кода, поэтому типизированные модули
 * ядра команды берут динамическим `await import(...)` — уже после установки.
 */
import { registerHooks } from 'node:module';

registerHooks({
  resolve(specifier, context, next) {
    if (specifier.startsWith('.') && specifier.endsWith('.js')) {
      try {
        return next(`${specifier.slice(0, -3)}.ts`, context);
      } catch {
        // Настоящего .ts нет — резолвим как просили.
      }
    }
    return next(specifier, context);
  },
});
