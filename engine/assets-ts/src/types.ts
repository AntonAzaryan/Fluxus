/**
 * Контракты модуля ассетов. Модуль обслуживает только presentation-ассеты —
 * данные внешних наблюдателей (ASSET-1): модели, текстуры, манифест визуалов.
 * Sim-значимые данные (террейн, арена, prefabs) грузятся загрузчиком конфига
 * сцены (SER-7) и через этот модуль не проходят — у модуля нет API, ведущего
 * в симуляцию, запрет обеспечен границей модулей.
 *
 * Модуль рендер-агностичен (ASSET-5): никаких зависимостей на Three.js, DOM
 * и GPU-API. Все типы описывают чистые данные; загрузка, парсинг и
 * декодирование изображений работают headless в Node — так логика покрывается
 * быстрыми тестами без браузера.
 */

/**
 * Вид ассета — ОТКРЫТОЕ множество (ASSET-3). Известные виды перечислены ради
 * автодополнения и опечаток, но тип принимает любую строку: добавление вида
 * (звук, шрифт) не должно быть правкой ядра — ровно как и добавление формата.
 * `string & {}` — идиома, которая оставляет подсказки по литералам, не закрывая
 * множество.
 */
export type KnownAssetKind =
  | 'model'
  | 'texture'
  | 'manifest'
  | 'terrain-curvature'
  // Документ эффекта частиц (ASSET-14). Вид назван частицами, а не просто
  // «эффектом»: эффектом в манифесте зовутся и транзиентные примитивы
  // (REND-23), и эффекты камеры (ASSET-8), и совпадение имён сделало бы вид
  // ассета неотличимым от них на слух.
  | 'particle-effect'
  // Таблица цветокоррекции кадра (`rendering` REND-34): трёхмерная решётка
  // «цвет → цвет», формат `.cube`.
  | 'lut'
  | 'presentation';
// Подавления здесь больше нет: `string & {}` — известная идиома открытого
// множества, и линтер её пропускает сам. Прежний комментарий гасил правило
// `ban-types`, которого в typescript-eslint 8 уже не существует.
export type AssetKind = KnownAssetKind | (string & {});

/**
 * Типизированная ссылка на ассет (ASSET-2). `T` — фантомный параметр типа
 * данных: в рантайме не хранится, но связывает `request` с `state`.
 * Данные ассета доступны только через сервис по handle.
 */
// eslint-disable-next-line @typescript-eslint/no-unused-vars -- `T` фантомный по построению: он и не должен появляться в полях
export interface Handle<T = unknown> {
  readonly id: string;
  readonly kind: AssetKind;
}

/**
 * Наблюдаемое состояние загрузки (ASSET-4); `failed` всегда с причиной.
 * Поля readonly, а сервис отдаёт объект замороженным: состояние разделяется
 * всеми подписчиками одного ассета, и правка «у себя» была бы правкой у всех.
 */
export type AssetState<T> =
  | { readonly status: 'loading' }
  | { readonly status: 'ready'; readonly data: T }
  | { readonly status: 'failed'; readonly reason: string };

/**
 * Источник байтов по ID ассета — ID является путём в дереве контента
 * (ASSET-2). Реализации: fetch в браузере, файловая система в тестах.
 */
export interface AssetSource {
  read(id: string): Promise<ArrayBuffer>;
}

/**
 * Контекст загрузки одного ассета (ASSET-3): всё, что загрузчику позволено
 * знать о внешнем мире.
 *
 * Формат вправе состоять из нескольких файлов — glTF это описание, внешний
 * бинарный буфер и внешние изображения, — поэтому загрузчику нужен способ
 * дочитать соседние файлы. Но именно СОСЕДНИЕ: контекст не даёт ни кэша, ни
 * реестра, ни возможности запросить ассет через сервис. Иначе загрузчик смог бы
 * тянуть цепочки загрузок через сервис — это рекурсия и вторая, неявная точка
 * входа в кэш.
 */
export interface LoaderContext {
  /** ID загружаемого ассета — путь в дереве контента. */
  readonly id: string;
  /**
   * Прочитать файл по пути, относительному от ID ассета (`'buffer.bin'`,
   * `'../shared/atlas.png'`). Выход за корень дерева контента запрещён.
   * Недоступность файла бросает ошибку, называющую недостающий путь, — сервис
   * превратит её в `failed` с этой причиной.
   */
  read(relativePath: string): Promise<ArrayBuffer>;
}

/**
 * Загрузчик формата (ASSET-3). Регистрируется в сервисе под парой «вид +
 * расширения», которые понимает, и парсит байты в иммутабельные данные ассета.
 * Новый формат — новый загрузчик; ядро сервиса и другие загрузчики не меняются.
 */
export interface AssetLoader<T = unknown> {
  kind: AssetKind;
  /** Расширения с точкой: `['.mdx']`, `['.png']`, `['.json']`. */
  extensions: readonly string[];
  load(bytes: ArrayBuffer, ctx: LoaderContext): Promise<T> | T;
}
