/**
 * Декодированное изображение — то, чем является текстурный ассет (ASSET-5).
 *
 * Именно декодированное, а не содержимое файла: ассет существует затем, чтобы
 * дорогая работа делалась один раз и разделялась всеми потребителями. Отдавая
 * потребителю сжатый PNG, модуль разделяет байты, которые ничего не стоят, и
 * заставляет каждый инстанс декодировать заново.
 */
export interface DecodedImage {
  readonly width: number;
  readonly height: number;
  /**
   * Пиксели построчно сверху вниз, 4 байта на пиксель. Единственный формат:
   * рендеру всё равно нужен именно он, а разнообразие раскладок на границе
   * модуля обернулось бы ветвлением у каждого потребителя.
   */
  readonly format: 'rgba8';
  /** Длина = width * height * 4. */
  readonly pixels: Uint8Array;
}
