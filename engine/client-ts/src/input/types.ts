/**
 * Контракты слоя источников ввода (input-devices INP-1): физическое устройство
 * переводится в семантический сэмпл — вектор движения, прицел, фронты действий —
 * и ничего устройство-специфичного (коды клавиш, координаты касаний, индексы
 * осей) за границу источника не выходит. Float здесь законен: это оболочка,
 * производящая ввод, а не тик; квантование в Q16.16 делает сэмплер в
 * единственной точке (INP-3).
 */

/**
 * Полный оборот в единице угла ядра (FP-7): `aimDir` — binary angle measure,
 * то есть сырое значение угла совпадает с Q16.16-долей оборота.
 */
export const TURN_UNITS = 0x10000;

/**
 * Вектор направления → угол в единицах ядра. Маска — чтобы по проводу не
 * ездили старшие биты: заворачивание угла ядро делает само.
 */
export function aimAngle(dx: number, dy: number): number {
  return Math.round((Math.atan2(dy, dx) / (2 * Math.PI)) * TURN_UNITS) & (TURN_UNITS - 1);
}

/**
 * Точка прицела в МИРОВЫХ координатах, float (INP-1). Величина того же класса,
 * что направление прицела, и различия устройств в ней умирают там же: источник
 * с указателем разрешает экранную позицию по видимому изображению (REND-15),
 * источник без указателя строит точку из своего органа управления сам.
 *
 * Понятий способности, её дальности и её фигуры у точки нет и быть не может:
 * источник отдаёт точку, а что с ней делать, решает симуляция (ABIL-5).
 */
export interface AimPoint {
  readonly x: number;
  readonly y: number;
}

/** Приёмник `aimTarget`: источник держит одну запись и переиспользует её. */
export interface MutableAimPoint {
  x: number;
  y: number;
}

/**
 * Разрешённый прицел указателя: направление и точка одним ответом. Обе
 * величины считает приложение (raycast по видимому — знание приложения, не
 * слоя ввода), и считает ОДНИМ лучом: два независимых ответа разъезжались бы
 * между собой ровно там, где превью обещает игроку то, по чему решит тик.
 */
export interface AimResolution extends AimPoint {
  /** Направление на точку в единицах угла ядра (FP-7). */
  readonly angle: number;
}

/**
 * Точка прицела органа управления БЕЗ указателя (INP-1): начало прицеливания
 * плюс отклонение стика, развёрнутое в мировую точку. Общий хелпер слоя —
 * стик геймпада и тач-стик строят точку одинаково, и двух арифметик под это не
 * заводится.
 *
 * `distance` — мировые единицы; сколько их даёт полный ход стика, знает
 * биндинг устройства (данные, не код). Ответ пишется в переданную запись:
 * опрос идёт покадрово, и свежий объект на каждый опрос был бы мусором.
 */
export function aimTarget(
  origin: AimPoint,
  angle: number,
  distance: number,
  out: MutableAimPoint,
): AimPoint {
  const radians = (angle / TURN_UNITS) * 2 * Math.PI;
  out.x = origin.x + Math.cos(radians) * distance;
  out.y = origin.y + Math.sin(radians) * distance;
  return out;
}

/**
 * Приёмник фронтов действий: источник пушит имя действия в момент
 * возникновения, сэмплер латчит его до границы тика (INP-2).
 */
export type ActionSink = (action: string) => void;

/**
 * Непрерывное состояние источника на момент опроса. Оси — мировые (Y вверх):
 * экранную инверсию Y каждый источник делает сам.
 */
export interface ContinuousSample {
  /** Вектор движения; сэмплер клампит единичным кругом (INP-3). */
  readonly moveX: number;
  readonly moveY: number;
  /** Прицел в единицах угла ядра; null — источник прицелом не владеет. */
  readonly aim: number | null;
  /**
   * Точка прицела в мировых координатах; null — источник точкой не владеет
   * (INP-1). Наравне с вектором движения и направлением: потребитель сэмпла не
   * знает, чем целились.
   *
   * Запись принадлежит источнику и переиспользуется — читать до следующей
   * выборки, ровно как множество `held()`.
   */
  readonly target: AimPoint | null;
}

/**
 * Источник ввода (INP-1, design D2): опрос непрерывного состояния + пуш
 * фронтов. Событийные устройства пушат из своих обработчиков; опросные —
 * из `poll()`, вычисляя фронт сравнением prev/current (`HeldActions`).
 */
export interface InputSource {
  readonly id: string;
  /** Сэмплер зовёт при добавлении; `press` — его латч фронтов (INP-2). */
  start(press: ActionSink): void;
  stop(): void;
  /** `null` — источник неактивен: устройство отключено или ещё не появилось (INP-5). */
  poll(): ContinuousSample | null;
  /**
   * Действия, чей орган управления зажат на момент выборки (INP-2): сэмплер
   * ORит их в маску сэмпла поверх залатченных фронтов, поэтому удержание
   * видно симуляции все тики подряд, а отпускание — как falling edge.
   *
   * Зовётся сразу после `poll()`: опросный источник заполняет своё состояние
   * там. Возвращаемое множество принадлежит источнику и переиспользуется —
   * читать его до следующей выборки. Источник без удерживаемых органов метод
   * не реализует; `null` — источник неактивен (INP-5).
   */
  held?(): ReadonlySet<string> | null;
}
