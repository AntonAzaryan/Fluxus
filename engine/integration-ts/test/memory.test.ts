/**
 * Сторожа реальной памяти процесса (`performance-budget` PERF-10, PERF-11) — по
 * образцу wall-time сторожей PERF-5: печать при КАЖДОМ прогоне, ассерт только
 * против роста порядка величины, эталона нет и быть не может.
 *
 * ## Два прибора, две фазы
 *
 * PERF-10 смотрит на кучу ПОСЛЕ принудительной сборки — то есть на удержанное:
 * замыкания и слушатели, внутренности сторонних библиотек, объекты интерпретатора
 * выражений. Это ровно то, чего не видят по построению точные величины PERF-8:
 * подписанный и не снятый слушатель ресурсов не заводит и записей не добавляет.
 *
 * PERF-11 смотрит на ту же кучу МЕЖДУ сборками — на порождённый мусор: число
 * малых сборок на тысячу тиков и байты, занятые окном тиков без единой сборки.
 * Этот класс не двигает ни счётчики стоимости PERF-3 (они считают работу, а не
 * объекты), ни величины PERF-8 (владеемые структуры не растут), ни сторож
 * PERF-10 (мусор собран до пробы), а PERF-5 замечает его лишь при росте времени
 * на порядок.
 *
 * ## Почему ассерт только относительный и только на порядок
 *
 * Уровень кучи — функция версии среды исполнения и её сборщика, а не кода:
 * репозиторий допускает три мажора Node (`engines`), и у каждого своя раскладка
 * объектов и свой размер молодого поколения. Жёсткий порог на уровень краснел бы
 * на обновлении среды, ничего не поймав, — тем же способом, каким краснел бы
 * жёсткий порог wall-time на слабой машине (PERF-5). Поэтому:
 *
 * - точка A снимается ПОСЛЕ прогрева (первый прогон греет JIT, кэши модулей,
 *   таблицы форм объектов), точка B — вдвое дальше;
 * - в каждой точке берётся минимум из нескольких проб с полной сборкой перед
 *   каждой (`sampleMemory`);
 * - ассертится РОСТ между точками, отнесённый к занятому в точке A.
 *
 * Запас порогов ниже — константы с обоснованием по НАБЛЮДАЕМОМУ разбросу, как
 * `MAX_UNITS_PER_TICK` у сторожа времени. Калибр тот же: утечка порядка самого
 * занятого объёма за окно обязана краснеть, дрожание — нет.
 *
 * ## Что эти сторожа НЕ ловят
 *
 * Одну удержанную запись в сотню байт на тик под дрожанием сборщика они не
 * увидят — её видит точный учёт PERF-8/PERF-9 первой же единицей. Здесь ловится
 * утечка ПОРЯДКА занятого объёма: слушатель на доставку, экземпляр на сессию,
 * объект на сущность за тик.
 */
import { beforeAll, describe, expect, it } from 'vitest';
import {
  createFootprint,
  withFootprintSink,
  type ExtractedTick,
} from '@fluxus/render';
import {
  BENCH_PRESETS,
  loadNpcStress,
  loadRecording,
  matchBench,
  prepareRecording,
  syntheticTick,
  type PreparedRecording,
  type SyntheticLoad,
} from './benchLoad.js';
import { calibrationLine } from '../../tests/bench/calibration.js';
import {
  allocationWindow,
  growthOf,
  mib,
  observeGc,
  sampleMemory,
} from '../../tests/bench/memory.js';

/** Запись, которой гоняется оборот сессий: самая длинная из набора (CLI-10). */
const SESSION_MATCH = 'match-fuzz';

/**
 * Сессий в обороте: половина до точки A, половина до точки B. Двенадцать —
 * компромисс между устойчивостью пробы и временем прогона: удержание в
 * модульном синглтоне (реестр, `warnOnce`, держатель стока) копится по одной
 * записи на сессию, и шести сессий хватает, чтобы рост стал виден.
 */
const SESSIONS = 12;

/**
 * Запас сторожа кучи: во сколько раз занятая память вправе вырасти за окно.
 *
 * Наблюдаемое на контейнере гейта — доли процента (единицы сотых): устоявшийся
 * прогон кучу не растит вовсе, и весь наблюдаемый рост — дрожание сборщика и
 * прогрев кодов JIT. Порог на порядок выше наблюдаемого, а не «в притык»:
 * сторож обязан пережить и другую версию среды, и чужую нагрузку на машине, а
 * утечку порядка занятого объёма (сессия, не отпустившая свой мир) пропустить
 * сквозь себя не вправе.
 */
const MAX_GROWTH_RATIO = 0.25;

/** Тиков в длинном прогоне сторожа давления на сборщик и знаменатель его величины. */
const PRESSURE_TICKS = 600;
const PER_TICKS = 1000;

/**
 * Запасы сторожа давления на сборщик: во сколько раз вправе вырасти число малых
 * сборок на тысячу тиков и байты окна без сборки. Порог У КАЖДОЙ НАГРУЗКИ СВОЙ и
 * выведен из ЕЁ наблюдаемого значения: общий порог, взятый по самой мусорной из
 * них, на всех прочих означал бы сотни крат запаса, то есть отсутствие сторожа.
 *
 * Наблюдаемое на контейнере гейта:
 *
 * - масса NPC (двести агентов): 40 малых сборок на тысячу тиков, порядка
 *   710 КиБ на тик в окне без сборки (куча плюс байты буферов: подложки
 *   типизированных массивов живут вне кучи изолята, и мусор из них по одной
 *   куче был бы невидим);
 * - оборот сессий (сборка мира и прогон записи): 2 малых сборки на тысячу тиков.
 *
 * Все три величины зависят от размера молодого поколения среды исполнения, а не
 * только от кода, поэтому ассерт — только на ПОРЯДОК над наблюдаемым, и жёстче
 * он быть не вправе (PERF-11).
 *
 * Чувствительность сторожа — функция того мусора, который тик уже порождает, и
 * это сказано прямо и в требовании: на нагрузке, где тик и так аллоцирует
 * килобайты на агента, небольшой объект на сущность двигает величину на
 * проценты, и порогом такой рост не ловится ни при каком допустимом запасе.
 * Виден он ПЕЧАТЬЮ, которая идёт при каждом прогоне, — ровно та роль, которую
 * PERF-5 отводит сторожам времени; краснеет же сторож на регрессии, поднимающей
 * мусор тика на порядок. Проверено на этой нагрузке: копия состояния на каждую
 * сущность каждым тиком (колонка мира на агента) даёт 7.7 МиБ на тик против
 * наблюдаемых 0.71 МиБ — сторож краснеет по байтам окна, а число малых сборок
 * при этом растёт вчетверо и добавляет девять десятков ПОЛНЫХ сборок, которых в
 * норме нет вовсе. Число сборок насыщается раньше байтов, и поэтому обе величины
 * печатаются, а не одна.
 */
const MAX_NPC_MINOR_PER_1000 = 400;
const MAX_SESSION_MINOR_PER_1000 = 25;
const MAX_BYTES_PER_TICK = 7_000_000;

/**
 * Ассерт числа малых сборок — только когда их НАБЛЮДАЛИ. Ноль сборок за окно не
 * является измерением: сборщик вправе не собирать вовсе (в общем пуле гейта
 * куча воркера уже выросла вместе с молодым поколением), и `0 < порог` прошло
 * бы такой прогон как чистый. «Не измерено» и «измерено и чисто» — разные
 * утверждения, и сторож обязан их различать (PERF-11, сценарий «Окна без
 * сборки не нашлось»).
 */
function guardMinorGc(where: string, minorPer1000: number, limit: number): void {
  if (minorPer1000 === 0) {
    console.log(`[bench] сборщик, ${where}: малых сборок не наблюдалось — НЕ ИЗМЕРЕНО`);
    return;
  }
  expect(minorPer1000, `${where}: малые сборки на тысячу тиков`).toBeLessThan(limit);
}

/** Нагрузка доставки для цикла стенда: наблюдатели на месте, состав сменяется. */
const DELIVERY_LOAD: SyntheticLoad = {
  entities: 48,
  observers: 2,
  vision: 1.5,
  extent: 16,
  shots: 0,
};

/** Циклов сборки и сноса презентационного тракта — как у вьюпорта (ED-15). */
const STAND_CYCLES = 12;
/** Доставок в одном цикле стенда. */
const STAND_DELIVERIES = 8;

function rotatingTick(round: number): ExtractedTick {
  const ext = syntheticTick(DELIVERY_LOAD);
  for (let i = DELIVERY_LOAD.observers; i < ext.count; i++) {
    ext.id[i] = 1_000_000 + round * ext.count + i;
  }
  return ext;
}

/**
 * Прогон половины окна, проба, вторая половина, проба — и печать обеих с ростом.
 * Общая часть трёх сторожей PERF-10: нагрузки разные, процедура одна.
 */
function guardHeapGrowth(name: string, half: () => void): void {
  // Прогрев ДО точки A: первый прогон греет JIT и кэши модулей, и его рост —
  // не утечка, а стоимость первого знакомства среды с кодом.
  half();
  const a = sampleMemory();
  half();
  const b = sampleMemory();
  const growth = growthOf(a, b);
  console.log(
    `[bench] куча, ${name}: ${mib(a.heapUsed)} → ${mib(b.heapUsed)} ` +
      `(рост ${(growth.ratio * 100).toFixed(1)} %, буферы ${mib(a.arrayBuffers)} → ${mib(b.arrayBuffers)})`,
  );
  expect(growth.ratio, name).toBeLessThan(MAX_GROWTH_RATIO);
}

describe('PERF-10: сторож кучи — рост в устоявшемся состоянии', () => {
  beforeAll(() => {
    // Печать при каждом прогоне (PERF-5, PERF-10): по строке калибровки
    // читаются остальные — она же называет режим сборки.
    console.log(calibrationLine());
  });

  it('оборот сессий: сборка мира и прогон записи не растят кучу', () => {
    const def = loadRecording(SESSION_MATCH);
    const half = (): void => {
      for (let i = 0; i < SESSIONS / 2; i++) {
        // Мир строится ЗАНОВО на каждую сессию и отпускается вместе с ней:
        // удержание в модульном синглтоне — ровно то, чего не видит ни один
        // сток, и ровно то, что этот сторож обязан поймать.
        prepareRecording(def).run();
      }
    };
    guardHeapGrowth(`оборот сессий (${SESSION_MATCH} ×${String(SESSIONS / 2)})`, half);
  });

  it('устоявшийся мир массы NPC: длинный прогон одного мира кучу не растит', () => {
    const world = prepareRecording(loadNpcStress());
    const runs = 8;
    const half = (): void => {
      for (let i = 0; i < runs; i++) world.run();
    };
    guardHeapGrowth(`масса NPC (${String(runs * world.ticks)} тиков)`, half);
  });

  it('цикл стенда: сборка и снос презентационного тракта кучу не растят', () => {
    const sink = createFootprint();
    const half = (): void => {
      withFootprintSink(sink, () => {
        for (let cycle = 0; cycle < STAND_CYCLES / 2; cycle++) {
          const bench = matchBench(BENCH_PRESETS.performance);
          for (let i = 0; i < STAND_DELIVERIES; i++) {
            bench.deliver(rotatingTick(cycle * STAND_DELIVERIES + i));
          }
          bench.stage.dispose();
        }
      });
    };
    guardHeapGrowth(`цикл стенда (×${String(STAND_CYCLES / 2)})`, half);
  });
});

/** Прогон нагрузки давления: тики идут синхронно, без снапшотов и доставки. */
function pressureWorld(): PreparedRecording {
  return prepareRecording(loadNpcStress());
}

describe('PERF-11: сторож давления на сборщик мусора', () => {
  it('масса NPC: малые сборки на тысячу тиков и байты окна без сборки', async () => {
    const world = pressureWorld();
    // Прогрев: первый прогон греет JIT, и его мусор — стоимость знакомства, а
    // не устоявшийся режим.
    world.run();

    const watch = observeGc();
    const runs = Math.ceil(PRESSURE_TICKS / world.ticks);
    for (let i = 0; i < runs; i++) world.run();
    const counts = await watch.take();
    watch.stop();
    const ticks = runs * world.ticks;
    const minorPer1000 = (counts.minor * PER_TICKS) / ticks;

    const window = await allocationWindow((width) => {
      for (let i = 0; i < width; i++) world.runTicks(1);
    }, world.ticks);
    const bytesPerTick = window.found ? window.bytes / window.ticks : Number.NaN;

    console.log(
      `[bench] сборщик, масса NPC: ${minorPer1000.toFixed(1)} малых сборок на ${String(PER_TICKS)} тиков ` +
        `(${String(counts.minor)} за ${String(ticks)} тиков, полных ${String(counts.major)}); ` +
        (window.found
          ? `${Math.round(bytesPerTick).toLocaleString('ru-RU')} байт на тик в окне ${String(window.ticks)} тиков`
          : `окна без сборки нет за ${String(window.attempts)} попыток — сам этот случай читается как давление`),
    );

    // Число сборок ассертится и тогда, когда окна без сборки не нашлось
    // (PERF-11): «не нашлось» не даёт числа байт, но само по себе давление на
    // сборщик уже описывает. Ноль сборок при этом измерением не считается.
    guardMinorGc('масса NPC', minorPer1000, MAX_NPC_MINOR_PER_1000);
    if (window.found) {
      expect(bytesPerTick, 'байты на тик в окне без сборки').toBeLessThan(MAX_BYTES_PER_TICK);
    }
  });

  it('оборот сессий: мусор сборки мира и прогона записи — той же меркой', async () => {
    const def = loadRecording(SESSION_MATCH);
    const session = (): void => {
      prepareRecording(def).run();
    };
    session();

    const watch = observeGc();
    const sessions = 8;
    for (let i = 0; i < sessions; i++) session();
    const counts = await watch.take();
    watch.stop();
    const ticks = sessions * def.ticks;
    const minorPer1000 = (counts.minor * PER_TICKS) / ticks;

    console.log(
      `[bench] сборщик, оборот сессий: ${minorPer1000.toFixed(1)} малых сборок на ` +
        `${String(PER_TICKS)} тиков (${String(counts.minor)} за ${String(sessions)} сессий, ` +
        `${String(ticks)} тиков)`,
    );
    guardMinorGc('оборот сессий', minorPer1000, MAX_SESSION_MINOR_PER_1000);
  });
});
