/**
 * Контракт мозга бота (BOT-2) — точка инверсии зависимостей по образцу DI-швов
 * ядра (`determinism-core` DI-4): хостинг бота зависит только от этого
 * интерфейса и не знает, какая реализация под ним. Замена классического мозга
 * на обученный — замена фабрики в сборке, а не правка хостинга, клиента или
 * протокола.
 *
 * Два метода — два каденса, и разведены они намеренно.
 *
 * `observe` зовётся на КАЖДОМ доставленном шаге клиента: наблюдение приходит по
 * мере прихода состояний и фактов. `sample` — синхронный съём «ввод на тик N»
 * из источника ввода клиента (`input-devices` INP-1): он обязан вернуться сразу,
 * потому что за ним стоит отправка кадра, и каденс отправки задаёт клиент, а не
 * скорость мышления (BOT-2, BOT-4). Мозг вправе думать асинхронно и в своём
 * темпе: тяжёлая реализация кладёт готовое решение в поле, `sample` читает
 * последнее готовое намерение либо отдаёт `undefined` — «ввода на этот тик нет».
 *
 * Единственный вход состояния мира — `ClientStep` своего клиента (BOT-3):
 * отфильтрованные персональные снапшоты и факты своего слота (`netcode`
 * NET-12..15). Ничего, кроме шага, мозг не получает ни при каком размещении
 * бота — в том числе когда бот собран в одном процессе с сервером.
 */
import type { ClientStep, InputSample } from '@game-mvp/net';
import type { BotProfile } from './profile.js';

/**
 * Кто именно этот мозг в матче. Слот приезжает сюда, потому что своя сущность в
 * персональном снапшоте опознаётся полем `Player.slot` (`tick-loop` TICK-5), а
 * узнаётся слот из `Welcome` собственного клиента — это его же отфильтрованный
 * поток, а не привилегия (BOT-3).
 */
export interface BotSelf {
  readonly playerId: string;
  readonly slot: number;
}

export interface BotBrain {
  /** Доставленный шаг клиента — наблюдение (BOT-3: только своё, фильтрованное). */
  observe(step: ClientStep): void;
  /** Синхронный съём намерения на тик; `undefined` — ввода нет (BOT-2). */
  sample(tick: number): InputSample | undefined;
  /** Освобождение ресурсов реализации (таймеры, воркеры мышления); необязателен. */
  dispose?(): void;
}

/**
 * Конструирование мозга (BOT-2, BOT-6): профиль поведения читается здесь, на
 * конструировании, и больше нигде — уровень сложности заводится документом, а
 * не правкой кода. Мира сервера в аргументах нет и быть не может (BOT-3).
 */
export type BotBrainFactory = (profile: BotProfile, self: BotSelf) => BotBrain;
