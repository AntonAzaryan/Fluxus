/**
 * Униформа шейдерного материала по имени — одна точка на весь рендер.
 *
 * Словарь униформ у `ShaderMaterial` объявлен с индексной подписью, поэтому по
 * типу «имени может не быть»: под `noUncheckedIndexedAccess` каждое обращение к
 * нему оптимистично. Там, где набор униформ объявляет ТОТ ЖЕ код, что их и
 * читает — сборка материала рядом, в том же модуле, — отсутствие имени есть
 * дефект сборки, а не состояние сцены: он называется отказом, а не молча
 * превращается в присваивание полю `undefined`.
 *
 * Униформа, которой у материала законно может не быть (её объявляет лишь одна
 * из вариаций программы — bloom выключен, LUT не доехал), читается обычной
 * проверкой на месте: этой функции там не место.
 */
import type * as THREE from 'three';

export function uniformOf(material: THREE.ShaderMaterial, name: string): THREE.IUniform {
  const uniform = material.uniforms[name];
  if (uniform === undefined) {
    throw new Error(`униформа "${name}" не объявлена сборкой материала`);
  }
  return uniform;
}
