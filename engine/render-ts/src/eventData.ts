/**
 * Полезная нагрузка события тика НА ВХОДНОЙ ГРАНИЦЕ рендера (REND-1).
 *
 * «Конверсия Q16.16 → float SHALL происходить на входе в рендер … и MUST NOT
 * происходить глубже. За этой границей fixed-point значений в рендере не
 * остаётся» — поэтому координатные поля события переводятся здесь, в точке
 * приёма, а не у потребителя. Раньше нагрузка копировалась полем в поле, и
 * деление на `FIXED_ONE` жило глубоко внутри подсистем: в ослаблении тряски
 * камеры расстоянием (`camera/director.ts`) и в точке события оболочек эффектов
 * и частиц (`subsystems/shellSupport.ts`).
 *
 * Перечень координатных полей — не догадка рендера о содержимом: тот же
 * перечень уже был конвенцией потребителей (точка мира `x`/`y`, вектор
 * направления `dirX`/`dirY` — `Extractor.aimYawOf`, `eventPointOf`,
 * `CameraDirector.falloff`), просто записан он был трижды, в местах деления.
 * Теперь он записан один раз и в одном месте — там же, где происходит перевод.
 * Прочие поля копируются как есть: ссылки на сущности (`EVENT_ENTITY_FIELDS`
 * ядра) — целые номера, а смысл остальных задаёт контент, и трогать их рендер
 * не вправе.
 *
 * Производителей события у рендера два, и оба зовут это отсюда: поток тиков
 * (`Extractor.copyEvents`) и канал сетевой оболочки, где факты приезжают с
 * провода (`client-ts/networkShell.ts`, SHELL-4). Третьего входа у событий нет:
 * документный продюсер (REND-11) событий не наполняет вовсе.
 */
import { FIXED_ONE } from '@fluxus/core';

/**
 * Координатные поля нагрузки события: мировая точка и вектор направления. Оба
 * приезжают из симуляции в Q16.16 (FP-1) и за эту границу уходят float'ами в
 * мировых единицах — как всё остальное в пакете рендера (REND-1).
 *
 * Наружу перечень не уходит: потребитель у него один — перевод ниже, а
 * опубликованный список звал бы читать нагрузку по именам полей где-то ещё,
 * то есть заводить второе место, знающее про координаты события.
 */
const FIXED_FIELDS: readonly string[] = ['x', 'y', 'dirX', 'dirY'];

/**
 * Копия нагрузки события с координатными полями, приведёнными к float. Копия, а
 * не правка на месте: нагрузка события ядра переживает `dispatch()` только
 * скопированной (OBS-3), а нагрузка провода принадлежит разобранному сообщению
 * и правкой на месте превратилась бы в величину, зависящую от того, сколько раз
 * её прочитали.
 */
export function renderEventData(
  data: Readonly<Record<string, number>>,
): Readonly<Record<string, number>> {
  const out: Record<string, number> = { ...data };
  for (const field of FIXED_FIELDS) {
    const value = out[field];
    if (value !== undefined) out[field] = value / FIXED_ONE;
  }
  return out;
}
