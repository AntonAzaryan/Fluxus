/**
 * Контракты рендера (REND-1..13). Рендер — внешний наблюдатель симуляции:
 * единственный вход ДАННЫХ СИМУЛЯЦИИ — `TickResult` через `RenderHost.onTick`,
 * единственный выход — сцена Three.js. Иного канала к идущему миру нет: мир
 * помимо `TickResult` не читается, мутирующие API не вызываются, зависимостью
 * ядра рендер не является. Ядро о рендере не знает.
 *
 * Несимуляционные входы у пакета есть, и их набор закрыт (REND-1):
 * presentation-ассеты через `AssetService` (манифест визуалов ASSET-6, карта
 * кривизны ASSET-7); сцена и сетка террейна при инициализации подсистем
 * (REND-8), в воркер-сборке доставленные хендшейком оболочки (SHELL-5);
 * документный набор инстансов (REND-11, `documentSource.ts`) — второй продюсер
 * presentation-состояния, взаимоисключающий с потоком тиков; набор
 * decoration-инстансов (REND-18, `decorations.ts`) — производная парного
 * presentation-документа сцены (`presentation-scene` PRES-1), действующая рядом
 * с любым продюсером, а не вместо него; локальный сэмпл ввода своего игрока
 * (`LocalInputSample` ниже) — вход единственной подсистемы превью каста
 * (REND-28); сужённый порт рендерера (`PostRendererLike` ниже, `FogRendererLike`
 * в `fog/contract.ts`) — вход подсистем, распоряжающихся проходами кадра, то
 * есть пост-обработки (REND-34) и тумана (FOW-7); конфиг рендера (шаг высоты
 * REND-7) и поза камеры (CAM-1). Ни один из них не ведёт обратно в мир и не
 * несёт данных, влияющих на симуляцию (ASSET-1).
 *
 * Все величины ПРЕЗЕНТАЦИОННОГО состояния здесь — float в мировых единицах.
 * Конверсия Q16.16 → float идёт
 * на входной границе и глубже не проникает (REND-1): у потока тиков — в
 * `extractor.ts` (состояние сущностей — в `copyEntity`, координатные поля
 * событий — в `copyEvents` через `eventData.ts`; тем же переводом входят факты
 * с провода в сетевой оболочке, SHELL-4), у прочих входов — в точке приёма
 * (`tileSize` и cliff-отрезки сетки в `subsystems/terrain.ts`,
 * `visualSurface.ts` и `camera/rig.ts`, точка прицела — в
 * `subsystems/abilityPreview.ts`).
 *
 * Двух мест это не касается, и оба названы своим именем в объявлении.
 * `LocalInputSample` — вход, а не состояние: точка приезжает ровно в той форме,
 * в какой уедет в мир, и конвертируется в точке приёма. `RenderEvent.data` —
 * нагрузка события: переведены её КООРДИНАТНЫЕ поля (`eventData.ts`), а смысл
 * и формат остальных задаёт контент, и рендер их не читает — они проезжают
 * насквозь к потребителям доставки (`match-hud` HUD-1), которым сцена их и
 * адресовала.
 * Обратной конверсии float → fixed в потоке рендера не существует:
 * квантование авторских величин с экрана делает редактор вызовом ядра, до
 * записи в документ и вне этого пакета (`editor` ED-1, ED-16).
 */
