/** Общий конфиг рендера, доступный всем подсистемам. */
export interface RenderConfig {
  /** Высота одного уровня террейна в мировых единицах — параметр рендера, не ядра (REND-7). */
  readonly heightStep: number;
  /**
   * Плотность разбиения клетки с кривизной: клетка с ненулевым узловым
   * смещением даёт `N × N` подклеток по визуальной поверхности (REND-9).
   * Такой же параметр рендера, как `heightStep`: цифру подбирает тот, кто
   * смотрит на арену, а не автор рендера. Клетка без кривизны остаётся одним
   * квадом при любом значении; не задан — `DEFAULT_CURVATURE_TESSELLATION`.
   */
  readonly curvatureTessellation?: number;
}

/**
 * Стартовая плотность разбиения. Четыре деления держат хорду билинейной дуги
 * амплитудой 7/16 шага в пределах нескольких процентов шага высоты — заметно
 * ниже порога, на котором глаз читает грань (REND-9).
 */
export const DEFAULT_CURVATURE_TESSELLATION = 4;

/** Что подсистема получает на инициализации (REND-8). */
export interface RenderContext {
  readonly scene: THREE.Scene;
  readonly assets: AssetService;
  readonly config: RenderConfig;
}

// -------------------------------------------------------- теневые кастеры

/**
 * Ярус теневого кастера: статический ярус рисуется в кэшированную карту и
 * перерисовывается только по событию, динамический — в покадровую. Ярус —
 * ПРОИЗВОДНАЯ ДАННЫХ, а не перечисление, которое кто-то проставляет вручную:
 * инстанс presentation-состояния (REND-11) динамичен всегда, decoration
 * (REND-18) — по наличию анимации у записи его вида (REND-4), геометрия
 * террейна (REND-7) статична.
 */
export type ShadowCasterTier = 'static' | 'dynamic';

/**
 * Фаза теневого прохода кадра: чья карта рисуется сейчас и, значит, чьи кастеры
 * подняты флагом. `none` — теней нет вовсе, `full` — оба яруса в одной карте,
 * `static` и `dynamic` — половины режима `hybrid` (REND-30).
 *
 * Словарь стоит здесь, рядом с ярусом кастера, а не внутри подсистемы: фазу
 * решает подсистема освещения, а называет её и печатает в дампе отладочный
 * источник (`render-debug` RDBG-7) — второго перечня этих имён быть не должно.
 */
export type ShadowPhase = 'none' | 'static' | 'dynamic' | 'full';

/**
 * Приёмник теневых кастеров: им подсистема-ВЛАДЕЛЕЦ объектов сообщает, к какому
 * ярусу относится нарисованное ею, а подсистема освещения решает, что с этим
 * делать в текущем режиме теней.
 *
 * Порт, а не прямая ссылка на подсистему освещения, по той же причине, по
 * которой источник визуальной поверхности приходит опцией (REND-9): подсистемы
 * не знают друг о друге, а общий объект им приносит сборка. Сцена без света
 * порта не передаёт вовсе, и ветки теней у владельцев объектов не работают.
 *
 * Регистрируется КОРЕНЬ нарисованного (узел детального яруса, группа батча,
 * меш чанка террейна), а не каждый меш: флаги `castShadow`/`receiveShadow`
 * расставляет приёмник обходом поддерева — он один знает режим и фазу.
 */
export interface ShadowCasterSink {
  /** Корень нарисованного и его ярус; повторный вызов переносит ярус. */
  setCaster(root: THREE.Object3D, tier: ShadowCasterTier): void;
  /** Корень ушёл из кадра: снятый инстанс, опустевший батч, пересобранный чанк. */
  dropCaster(root: THREE.Object3D): void;
  /**
   * Кэшированная карта статики устарела: сцена загрузилась, набор декораций
   * переподан (REND-18), сетка террейна правлена (REND-14). Перерисовка идёт
   * ближайшим кадром (ED-15), а не здесь.
   */
  invalidateStatic(): void;
}

// ------------------------------------------ носители контактных пятен (blob)

/**
 * Позиция носителя контактного пятна (REND-30, режим `blob`) — переиспользуемая
 * запись, а не новый объект на носителя на кадр: кадровый путь читает её на
 * каждом носителе сцены (REND-26).
 *
 * Ориентации здесь нет намеренно: пятно — ЗНАК ПОЗИЦИИ, а не силуэт позы
 * (REND-30), и поворачивать круг вокруг вертикали не за чем.
 */
export interface BlobCasterPose {
  x: number;
  y: number;
  /** Точка контакта с поверхностью — опора инстанса, а не его центр. */
  z: number;
}

/**
 * Носитель контактного пятна (REND-30): инстанс ДИНАМИЧЕСКОГО яруса кастеров.
 * Регистрирует его владелец инстанса — тот же, что объявляет ярус кастера, — а
 * подсистема освещения решает, рисовать ли пятна вообще (это свойство режима).
 *
 * Порт per-instance, а не реестр корней: корень батчевого яруса (REND-20) один
 * на десятки инстансов, и пятно по нему вышло бы одно на весь батч.
 */
export interface BlobCaster {
  /**
   * Радиус пятна в мировых единицах — ПРОИЗВОДНАЯ ДАННЫХ ИНСТАНСА (REND-30):
   * горизонтальный габарит вида из манифеста, тот же источник, что у отсечения
   * и выбора уровня детализации (REND-21, REND-22). НЕ readonly: переподача
   * манифеста (REND-17) правит габарит живого носителя.
   */
  radius: number;
  /**
   * Позиция носителя в переиспользуемую запись; `false` — в кадре его нет
   * (инстанс ещё не получил позы либо отсечён), и пятну взяться неоткуда.
   */
  pose(out: BlobCasterPose): boolean;
}

/**
 * Приёмник носителей контактных пятен (REND-30) — порт подсистемы освещения по
 * образцу `ShadowCasterSink` и `LightCarrierSink`. Необязателен: сцена, чьё
 * освещение его не несёт (тестовый двойник), просто не получает пятен.
 */
export interface BlobCasterSink {
  /** Носитель появился; повторный вызов с тем же носителем последствий не имеет. */
  setBlobCaster(caster: BlobCaster): void;
  /** Носитель ушёл: снятый инстанс либо инстанс, ставший статическим кастером. */
  dropBlobCaster(caster: BlobCaster): void;
  /**
   * Позы кадра поставлены владельцем инстансов — пятна можно писать. Зовётся в
   * конце его `updateFrame`, и это ЕДИНСТВЕННЫЙ момент кадра, когда поза
   * инстанса и его видимость уже посчитаны (REND-3, REND-21).
   *
   * Отдельная точка, а не запись пятен в собственном `updateFrame` подсистемы
   * освещения, ровно потому, что подсистема освещения зарегистрирована РАНЬШЕ
   * владельца инстансов (порт объявляет владелец порта, REND-8): её кадр идёт
   * первым, и пятна отставали бы на кадр — а REND-30 требует, чтобы пятно
   * следовало позиции инстанса на КАЖДОМ кадре.
   */
  blobCastersPosed(): void;
}

// -------------------------------------------- носители локального света

/**
 * Мировая поза носителя локального света (REND-33) — то, чем подсистема
 * освещения ставит источник в кадре. Переиспользуемая запись, а не новый объект
 * на носителя на кадр: кадровый путь читает её на каждом носителе сцены.
 *
 * Ориентация приезжает вместе с позицией потому, что смещение опоры света и
 * направление конуса (`assets` ASSET-16) заданы В ОПОРЕ ИНСТАНСА: факел,
 * повёрнутый к стене, светит с чаши, а не из точки, куда чаша смотрела бы у
 * неповёрнутого. Масштаба здесь нет — величины блока мировые (ASSET-16).
 */
export interface LightCarrierPose {
  x: number;
  y: number;
  z: number;
  /** Кватернион ориентации инстанса `(x, y, z, w)` — тот же, что у его позы. */
  qx: number;
  qy: number;
  qz: number;
  qw: number;
}

/**
 * Носитель локального света (REND-33): инстанс записи, чей вид несёт блок
 * `light` (`assets` ASSET-16). Регистрирует его ВЛАДЕЛЕЦ инстанса — трансформ и
 * жизненный цикл принадлежат ему, — а подсистема освещения решает, какие из
 * носителей светят в этом кадре.
 */
export interface LightCarrier {
  /**
   * Ключ носителя — тай-брейк отбора активных источников (REND-33): ключ записи
   * манифеста плюс порядковый номер инстанса в его наборе. От кадра и от
   * порядка обхода реестра он не зависит, поэтому повтор того же кадра отбирает
   * те же источники (`editor` ED-22).
   *
   * «Устойчив» он в пределах поданного набора, а не навсегда: номер размещения
   * выдаёт набор инстансов при сведении (REND-11, REND-18), и пересозданное
   * размещение получает новый — за сессию правки тай-брейк между носителями с
   * в точности равными оценками вправе перевернуться. Подробнее — у владельца
   * ключа (`subsystems/models.ts`, `lightCarrierKey`).
   */
  readonly key: string;
  /**
   * Разобранный блок записи (ASSET-16). НЕ readonly: переподача манифеста
   * (REND-17) правит числа света живого носителя — снятия и повторной
   * регистрации это не требует, свет виден не позже следующего кадра (ED-15).
   */
  light: ResolvedVisualLight;
  /**
   * Поза носителя в переиспользуемую запись; `false` — в кадре его нет
   * (инстанс ещё не получил позы), и светить ему неоткуда.
   */
  pose(out: LightCarrierPose): boolean;
}

/**
 * Приёмник носителей локального света (REND-33) — порт подсистемы освещения по
 * образцу `ShadowCasterSink`: владелец инстансов объявляет носителя при
 * создании инстанса записи с блоком `light` и снимает при его исчезновении.
 *
 * Порт, а не чтение presentation-состояния самим освещением: трансформы и
 * жизненный цикл инстансов принадлежат их подсистемам (REND-3), и второй
 * просмотр состояния дублировал бы их логику. Направление порта задаёт и
 * порядок сноса (REND-31): владелец порта зарегистрирован раньше и снесён будет
 * позже, поэтому носитель успевает сняться сам.
 */
export interface LightCarrierSink {
  /** Носитель появился; повторный вызов с тем же носителем последствий не имеет. */
  setLightCarrier(carrier: LightCarrier): void;
  /** Носитель ушёл из кадра: снятый инстанс либо снятый переподачей блок света. */
  dropLightCarrier(carrier: LightCarrier): void;
}

/**
 * Порты подсистемы освещения, которые нужны владельцу инстансов: приёмник
 * теневых кастеров (REND-30), приёмник носителей локального света (REND-33) и
 * приёмник носителей контактных пятен (REND-30, режим `blob`). Владелец у всех
 * один, и потребители подают его ОДНОЙ ссылкой — второй опции сборки не
 * заводится: она заставила бы каждого собирающего писать ту же ссылку дважды, а
 * вьюпорт редактора получил бы локальный свет только правкой своего кода
 * (`editor` ED-1 требует ровно обратного).
 *
 * Приёмники носителей необязательны: сцена, чьё освещение их не несёт (сборка
 * старше REND-33, тестовый двойник), просто не получает ни локального света, ни
 * пятен — как сцена без света не получает флагов теней.
 */
export type LightingSink = ShadowCasterSink &
  Partial<LightCarrierSink> &
  Partial<BlobCasterSink>;

// -------------------------------------------- пост-обработка кадра (REND-34)

/**
 * Рендерер глазами полноэкранного прохода — структурный минимум
 * `THREE.WebGLRenderer`: подсистемы не требуют живого WebGL в тестах, а в сборке
 * это он и есть.
 *
 * Реестр расширений необязателен по той же причине: тестовый двойник его не
 * несёт, и спрашивать тогда нечего — цепочка идёт полным путём (design D6).
 */
export interface PostRendererLike {
  render(scene: THREE.Object3D, camera: THREE.Camera): void;
  setRenderTarget(target: THREE.WebGLRenderTarget | null): void;
  getDrawingBufferSize(target: THREE.Vector2): THREE.Vector2;
  readonly extensions?: { has(name: string): boolean };
}

/**
 * Вход маскирующего прохода (FOW-7, design D2): ЦВЕТ — выход сведения цепочки
 * пост-обработки, ГЛУБИНА — глубина сцены, по которой маска восстанавливает
 * мировые координаты фрагмента. Ровно две текстуры: порт узкий намеренно —
 * пересечение владений тумана и пост-обработки самая тонкая точка обеих.
 */
export interface ScenePostFrame {
  readonly color: THREE.Texture;
  /**
   * `null` — у цели кадра не оказалось текстуры глубины. Цепочка заводит её
   * всегда, но тип цели three её отсутствие допускает, и маскирующий проход
   * обязан такое пережить (кадр без реконструкции мировых XY), а не отказать.
   */
  readonly depth: THREE.Texture | null;
}

/**
 * Пост-обработка кадра глазами подсистемы тумана (REND-34, FOW-7, design D2).
 *
 * Порт, а не прямая ссылка на подсистему: подсистемы не знают друг о друге, а
 * общий объект им приносит сборка — тот же приём, что у приёмника теневых
 * кастеров (`ShadowCasterSink`). Направление задаёт и порядок сноса (REND-31):
 * пост-обработка регистрируется РАНЬШЕ тумана и переживает его снос.
 *
 * Неактивная цепочка (`active === false`) означает «делай как до REND-34»:
 * туман рисует сцену сам, в свою LDR-цель, и ни одного прохода цепочки в кадре
 * нет.
 */
export interface ScenePostSource {
  /** Есть ли у цепочки работа: false — потребитель рисует сцену сам. */
  readonly active: boolean;
  /**
   * Кадр цепочки на экран: маски нет, и маскирующего прохода за ним не будет —
   * кадр равен ровно проходам REND-34 (FOW-7).
   */
  renderToScreen(renderer: PostRendererLike, camera: THREE.Camera): void;
  /**
   * Кадр цепочки в цель: возвращает вход маскирующего прохода. Цель кадра
   * рендерера при возврате — канвас: следующий проход чужой.
   */
  renderToTexture(renderer: PostRendererLike, camera: THREE.Camera): ScenePostFrame;
}

// ------------------------------------------------------- ручки качества

/**
 * Значение ручки качества (`render-quality` QUAL-1): число (разрешение, порог,
 * множитель), строка (перечислимый выбор — ярус представления) либо флаг
 * (вкл/выкл прохода). Пресет — JSON-документ из таких значений, и ничего, чего
 * JSON не выражает, в нём не бывает.
 */
export type QualityValue = number | string | boolean;

/**
 * Как пресет действует на ручку (QUAL-1, design D3):
 *
 * - `ceiling` — ПОТОЛОК над авторским значением: действующее = min(авторское,
 *   значение ручки). Так подчиняются пресету параметры, чей источник — контент
 *   (разрешение маски тумана из секции `fog`, FOW-10): пресет вправе ограничить
 *   картинку сверху, но MUST NOT поднять её выше авторской и MUST NOT править
 *   сам документ;
 * - `value` — значение применяется НАПРЯМУЮ: у ручки авторского источника нет
 *   (множитель плотности частиц, ярус представления по умолчанию), и спорить
 *   пресету не с чем.
 */
export type QualityKnobSemantics = 'ceiling' | 'value';

/**
 * Объявление одной ручки качества (QUAL-1). Имя ОБЯЗАНО начинаться с имени
 * подсистемы-владельца (`fog.maskResolution`): неймспейс делает реестр плоским,
 * а принадлежность ручки — читаемой в документе пресета без словаря.
 *
 * Диапазон задаётся либо числовыми границами (`min`/`max`, включительно), либо
 * перечнем допустимых значений (`values`) — ровно одним из двух: ручка, чей
 * набор значений закрыт, диапазоном не описывается, и наоборот.
 */
export interface QualityKnob {
  /** Полное имя: `<подсистема>.<ручка>`. */
  readonly name: string;
  /**
   * Стоимостная ось, которой ручка правит (QUAL-1), — прозой: её печатает
   * отчёт контроллера и читает ревью, решая, тот ли рычаг заведён.
   */
  readonly cost: string;
  readonly semantics: QualityKnobSemantics;
  /**
   * Документированное значение по умолчанию (QUAL-1): его получает подсистема,
   * когда документ пресета ручку не называет. У ручки-потолка умолчание —
   * `Number.POSITIVE_INFINITY`, то есть «потолка нет, действует авторское
   * значение»; диапазону оно намеренно не подчиняется — диапазон описывает то,
   * что вправе написать АВТОР ПРЕСЕТА, а не отсутствие ограничения.
   */
  readonly default: QualityValue;
  /** Нижняя граница числовой ручки, включительно. */
  readonly min?: number;
  /** Верхняя граница числовой ручки, включительно. */
  readonly max?: number;
  /** Закрытый перечень значений — альтернатива числовому диапазону. */
  readonly values?: readonly QualityValue[];
}

/**
 * Декларация подсистемы в реестре качества (QUAL-1, QUAL-3; design D1).
 * Центрального перечня ручек в коде нет: реестр СОБИРАЕТСЯ из деклараций при
 * регистрации подсистем, и фича без декларации рычага не имеет — это видно
 * в ревью её регистрации, а не выясняется на слабом устройстве.
 *
 * QUAL-3 симметричен: подсистема, чья стоимость от объёма контента не растёт,
 * объявляет пустой список ручек и НАЗЫВАЕТ причину в `constantCost`. «Ручек
 * нет» и «объявлено, что стоимость константна» обязаны различаться, поэтому
 * пустой список без причины контроллер отвергает.
 */
export interface QualityDeclaration {
  /** Имя подсистемы-владельца — неймспейс её ручек (`RenderSubsystem.name`). */
  readonly subsystem: string;
  readonly knobs: readonly QualityKnob[];
  /** Почему стоимость константна (QUAL-3); обязательно при пустом списке ручек. */
  readonly constantCost?: string;
}

/**
 * Значения ручек, доставляемые подсистеме: ключ — ПОЛНОЕ имя ручки, как она
 * себя объявила. Подсистема получает только свои ручки (design D2) и читает их
 * по тем же константам, которыми объявляла.
 */
export type QualityValues = ReadonlyMap<string, QualityValue>;

/** Документ пресета (QUAL-1): «имя ручки → значение», политика поверх механизма. */
export type QualityPreset = Readonly<Record<string, QualityValue>>;

/**
 * Контракт подсистемы рендера (REND-8): `syncTick` и `updateFrame` вызываются
 * в порядке регистрации. Подсистема владеет своими сценовыми объектами и
 * кэшами; добавление новой подсистемы не требует правок существующих.
 */
export interface RenderSubsystem {
  readonly name: string;
  init(ctx: RenderContext): void;
  /**
   * Обратная операция к `init` (REND-31): подсистема отдаёт ресурсы GPU,
   * которыми владеет, — геометрии, материалы, текстуры, цели отрисовки. Без неё
   * время жизни владения (REND-8) равно времени жизни процесса, а вьюпорт
   * авторинга живёт короче: открытие другой сцены сносит прежний кадр (ED-15).
   *
   * Метод необязателен, и его отсутствие дефектом не является: подсистеме,
   * ничем в GPU не владеющей, освобождать нечего — то же различие, что у
   * отладочных источников (REND-27), и в отличие от объявления стоимостной
   * ручки (QUAL-3). Зовётся он событием сноса, а не кадром, и счётных величин
   * стоимости (PERF-2, PERF-3) не двигает.
   *
   * Порядок сноса обратен порядку регистрации, и это несущее: подсистема
   * вправе сообщить владельцу полученного порта (`ShadowCasterSink`), что её
   * объекты ушли, — владелец зарегистрирован раньше и снесён будет позже.
   * Освобождать ресурсы соседа она при этом не должна: своё отдаёт каждый сам.
   */
  dispose?(): void;
  /** Синхронизация с тиком: view скопирован и валиден до следующего syncTick. */
  syncTick(view: TickView): void;
  /**
   * Полный набор decoration-инстансов (REND-18) — третий набор рядом с
   * продюсерами presentation-состояния, а не второй `syncTick`. Отдельный вход
   * потому, что набор с продюсерами СОСУЩЕСТВУЕТ: смена продюсера гасит
   * presentation-состояние (REND-11), а декорации гасить MUST NOT — и приди
   * они тем же входом, гасились бы вместе с ним.
   *
   * Метод необязателен: подсистема, которой инстансы не принадлежат (террейн,
   * наложения), декораций не рисует и знать о них не должна.
   */
  syncDecorations?(entities: ReadonlyMap<EntityId, EntityView>): void;
  /**
   * Покадровое обновление: `dt` — секунды с прошлого кадра СО ЗНАКОМ хода мира
   * (REND-2, REND-25), `alpha` — доля тика [0..1], `realDt` — те же секунды по
   * часам главного потока, без знака и без остановки в замороженном мире.
   *
   * Мир доигрывает `dt`; `realDt` берут только величины самой картинки, которым
   * режим мира не указ, — счётчик кадров HUD (HUD-5). Параметр третий и
   * необязательный к объявлению: подсистема, которой он не нужен, объявляет два
   * прежних аргумента и ничего не знает о нём.
   */
  updateFrame(dt: number, alpha: number, realDt: number): void;
  /**
   * Декларация ручек качества (`render-quality` QUAL-1, QUAL-3) — расширение
   * контракта REND-8 точкой объявления, а не отдельным реестром: спрашивают её
   * один раз, при регистрации подсистемы.
   *
   * Метод необязателен технически (подсистема вне сцены с контроллером качества
   * его не увидит), но не по норме: QUAL-3 требует от подсистемы с растущей
   * стоимостью либо ручки, либо явного объявления константности, и «метода нет»
   * — это ни то, ни другое.
   */
  quality?(): QualityDeclaration;
  /**
   * Значения объявленных ручек (QUAL-1, design D2): доставляются при
   * регистрации подсистемы и при смене пресета в рантайме — СОБЫТИЯМИ, а не
   * кадром. Пересборки рендера смена не требует: подсистема
   * применяет значения на живых объектах, как туман применяет конфиг (FOW-10).
   *
   * Метода нет у подсистемы, объявившей стоимость константной: раздавать ей
   * нечего.
   */
  applyQuality?(values: QualityValues): void;
  /**
   * Объявление отладочных источников (`render-debug` RDBG-1) — то же расширение
   * контракта REND-8 точкой объявления (REND-27), каким стала декларация ручек
   * качества: спрашивают его один раз, при регистрации подсистемы.
   *
   * Данные подсистемы принадлежат ей, и источник, показывающий её маску, её
   * инстансы или её сетку, пишется там, где эти данные есть; отладочный слой при
   * этом не знает о внутреннем устройстве подсистемы ничего сверх пробы
   * (RDBG-2). Каждый `id` обязан начинаться с имени подсистемы — неймспейс
   * владельца тот же, что у ручек качества.
   *
   * Объявление НЕОБЯЗАТЕЛЬНО и его отсутствие дефектом не является (REND-27) —
   * в отличие от объявления стоимостной ручки (QUAL-3): подсистеме бывает нечего
   * показывать, а вот стоимость у неё есть всегда.
   */
  debugSources?(): readonly DebugSource[];
}

// ------------------------------------------------------------ конфиг хоста

/**
 * Конфиг хоста рендера. Все входы СБОРКИ плоской формы (`ExtractorConfig`)
 * входят сюда как есть и уезжают в `Extractor` без пересказа: второй список тех
 * же полей разошёлся бы с первым молча — новый вход сборки появлялся бы у
 * экстрактора и не доезжал бы до хоста. Здесь остаётся только то, чего у
 * сборки нет: шаг тика, разделяемая сцена и часы буфера видов.
 */
export interface RenderHostConfig extends ExtractorConfig {
  /** Длительность тика в секундах — знаменатель альфы интерполяции (REND-2). */
  readonly tickSeconds: number;
  /**
   * Сцена подсистем, разделяемая с другим продюсером presentation-состояния
   * (REND-11): её передаёт редактор, чтобы вьюпорт и превью (ED-9) кормили одни
   * и те же подсистемы. По умолчанию хост заводит свою — в игровом клиенте
   * второго продюсера не существует.
   */
  readonly stage?: PresentationStage;
  /** Скачок позиции за тик больше этого (мировых единиц) — телепорт, snap (REND-2). */
  readonly snapDistance?: number;
  /** Часы в миллисекундах; по умолчанию performance.now — параметр ради тестов. */
  readonly clock?: () => number;
}
