// ------------------------------------------------- presentation-состояние

/**
 * Presentation-срез одной сущности: два последних тика для интерполяции
 * (REND-2) плюс производные признаки для анимаций (REND-4, REND-5).
 * Объект стабилен на всё время жизни сущности — подсистемы могут держать
 * ссылку; мутирует его продюсер presentation-состояния и только он: поток
 * тиков — в `ViewBuffer.apply` из `RenderHost.onTick`, документный набор —
 * в `DocumentSource.apply` (REND-11). Подсистеме, который из них, не видно.
 */
export interface EntityView {
  readonly id: EntityId;
  /** Визуальный тип (ключ манифеста визуалов) либо null — сущность не рисуется. */
  readonly kind: string | null;
  /** Позиция предыдущего тика. */
  prevX: number;
  prevY: number;
  /** Позиция последнего тика. */
  currX: number;
  currY: number;
  /** Уровень террейна под сущностью на тех же двух тиках (TERR-4 производное). */
  prevLevel: number;
  currLevel: number;
  /** Разрыв непрерывности в этом тике (спавн, телепорт, rewind): рисовать без интерполяции. */
  snap: boolean;
  /** Появилась в этом тике. */
  spawned: boolean;
  /** Скорость выше порога на последнем тике — состояние `move` (REND-4). */
  moving: boolean;
  /**
   * Состояние машины локомоушена на последнем тике (`LOCOMOTION_*` ядра,
   * LOC-3): из него берётся состояние анимации манёвра (REND-4).
   */
  motion: number;
  /**
   * То же состояние на ПРЕДЫДУЩЕМ доставленном тике — паре к `prevMotionPhase`.
   * Держится потому, что высота дуги задаётся на вид манёвра (REND-12): вклад
   * прошлого тика обязан считаться высотой ТОГО манёвра, иначе тик приземления
   * (манёвра уже нет) обнулял бы спуск скачком, а переход «прыжок → уклон»
   * смешивал бы высоты двух видов — ровно то, что REND-12 запрещает.
   */
  prevMotion: number;
  /**
   * Фаза манёвра на тех же двух тиках, что позиция, — доля пройденных тиков
   * манёвра; `NaN` — манёвра на этом тике не было. Вход дуги манёвра (REND-12).
   */
  prevMotionPhase: number;
  currMotionPhase: number;
  /**
   * Фаза полёта — доля пройденного пути от нуля к единице (REND-12). Вход
   * полётной дуги; `NaN` — фазы нет, и дуги не будет независимо от манифеста:
   * рендер фазу MUST NOT вычислять и MUST NOT выдумывать. Отсутствие выражено
   * `NaN`, а не отсутствием поля: так же, как у фазы манёвра и у курса, — одно
   * представление «нет значения» на всю плоскую форму. Заполняет её сборка
   * воркера (`client-shell` SHELL-2), поток тиков; наборы инстансов (REND-11,
   * REND-18) поля не касаются — полёта у размещённого объекта не бывает.
   */
  flightPhase: number;
  /**
   * Персональная шкала времени сущности (`time-system` TIME-2) последнего
   * доставленного тика — множитель её часов презентации (REND-38): им идут
   * фазы клипов обоих ярусов (REND-20) и шаг эмиттеров её оболочек (REND-24).
   * Единица — обычный темп: сущность без компонента шкалы (TIME-3) и любой
   * размещённый объект наборов инстансов (REND-11, REND-18) едут ею.
   *
   * Пары для интерполяции у неё нет намеренно: плавность даёт tween самой ауры
   * на стороне симуляции, и вторая, кадровая, была бы сглаживанием сглаженного.
   * Режиму мира шкала ПОДЧИНЕНА, а не заменяет его (REND-25): направление и ход
   * задаёт `FrameTiming.dt`, шкала — только множитель.
   */
  timeScale: number;
  /**
   * Именованные геймплейные статы сущности (`match-hud` HUD-8): hp, оставшиеся
   * тики кулдауна, счёт смертей — что объявила конфигурация сборки воркера, то
   * и едет. Имена принадлежат контенту, и смысла им ни рендер, ни HUD не
   * придают; стата, которого у сущности нет, в словаре НЕТ — «нет данных» и
   * «ноль» обязаны различаться.
   *
   * Словарь принадлежит продюсеру и переиспользуется между доставками, как и
   * сама запись: потребитель, удерживающий значение между тиками, копирует его.
   */
  stats?: ReadonlyMap<string, number>;
  /** Override уровня (TERR-4): сущность не «на поверхности», наклон не применяется (REND-10). */
  levelOverride: boolean;
  /** Последний курс движения, радианы; сохраняется, пока сущность стоит. */
  facingYaw: number;
  /** Направление последнего каста/атаки, радианы; null — цель протухла (REND-5). */
  aimYaw: number | null;
  /**
   * Битовая маска состояний сущности: бит i — присутствие i-й компоненты из
   * `stateComponents` конфига Extractor'а. Потребитель — длящиеся эффекты
   * камеры (CAM-6, ASSET-8).
   */
  states: number;
  /**
   * Клип, назначенный набором инстансов (REND-11): играет зацикленно поверх
   * состояния. `undefined` — клип производен от состояния сущности (REND-4);
   * поток тиков поле не заполняет никогда. `undefined` здесь ЗНАЧАЩЕЕ: запись
   * инстанса переиспользует ту же запись между наборами (REND-3), и снятый в
   * документе клип гасится записью `undefined`, а не пропуском присваивания —
   * пропуск оставил бы клип прежнего набора.
   */
  clip?: string | undefined;
  /**
   * Скин, назначенный набором инстансов (REND-11): смена обновляет материалы
   * существующего инстанса (REND-6). `undefined` — скином правит потребитель
   * (`ModelsSubsystem.setSkin`), и поток тиков поле не заполняет. Как и у
   * `clip`, `undefined` — рабочее значение: им набор снимает скин с записи,
   * которую он же и переиспользует.
   */
  skin?: string | undefined;
  /**
   * Множитель масштаба поверх масштаба записи манифеста (REND-11); `undefined`
   * — масштаб целиком из записи (ASSET-6).
   */
  scale?: number | undefined;
  /**
   * Поверхность меша входит в единое поле высот (REND-9) — флаг записи
   * decoration парного документа (PRES-2, REND-18). Заполняет только набор
   * декораций; продюсеры presentation-состояния поля не касаются — walkable
   * у сущностей мира не бывает, и `undefined` с false неразличимы.
   */
  walkable?: boolean | undefined;
}

/** Копия события тика: переживает `dispatch()`, в отличие от view ядра (OBS-3). */
export interface RenderEvent {
  readonly type: string;
  /** Тик, в котором событие произошло: при доставке каналом оболочки view может нести события нескольких тиков (SHELL-4). */
  readonly tick?: number;
  /**
   * Полезная нагрузка события — как её эмитировала система, но координатные
   * поля (`x`/`y`, `dirX`/`dirY`) уже приведены к float в мировых единицах на
   * входной границе (REND-1, `eventData.ts`). Прочие поля копируются как есть:
   * ссылки на сущности — целые номера, а смысл остальных задаёт контент.
   */
  readonly data: Readonly<Record<string, number>>;
}

/**
 * Presentation-состояние, передаваемое подсистемам в `syncTick`. Владеет им
 * продюсер, который его наполнил (REND-11): `RenderHost`/`ViewBuffer` у потока
 * тиков, `DocumentSource` у документного набора. В отличие от `TickResult`
 * ядра, данные скопированы и валидны до следующего `syncTick`.
 *
 * Поля, производные от тика (`events`, `freshEvents`, `snapAll`, `floorBits`),
 * документный продюсер не наполняет ничем: интерполяции, событий и фильтра
 * видимости в режиме правки нет (REND-11).
 */
export interface TickView {
  tick: number;
  mode: WorldMode;
  isReplay: boolean;
  /** Разрыв непрерывности всего мира (rewind/смена режима): всем сущностям snap (REND-2). */
  snapAll: boolean;
  /** Первый честный проход тика: события можно проигрывать (OBS-5 — дедуп на потребителе). */
  freshEvents: boolean;
  readonly entities: ReadonlyMap<EntityId, EntityView>;
  /**
   * Имена статов доставки (`match-hud` HUD-8) — словарь конфигурации сборки
   * воркера, общий на все сущности; пустой список — статов сборка не объявила.
   * Потребители биндятся на ИМЕНА: индексы — дело канала, и наружу их нет.
   */
  statNames: readonly string[];
  events: readonly RenderEvent[];
  /** Зеркало карты пола (1 — пол есть), row-major; null — сцена без террейна. */
  floorBits: Uint8Array | null;
  /** Клетки, чей пол изменился в этом тике (TERR-6 → REND-7). */
  floorChangedCells: readonly number[];
}

// ------------------------------------------- локальный сэмпл ввода (REND-1)

/**
 * Точка прицела локального сэмпла — **Q16.16**, ровно в той форме, в какой она
 * уедет в мир обычным `InputFrame` (`tick-loop` TICK-2, `input-devices` INP-3).
 * Единственная величина пакета, приходящая fixed-point'ом помимо потока тиков:
 * квантование живёт в единственной точке слоя ввода (INP-3), и рендер получает
 * ЕЁ ЖЕ, а не второе округление той же точки — иначе превью обещало бы игроку
 * не ту точку, по которой решит тик. Конверсия во float — в точке приёма
 * (`AbilityPreviewSubsystem.applyLocalInput`), глубже fixed-point не идёт
 * (REND-1).
 */
export interface LocalAimPoint {
  readonly x: number;
  readonly y: number;
}

/**
 * Локальный сэмпл ввода своего игрока (REND-1, `input-devices` INP-1) — ещё не
 * подтверждённое прицеливание ТЕКУЩЕГО КАДРА, перечисленный несимуляционный
 * вход и вход единственной подсистемы превью каста (REND-28).
 *
 * Он в закрытом наборе потому, что показывать обязан то, чего в `TickResult`
 * нет по построению: до подтверждения фазы в симуляции не происходит ничего
 * (`ability-system` ABIL-5). Каналом в мир он при этом не становится: в мир тот
 * же сэмпл едет своим путём — `InputFrame` через обратный канал оболочки
 * (`client-shell` SHELL-6), — а рендер его только читает и ничего не пишет.
 *
 * Сущность своего игрока — часть сэмпла, а не отдельный вход: сэмпл и есть
 * «прицеливание ВОТ ЭТОГО игрока», и только его состояние превью читает
 * (`netcode` NET-15). Битов действий в сэмпле нет намеренно: идёт ли каст и
 * сколько шагов подтверждено, говорит ДОСТАВЛЕННОЕ состояние, а бит
 * подтверждения — вход мира, а не картинки.
 */
export interface LocalInputSample {
  /** Сущность своего игрока — владелец слотов, чьё превью рисуется (NET-15). */
  readonly entity: EntityId;
  /** Точка прицела кадра в Q16.16; null — источник точкой не владел (INP-1). */
  readonly target: LocalAimPoint | null;
}

