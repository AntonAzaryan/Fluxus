// ------------------------------------------------------- ручки качества

/**
 * Значение ручки качества (`render-quality` QUAL-1): число (разрешение, порог,
 * множитель), строка (перечислимый выбор — ярус представления) либо флаг
 * (вкл/выкл прохода). Пресет — JSON-документ из таких значений, и ничего, чего
 * JSON не выражает, в нём не бывает.
 */
export type QualityValue = number | string | boolean;

/**
 * Как пресет действует на ручку (QUAL-1, design D3):
 *
 * - `ceiling` — ПОТОЛОК над авторским значением: действующее = min(авторское,
 *   значение ручки). Так подчиняются пресету параметры, чей источник — контент
 *   (разрешение маски тумана из секции `fog`, FOW-10): пресет вправе ограничить
 *   картинку сверху, но MUST NOT поднять её выше авторской и MUST NOT править
 *   сам документ;
 * - `value` — значение применяется НАПРЯМУЮ: у ручки авторского источника нет
 *   (множитель плотности частиц, ярус представления по умолчанию), и спорить
 *   пресету не с чем.
 */
export type QualityKnobSemantics = 'ceiling' | 'value';

/**
 * Объявление одной ручки качества (QUAL-1). Имя ОБЯЗАНО начинаться с имени
 * подсистемы-владельца (`fog.maskResolution`): неймспейс делает реестр плоским,
 * а принадлежность ручки — читаемой в документе пресета без словаря.
 *
 * Диапазон задаётся либо числовыми границами (`min`/`max`, включительно), либо
 * перечнем допустимых значений (`values`) — ровно одним из двух: ручка, чей
 * набор значений закрыт, диапазоном не описывается, и наоборот.
 */
export interface QualityKnob {
  /** Полное имя: `<подсистема>.<ручка>`. */
  readonly name: string;
  /**
   * Стоимостная ось, которой ручка правит (QUAL-1), — прозой: её печатает
   * отчёт контроллера и читает ревью, решая, тот ли рычаг заведён.
   */
  readonly cost: string;
  readonly semantics: QualityKnobSemantics;
  /**
   * Документированное значение по умолчанию (QUAL-1): его получает подсистема,
   * когда документ пресета ручку не называет. У ручки-потолка умолчание —
   * `Number.POSITIVE_INFINITY`, то есть «потолка нет, действует авторское
   * значение»; диапазону оно намеренно не подчиняется — диапазон описывает то,
   * что вправе написать АВТОР ПРЕСЕТА, а не отсутствие ограничения.
   */
  readonly default: QualityValue;
  /** Нижняя граница числовой ручки, включительно. */
  readonly min?: number;
  /** Верхняя граница числовой ручки, включительно. */
  readonly max?: number;
  /** Закрытый перечень значений — альтернатива числовому диапазону. */
  readonly values?: readonly QualityValue[];
}

/**
 * Декларация подсистемы в реестре качества (QUAL-1, QUAL-3; design D1).
 * Центрального перечня ручек в коде нет: реестр СОБИРАЕТСЯ из деклараций при
 * регистрации подсистем, и фича без декларации рычага не имеет — это видно
 * в ревью её регистрации, а не выясняется на слабом устройстве.
 *
 * QUAL-3 симметричен: подсистема, чья стоимость от объёма контента не растёт,
 * объявляет пустой список ручек и НАЗЫВАЕТ причину в `constantCost`. «Ручек
 * нет» и «объявлено, что стоимость константна» обязаны различаться, поэтому
 * пустой список без причины контроллер отвергает.
 */
export interface QualityDeclaration {
  /** Имя подсистемы-владельца — неймспейс её ручек (`RenderSubsystem.name`). */
  readonly subsystem: string;
  readonly knobs: readonly QualityKnob[];
  /** Почему стоимость константна (QUAL-3); обязательно при пустом списке ручек. */
  readonly constantCost?: string;
}

/**
 * Значения ручек, доставляемые подсистеме: ключ — ПОЛНОЕ имя ручки, как она
 * себя объявила. Подсистема получает только свои ручки (design D2) и читает их
 * по тем же константам, которыми объявляла.
 */
export type QualityValues = ReadonlyMap<string, QualityValue>;

/** Документ пресета (QUAL-1): «имя ручки → значение», политика поверх механизма. */
export type QualityPreset = Readonly<Record<string, QualityValue>>;

/**
 * Контракт подсистемы рендера (REND-8): `syncTick` и `updateFrame` вызываются
 * в порядке регистрации. Подсистема владеет своими сценовыми объектами и
 * кэшами; добавление новой подсистемы не требует правок существующих.
 */
export interface RenderSubsystem {
  readonly name: string;
  init(ctx: RenderContext): void;
  /** Синхронизация с тиком: view скопирован и валиден до следующего syncTick. */
  syncTick(view: TickView): void;
  /**
   * Полный набор decoration-инстансов (REND-18) — третий набор рядом с
   * продюсерами presentation-состояния, а не второй `syncTick`. Отдельный вход
   * потому, что набор с продюсерами СОСУЩЕСТВУЕТ: смена продюсера гасит
   * presentation-состояние (REND-11), а декорации гасить MUST NOT — и приди
   * они тем же входом, гасились бы вместе с ним.
   *
   * Метод необязателен: подсистема, которой инстансы не принадлежат (террейн,
   * наложения), декораций не рисует и знать о них не должна.
   */
  syncDecorations?(entities: ReadonlyMap<EntityId, EntityView>): void;
  /**
   * Покадровое обновление: `dt` — секунды с прошлого кадра СО ЗНАКОМ хода мира
   * (REND-2, REND-25), `alpha` — доля тика [0..1], `realDt` — те же секунды по
   * часам главного потока, без знака и без остановки в замороженном мире.
   *
   * Мир доигрывает `dt`; `realDt` берут только величины самой картинки, которым
   * режим мира не указ, — счётчик кадров HUD (HUD-5). Параметр третий и
   * необязательный к объявлению: подсистема, которой он не нужен, объявляет два
   * прежних аргумента и ничего не знает о нём.
   */
  updateFrame(dt: number, alpha: number, realDt: number): void;
  /**
   * Декларация ручек качества (`render-quality` QUAL-1, QUAL-3) — расширение
   * контракта REND-8 точкой объявления, а не отдельным реестром: спрашивают её
   * один раз, при регистрации подсистемы.
   *
   * Метод необязателен технически (подсистема вне сцены с контроллером качества
   * его не увидит), но не по норме: QUAL-3 требует от подсистемы с растущей
   * стоимостью либо ручки, либо явного объявления константности, и «метода нет»
   * — это ни то, ни другое.
   */
  quality?(): QualityDeclaration;
  /**
   * Значения объявленных ручек (QUAL-1, design D2): доставляются при
   * регистрации подсистемы и при смене пресета в рантайме — СОБЫТИЯМИ, а не
   * кадром. Пересборки рендера смена не требует: подсистема
   * применяет значения на живых объектах, как туман применяет конфиг (FOW-10).
   *
   * Метода нет у подсистемы, объявившей стоимость константной: раздавать ей
   * нечего.
   */
  applyQuality?(values: QualityValues): void;
  /**
   * Объявление отладочных источников (`render-debug` RDBG-1) — то же расширение
   * контракта REND-8 точкой объявления (REND-27), каким стала декларация ручек
   * качества: спрашивают его один раз, при регистрации подсистемы.
   *
   * Данные подсистемы принадлежат ей, и источник, показывающий её маску, её
   * инстансы или её сетку, пишется там, где эти данные есть; отладочный слой при
   * этом не знает о внутреннем устройстве подсистемы ничего сверх пробы
   * (RDBG-2). Каждый `id` обязан начинаться с имени подсистемы — неймспейс
   * владельца тот же, что у ручек качества.
   *
   * Объявление НЕОБЯЗАТЕЛЬНО и его отсутствие дефектом не является (REND-27) —
   * в отличие от объявления стоимостной ручки (QUAL-3): подсистеме бывает нечего
   * показывать, а вот стоимость у неё есть всегда.
   */
  debugSources?(): readonly DebugSource[];
}

// ------------------------------------------------------------ конфиг хоста

export interface RenderHostConfig {
  /** Длительность тика в секундах — знаменатель альфы интерполяции (REND-2). */
  readonly tickSeconds: number;
  /**
   * Сцена подсистем, разделяемая с другим продюсером presentation-состояния
   * (REND-11): её передаёт редактор, чтобы вьюпорт и превью (ED-9) кормили одни
   * и те же подсистемы. По умолчанию хост заводит свою — в игровом клиенте
   * второго продюсера не существует.
   */
  readonly stage?: PresentationStage;
  /**
   * Визуальный тип сущности — ключ манифеста визуалов; null — не рисовать.
   * Ядро не хранит имя prefab'а на сущности, поэтому связь задаёт вызывающий;
   * практичный резолвер — `kindByTags` по тегам prefab'а.
   */
  readonly kindOf: (state: WorldState, entity: EntityId) => string | null;
  /** Компонент скорости; конвенция физики ядра — 'Velocity' с полями x/y. */
  readonly velocityComponent?: string;
  /** Скачок позиции за тик больше этого (мировых единиц) — телепорт, snap (REND-2). */
  readonly snapDistance?: number;
  /** Порог скорости (мировых единиц за тик) для состояния `move` (REND-4). */
  readonly moveEpsilon?: number;
  /** Сетка террейна сцены — уровень под сущностями и зеркало карты пола (REND-7). */
  readonly terrainGrid?: TerrainGrid;
  /** Типы событий, несущие направление атаки/каста для bone-контроля (REND-5). */
  readonly aimEvents?: readonly string[];
  /** Сколько тиков держится направление каста, прежде чем цель протухнет. */
  readonly aimHoldTicks?: number;
  /** Компоненты, зеркалируемые в `EntityView.states` (эффекты камеры, CAM-6). */
  readonly stateComponents?: readonly string[];
  /** Имена компонентов локомоушена (LOC-1); дефолты — как у системы ядра. */
  readonly locomotion?: { readonly stateComponent?: string; readonly configComponent?: string };
  /** Источник фазы полёта снаряда (REND-12) — конфигурация сборки, не конвенция ядра. */
  readonly flight?: FlightPhaseSource;
  /** Часы в миллисекундах; по умолчанию performance.now — параметр ради тестов. */
  readonly clock?: () => number;
}
