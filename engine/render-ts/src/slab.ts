/**
 * Слэбовый тест луча против осевой коробки (REND-15) — общий примитив
 * наведения: им режется и объём-прокси инстанса в его локальных осях
 * (`picking.ts`), и прямоугольник арены при марше по полю высот
 * (`surfaceMarch.ts`). Второй его записи быть не должно: срез луча коробкой
 * один, и разойдись эти два, наведение по инстансу и наведение по поверхности
 * отвечали бы про разные лучи.
 *
 * Диапазон параметра живёт в модульной записи, а не создаётся на луч: наведение
 * зовут по кадру на курсор, а вложенных слэб-тестов нет — вызывающий выставляет
 * границы перед первой осью и читает их после последней.
 */

/** Направление считается вырожденным по оси ниже этого модуля. */
export const EPS_DIR = 1e-12;

/** Диапазон параметра луча [tMin, tMax], сужаемый осями. */
export const SLAB_RANGE = { tMin: 0, tMax: 0 };

/**
 * Сужение `SLAB_RANGE` слэбом одной оси. `false` — луч вырожден по этой оси и
 * лежит вне слэба: дальше считать нечего, остальные оси не смотрим.
 */
export function slabAxis(origin: number, dir: number, lo: number, hi: number): boolean {
  if (Math.abs(dir) < EPS_DIR) return origin >= lo && origin <= hi;
  let t1 = (lo - origin) / dir;
  let t2 = (hi - origin) / dir;
  if (t1 > t2) {
    const swap = t1;
    t1 = t2;
    t2 = swap;
  }
  if (t1 > SLAB_RANGE.tMin) SLAB_RANGE.tMin = t1;
  if (t2 < SLAB_RANGE.tMax) SLAB_RANGE.tMax = t2;
  return true;
}
