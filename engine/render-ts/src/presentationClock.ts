/**
 * Часы презентации: ход, который получают подсистемы кадра (REND-25).
 *
 * Врозь с буфером состояния потому, что это разные вещи: там — приём доставок,
 * записи сущностей и их пары интерполяции, здесь — арифметика ОДНОГО числа,
 * которое кадр раздаёт подсистемам, и три множителя, из которых оно собрано:
 * направление по режиму мира, темп обратного хода (`deliveryCadence.ts`) и
 * мировой множитель показа.
 *
 * Персональной шкалы сущности (REND-38) здесь нет и быть не может: она —
 * четвёртый множитель того же времени, но применяют её потребители, у которых
 * на руках сущность, а не кадр.
 */
import type { WorldMode } from '@fluxus/core';

/**
 * Потолок кадрового шага, секунды. После паузы вкладки первый кадр не должен
 * «доигрывать» минуты; величина нормирует то, что ПОЛУЧАЮТ подсистемы, поэтому
 * стоит после всех множителей, а не до них.
 */
const MAX_FRAME_STEP = 0.25;

/**
 * Ход часов презентации по режиму доставленного мира (REND-25): вперёд в
 * `Running`, стоп в `Paused`, назад в `Rewinding`. Своего «времени перемотки»
 * рендер не заводит — направление есть чистая функция режима, а движение назад
 * приносят сами восстановленные состояния.
 */
function clockDirection(mode: WorldMode): number {
  switch (mode) {
    case 'Running':
      return 1;
    case 'Rewinding':
      return -1;
    default:
      return 0;
  }
}

/**
 * Шаг подсистем кадра: `min(|Δt| · темп · множитель, потолок) · направление`.
 *
 * Оба множителя стоят ПОД потолком (REND-25, change `presentation-time-scale`,
 * design D1): потолок нормирует полученный подсистемами шаг независимо от того,
 * чем его разогнали, — иначе при множителе 4 подсистема вправе была бы получить
 * секунду за кадр, и инвариант «|dt| ≤ потолок» на этом бы кончился. Знак
 * остаётся снаружи: он принадлежит режиму, а множители знака не несут.
 */
export function frameStep(
  magnitude: number,
  pace: number,
  timeScale: number,
  mode: WorldMode,
): number {
  return Math.min(magnitude * pace * timeScale, MAX_FRAME_STEP) * clockDirection(mode);
}

/**
 * Проверка мирового множителя показа (REND-25). Направления он не несёт — оно
 * принадлежит режиму мира, — поэтому отрицательное значение это ошибка
 * вызывающего, а не «ход назад»; ноль законен и тождествен заморозке.
 *
 * `owner` — имя того, кто отверг величину: множитель проходит проверку и в
 * буфере, и в удалённом хосте (буфера у него до handshake ещё нет), а сообщение
 * обязано называть отказавшего.
 */
export function assertTimeScale(scale: number, owner: string): void {
  if (!Number.isFinite(scale) || scale < 0) {
    throw new Error(`${owner}: множитель часов презентации ${scale} — ожидалось число не меньше нуля`);
  }
}
