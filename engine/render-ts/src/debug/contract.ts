/**
 * Контракт отладочного источника и закрытый словарь примитивов рисования
 * (`render-debug` RDBG-1, RDBG-2, RDBG-3).
 *
 * ## Открытый реестр источников, закрытый словарь примитивов
 *
 * Источник — это `id` в неймспейсе владельца, проба и (если ему есть что
 * рисовать) рисовальщик. Реестр ОТКРЫТ: новая ось наблюдения добавляется
 * регистрацией источника, а не правкой кадрового пути (RDBG-1) — по образцу
 * того, как новая подсистема добавляется регистрацией (`rendering` REND-8).
 * Словарь ПРИМИТИВОВ, наоборот, закрыт и назван рендером: сцены источник не
 * видит, узлов не создаёт, материалов не трогает (RDBG-3), иначе появился бы
 * второй путь отрисовки — тот же, что запрещают REND-16 и `editor` ED-1.
 *
 * ## Одна проба — две грани
 *
 * Источник отвечает ОДНИМ значением — пробой. Наложение рисуется из пробы, дамп
 * сериализует её же (RDBG-2): два независимых чтения живого состояния разошлись
 * бы молча, и человек с моделью обсуждали бы разные кадры. Поэтому у
 * рисовальщика другого входа, кроме пробы, нет — ни сцены, ни подсистемы.
 *
 * Проба обязана быть САМОДОСТАТОЧНОЙ: числа, короткие перечни и имена, а не
 * ссылки на живые структуры рендера. Удержанная ссылка пережила бы кадр и
 * открыла бы чтение состояния за пределами окна его валидности — то же
 * соображение, по которому запись диагностики ядра передаётся самодостаточными
 * данными (`diagnostics` DIAG-4), а событие тика копируется в presentation-форму
 * (`tick-loop` OBS-3). Механически это держит сборка дампа (`dump.ts`): значение,
 * которое не выражается плоским JSON, она отвергает адресно.
 *
 * Структура пробы ПЕРЕИСПОЛЬЗУЕТСЯ между кадрами (RDBG-2, REND-26): включённый
 * источник платит за пробу каждый кадр, и свежий объект на кадр был бы мусором,
 * растущим с числом сущностей.
 */
import type { WorldMode } from '@game-mvp/core';
import type { TickView } from '../types.js';

// ------------------------------------------------------------------- проба

/**
 * Проба источника — плоские самодостаточные данные текущего состояния кадра.
 *
 * Два поля механизма, остальное — дело источника:
 *
 * - `noData` — «данных нет» с причиной (RDBG-6). Источник, чьих данных сборка не
 *   объявила (стат HUD-8) или чей вход вырезан фильтром снапшота (`netcode`
 *   NET-12), говорит это вслух и MUST NOT показывать выдуманное значение.
 *   Отсутствие поля — данные есть; «выключен» же выражается ОТСУТСТВИЕМ секции
 *   в дампе (RDBG-7), а не пустой пробой;
 * - `clock` — величины, выведенные из часов главного потока (альфа интерполяции
 *   SHELL-7, частота кадров, сглаженные оценки каденса доставки). Сборка дампа
 *   поднимает их в отдельную секцию: воспроизводимыми они не бывают, и
 *   смешанные с остальными они превратили бы всякий дифф в шум (RDBG-7).
 */
export interface DebugProbe {
  /** Причина отсутствия данных (RDBG-6); нет поля — данные есть. */
  readonly noData?: string;
  /** Часовые величины: в дампе они уезжают отдельной секцией (RDBG-7). */
  readonly clock?: Readonly<Record<string, number>>;
  readonly [field: string]: unknown;
}

/**
 * Состояние кадра, на котором снимается проба: доставленное presentation-
 * состояние и кадровые величины. Больше у источника входов нет — этим и держится
 * информационная граница (RDBG-6): источник читает то же, что и кадр.
 */
export interface DebugFrameState {
  /** Presentation-состояние последней доставки; null — доставок ещё не было. */
  readonly view: TickView | null;
  /** Доля тика [0..1] между двумя доставленными тиками (`client-shell` SHELL-7). */
  readonly alpha: number;
  /** Часы презентации: секунды с прошлого кадра СО ЗНАКОМ хода мира (REND-25). */
  readonly dtSeconds: number;
  /** Часы главного потока: те же секунды без знака и без остановки (REND-2). */
  readonly realDtSeconds: number;
}

/** Режим мира последней доставки; `none` — доставок не было (REND-25). */
export type DebugWorldMode = WorldMode | 'none';

// ------------------------------------------------------- словарь примитивов

/** Цвет примитива, `0xRRGGBB`. Палитра — политика источника (RDBG-1). */
export type DebugColor = number;

/**
 * Поза и габариты коробки: то же представление, каким подсистема моделей отдаёт
 * объём-прокси инстанса (REND-15, `picking.ts`). Совпадение намеренное — рамка
 * инстанса рисуется ТЕМ ЖЕ преобразованием, каким он нарисован, а не вторым
 * расчётом позы.
 */
export interface DebugPose {
  readonly posX: number;
  readonly posY: number;
  readonly posZ: number;
  readonly quatX: number;
  readonly quatY: number;
  readonly quatZ: number;
  readonly quatW: number;
  readonly scaleX: number;
  readonly scaleY: number;
  readonly scaleZ: number;
  readonly minX: number;
  readonly minY: number;
  readonly minZ: number;
  readonly maxX: number;
  readonly maxY: number;
  readonly maxZ: number;
}

/**
 * Растровая плашка над ареной — единственный примитив словаря, несущий растр
 * (RDBG-3). Тексели живут в пробе ради наложения, но в дамп они НЕ едут:
 * сериализация заменяет их числом текселей (RDBG-7) — растр 512×512 бесполезен
 * обеим граням.
 *
 * Растр обязан быть КОПИЕЙ, а не ссылкой на буфер подсистемы (RDBG-2): буфер
 * маски перезаписывается доставкой, и удержанная ссылка показала бы кадр,
 * которого не было.
 */
export interface DebugRaster {
  /** Метка примитива: по ней сборка дампа узнаёт растр и опускает тексели. */
  readonly raster: true;
  readonly widthTexels: number;
  readonly heightTexels: number;
  /** Мировой прямоугольник плашки, мировые единицы. */
  readonly worldX: number;
  readonly worldY: number;
  readonly worldWidth: number;
  readonly worldHeight: number;
  /** Высота плашки над ареной, мировые единицы. */
  readonly worldZ: number;
  /** Значения текселей [0..255]; в дамп не едут (RDBG-7). */
  readonly texels: Uint8Array;
}

/**
 * Закрытый словарь примитивов (RDBG-3). Смысл примитива приносит источник,
 * форму знает рендер: сценовыми объектами владеет отладочный слой, и прямого
 * доступа к сцене у источника нет.
 *
 * Текста здесь нет и не будет: пакет рендера свободен от DOM (REND-19), а текст
 * в сцене — канвас-текстура, то есть DOM. Имена и числа живут в дампе (RDBG-7) и
 * в панели встраивающего приложения.
 */
export interface DebugDraw {
  /** Точка в мировых координатах. */
  point(x: number, y: number, z: number, color: DebugColor): void;
  /** Отрезок между двумя мировыми точками. */
  segment(
    x1: number,
    y1: number,
    z1: number,
    x2: number,
    y2: number,
    z2: number,
    color: DebugColor,
  ): void;
  /** Ломаная по тройкам `x,y,z`; `closed` замыкает её последним звеном. */
  polyline(points: readonly number[], color: DebugColor, closed?: boolean): void;
  /** Окружность по визуальной поверхности (REND-9): контур, а не заливка. */
  circle(x: number, y: number, radius: number, color: DebugColor): void;
  /** Диск по визуальной поверхности (REND-9): заливка. */
  disc(x: number, y: number, radius: number, color: DebugColor): void;
  /** Коробка в заданной позе — рёбрами. */
  box(pose: DebugPose, color: DebugColor): void;
  /** Выпуклый полигон по визуальной поверхности; точки — пары `x,y`. */
  polygon(points: readonly number[], color: DebugColor): void;
  /** Растровая плашка над ареной. */
  raster(raster: DebugRaster, color: DebugColor): void;
}

// ------------------------------------------------------------- источник

/**
 * Отладочный источник (RDBG-1). Регистрируют его подсистема — в точке своей
 * регистрации (REND-27) — либо встраивающая сборка: игровое приложение и
 * вьюпорт редактора вправе привезти свои, не правя движок.
 *
 * `id` — в неймспейсе владельца (`fog.mask`, `models.bounds`, `net.delivery`):
 * плоский реестр с читаемой принадлежностью, как у ручек качества (QUAL-1).
 */
export interface DebugSource<P extends DebugProbe = DebugProbe> {
  /** Полное имя `<владелец>.<источник>`; повторный отвергается адресно (RDBG-1). */
  readonly id: string;
  /** Подпись человеку — её печатает панель встраивающего приложения. */
  readonly title?: string;
  /** Снимок собственных данных на этом состоянии кадра; структура переиспользуется. */
  probe(state: DebugFrameState): P;
  /** Наложение ИЗ ПРОБЫ (RDBG-2); нет метода — источнику нечего рисовать. */
  draw?(probe: P, out: DebugDraw): void;
  /**
   * Переключатель источника щёлкнул (RDBG-4). Метод нужен ровно тем источникам,
   * у которых включение — не только «начать считать пробу»: читателю счётчиков
   * стоимости им подключается и отпускается сток (RDBG-8, design D8).
   * Выключенный источник обязан не стоить ничего, и «отпустить» — часть этого.
   */
  toggle?(enabled: boolean): void;
}

/**
 * Перечень с потолком (RDBG-7): «наличие потолка — механизм, его величина —
 * политика источника». Записи ПЕРЕИСПОЛЬЗУЮТСЯ между пробами (RDBG-2) — свежий
 * массив объектов на кадр был бы аллокацией пропорционально числу сущностей.
 */
export interface DebugList<T> {
  readonly items: readonly T[];
  /** Сколько записей было ДО потолка. */
  readonly total: number;
  /** Перечень усечён потолком. */
  readonly truncated: boolean;
}

/**
 * Наполнитель перечня с потолком: пул записей заводится один раз, проба лишь
 * переписывает их поля. `begin()` → `next()` на каждую запись → `end()`.
 */
export class DebugRows<T extends object> {
  /** Перечень в форме пробы: объект стабилен, длина `items` меняется. */
  readonly list: { items: T[]; total: number; truncated: boolean } = {
    items: [],
    total: 0,
    truncated: false,
  };

  private readonly cap: number;
  private readonly make: () => T;
  private readonly pool: T[] = [];
  private count = 0;

  constructor(cap: number, make: () => T) {
    this.cap = Math.max(0, Math.floor(cap));
    this.make = make;
  }

  begin(): void {
    this.count = 0;
    this.list.total = 0;
    this.list.truncated = false;
  }

  /** Следующая запись либо null — потолок достигнут, усечение помечено. */
  next(): T | null {
    this.list.total += 1;
    if (this.count >= this.cap) {
      this.list.truncated = true;
      return null;
    }
    const row = this.pool[this.count] ?? this.grow();
    this.count += 1;
    return row;
  }

  /** Закрывает перечень: наружу видны ровно заполненные записи. */
  end(): void {
    this.list.items.length = this.count;
    for (let i = 0; i < this.count; i += 1) this.list.items[i] = this.pool[i]!;
  }

  private grow(): T {
    const row = this.make();
    this.pool.push(row);
    return row;
  }
}
