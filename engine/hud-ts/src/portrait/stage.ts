/**
 * Шов стенда портрета (HUD-7, design Decision 8): интерфейс, за которым сидит
 * вся THREE-часть виджета — второй `WebGLRenderer` со своей мини-сценой,
 * камерой и циклом кадра.
 *
 * Шов проведён между ДАННЫМИ и КАРТИНКОЙ: резолв kind → запись манифеста,
 * запрос модели у разделяемого asset-сервиса (ASSET-2) и реакции на
 * доставленные события живут в виджете (`widget.ts`) и тестируются без
 * браузера; стенд получает уже загруженную нормализованную модель и рисует
 * её. Поэтому стенд КОНСТРУКТИВНО не может ни рендерить арену, ни читать
 * доставленное состояние: ему не передаётся ни сцена арены, ни доставка —
 * только asset-сервис (для текстур скина) и данные одной модели (HUD-7).
 *
 * Реальная реализация — `threeStage.ts`; тесты подставляют заглушку через
 * `PortraitSetup.createStage`.
 */
import type { AssetService, EntityVisual, NormalizedModel } from '@game-mvp/assets';

/**
 * Изолированный стенд одной модели. Жизненный цикл повторяет виджет:
 * `attach` — при материализации canvas из разметки (`HudNode.ref`),
 * `showModel`/`clearModel` — по смене визуального типа сущности портрета,
 * `dispose` — вместе с виджетом. Кадровый цикл — забота реализации; контракт
 * лишь требует, чтобы он не рисовал ничего без canvas и без модели.
 */
export interface PortraitStage {
  /** Canvas виджета материализован — стенду есть куда рисовать. */
  attach(canvas: HTMLCanvasElement): void;
  /**
   * Показать модель стенда: нормализованные данные ассета (тот самый
   * разделяемый объект из общего кэша, ASSET-2) плюс запись манифеста,
   * из которой стенд берёт масштаб, скрытые части, скин и idle-клип.
   * Прежняя модель, если была, снимается.
   */
  showModel(model: NormalizedModel, visual: EntityVisual): void;
  /** Снять модель: стенд пуст и ничего не рисует. */
  clearModel(): void;
  /** Останавливает цикл кадра и освобождает ресурсы рендера. */
  dispose(): void;
}

/**
 * Что стенд получает при создании — РОВНО общий asset-сервис и ничего сверх:
 * отсутствие в этой записи сцены арены, камеры арены и доставки — то самое
 * «MUST NOT быть камерой в сцену арены» HUD-7, обеспеченное сигнатурой,
 * а не дисциплиной кода.
 */
export interface PortraitStageOptions {
  /**
   * ТОТ ЖЕ `AssetService`, которым живёт рендер арены (ASSET-2): стенд просит
   * через него текстуры скина, и уже загруженное ареной приходит из общего
   * кэша тем же handle, без повторной загрузки.
   */
  readonly assets: AssetService;
}

/** Фабрика стенда — точка подмены THREE-части заглушкой в тестах. */
export type PortraitStageFactory = (options: PortraitStageOptions) => PortraitStage;
