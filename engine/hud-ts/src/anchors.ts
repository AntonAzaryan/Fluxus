/**
 * Мировые якоря глазами HUD (HUD-10): узкий порт над тем, что публикует рендер
 * (`rendering` REND-41).
 *
 * Порт, а не импорт рендера, по той же причине, по какой у HUD свой `HudNode`:
 * пакет HUD не зависит от `render-ts` и собирается без него — тест композиции
 * идёт без сцены вовсе. Форма здесь ровно та, которую читает размещение:
 * пиксели прямоугольника вьюпорта и два признака. Считать проекцию самому
 * экранному слою запрещено (HUD-3): вторая посадка позы камеры разъезжается с
 * кадром так же, как разъехался бы с ним второй луч курсора (REND-42).
 */

/** Опубликованный якорь одной сущности (REND-41). */
export interface HudScreenAnchor {
  /** Пиксели прямоугольника вьюпорта от его левого верхнего угла. */
  readonly x: number;
  readonly y: number;
  /** Точка перед камерой и внутри прямоугольника вьюпорта. */
  readonly onScreen: boolean;
  /** Инстанс нарисован этим кадром: он есть и не отсечён (REND-21). */
  readonly drawn: boolean;
}

/**
 * Источник якорей — то, что сборка отдаёт исполнителю композиции. `null` —
 * сущности в наборе нет: якорный виджет тогда скрыт, а не оставлен висеть в
 * последней известной точке (HUD-10).
 */
export interface HudAnchorSource {
  anchorOf(entity: number): HudScreenAnchor | null;
}

/**
 * Сущность из значения биндинга (HUD-10): селектор вправе отдать и запись
 * доставленного состояния (`HudEntityView`), и голый идентификатор — «сущность»
 * в композиции называется слотом, а не формой значения. `null` — значения нет
 * либо оно сущностью не является, и виджет скрывается.
 */
export function anchorEntityOf(value: unknown): number | null {
  if (typeof value === 'number') return Number.isInteger(value) && value > 0 ? value : null;
  if (typeof value !== 'object' || value === null) return null;
  const id = (value as { id?: unknown }).id;
  return typeof id === 'number' && Number.isInteger(id) && id > 0 ? id : null;
}
