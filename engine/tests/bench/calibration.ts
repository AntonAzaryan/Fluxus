/**
 * Калибровка машины для wall-time сторожей (`performance-budget` PERF-5).
 *
 * PERF-5 разрешает ассертить реальное время ТОЛЬКО против деградации порядка
 * величины и прямо запрещает жёсткие пороги: «жёсткие пороги wall-time в гейте
 * MUST NOT использоваться — числа между машинами несравнимы, и жёсткий порог
 * даёт ложные срабатывания на слабой машине разработчика». Порог в абсолютных
 * миллисекундах этому не отвечает по устройству: он — функция скорости машины и
 * её загрузки, а не стоимости кода. Так и краснели сторожа маски FoW в
 * контейнере гейта — 5.2 мс на нагрузке, для которой автор наблюдал 0.3 мс и
 * поставил порог 4 мс: сработал первый сценарий требования («слабая машина не
 * краснит гейт») наоборот, не поймав ни одной регрессии.
 *
 * Здесь порог становится функцией МАШИНЫ, а не константой. В том же процессе и
 * рядом по времени меряется маленькая фиксированная синтетическая нагрузка —
 * эталонная единица работы, — и бюджеты сторожей выражаются её кратными:
 *
 * - машина вдвое (или впятеро) медленнее замедляет и эталон, и измеряемое, их
 *   отношение не меняется — гейт остаётся зелёным (сценарий PERF-5 «слабая
 *   машина не краснит гейт»);
 * - правка, делающая каждую операцию в 20 раз дороже при неизменном их числе,
 *   эталона не трогает вовсе — отношение растёт в 20 раз и краснеет (сценарий
 *   PERF-5 «константное замедление на единицу работы»).
 *
 * Эталон умышленно не зависит ни от одного пакета репозитория и меряет не его:
 * целочисленная арифметика плюс чтение-запись типизированного массива — то, из
 * чего состоят и растеризация маски, и цикл тика, и кодек канала. Его работа
 * обязана оставаться неизменной: поменяется эталон — молча поедут кратные во
 * всех сторожах сразу.
 *
 * Отношение — не абсолютный инвариант, и выдавать его за таковой нельзя: на
 * машине с другим соотношением «счёт против памяти» оно уедет на десятки
 * процентов, а под чужой нагрузкой замер длиннее калибровки ловит планировщика
 * и уезжает в разы. Запас порога — на порядок — ровно про это: сторож обязан
 * пережить и то и другое, а деградацию на порядок пропустить сквозь себя.
 *
 * Точный контроль объёма работы этим не подменяется и подменяться не может: его
 * держат детерминированные счётчики (PERF-3, PERF-4). Wall-time страхует то,
 * чего счётчики не видят, — константное замедление на единицу работы.
 */
import { DEBUG } from '@fluxus/core';

/** Байт эталонного растра: 4 КиБ живут в L1 любой машины — меряется счёт, а не шина памяти. */
const RASTER_BYTES = 64 * 64;
/** Проходов по растру в одной эталонной единице — единица весит порядка миллисекунды. */
const PASSES = 128;
/** Замеров, из которых берётся МИНИМУМ: одиночный замер меряет планировщик, а не машину. */
const SAMPLES = 7;
/** Прогонов на прогрев JIT перед замером — та же конвенция, что у самих сторожей. */
const WARMUP = 3;

const raster = new Uint8Array(RASTER_BYTES);

/**
 * Эталонная единица работы: xorshift-арифметика с чтением-записью растра.
 * Возвращает контрольную сумму — её читает вызывающий, иначе JIT вправе выбросить
 * цикл целиком и калибровка мерила бы пустоту.
 */
function referenceUnit(): number {
  let x = 0x9e3779b9 | 0;
  let sum = 0;
  for (let pass = 0; pass < PASSES; pass++) {
    for (let i = 0; i < RASTER_BYTES; i++) {
      x ^= x << 13;
      x ^= x >>> 17;
      x ^= x << 5;
      const value = ((raster[i] ?? 0) + (x & 0xff)) & 0xff;
      raster[i] = value;
      sum += value;
    }
  }
  return sum;
}

let unitMs: number | undefined;

/**
 * Стоимость эталонной единицы работы на ЭТОЙ машине, мс.
 *
 * Замер один на процесс и ленивый: он делается при первом обращении, то есть
 * внутри первого же сторожевого теста файла — рядом по времени с тем, что
 * сторож меряет, и под той же загрузкой (в гейте тестовые файлы идут
 * параллельно, и загрузка эта совсем не нулевая).
 *
 * Берётся МИНИМУМ семи замеров, а не медиана и не среднее: планировщик, GC и
 * прогрев умеют сделать отдельный замер только медленнее, никогда быстрее, —
 * поэтому минимум и есть самая устойчивая оценка скорости машины (наблюдаемый
 * разброс минимума — проценты, медианы — разы: 1.6…3.5 мс на одной и той же
 * машине). Устойчивость нужна с обеих сторон: завышенная калибровка ослабляет
 * сторож ровно во столько же раз, во сколько заниженная его ужесточает.
 */
export function machineUnitMs(): number {
  if (unitMs !== undefined) return unitMs;

  let checksum = 0;
  for (let i = 0; i < WARMUP; i++) checksum += referenceUnit();

  const samples: number[] = [];
  for (let i = 0; i < SAMPLES; i++) {
    const started = performance.now();
    checksum += referenceUnit();
    samples.push(performance.now() - started);
  }
  // Контрольная сумма читается: без этого цикл выше — мёртвый код для JIT.
  if (checksum === 0) throw new Error('калибровка не выполнила работу: эталон выродился');

  unitMs = Math.min(...samples);
  return unitMs;
}

/**
 * Стоимость измеренного отрезка в эталонных единицах — величина, которую и
 * стерегут сторожа: она не зависит от того, насколько быстра машина, а зависит
 * только от того, во сколько операций обошлась работа и почём операция.
 *
 * Кратное в вызывающем читается как «во сколько раз дороже эталона позволено
 * быть измеряемому»; ставится оно на порядок выше наблюдаемого отношения
 * (PERF-5), а не «в притык», и само наблюдаемое отношение называется рядом.
 */
export function benchUnits(elapsedMs: number): number {
  return elapsedMs / machineUnitMs();
}

/**
 * Строка про калибровку для печати `[bench]`: одна на файл сторожей.
 *
 * Режим сборки назван в ней намеренно (PERF-5). Сторожа меряют ту сборку, в
 * которой запущен раннер, а под `vitest` это debug: `DEBUG` ядра — это
 * `NODE_ENV !== 'production'`, и в нём каждая fixed-операция и каждое чтение
 * поля несут assert; та же нагрузка в релизе примерно на 40 % дешевле
 * (`docs/reviews/2026-09-02-core-tick-headroom.md`). Разница между режимами
 * поэтому легко читается как регресс или как ускорение, хотя не является ни
 * тем ни другим: цифра сторожа сравнима только с цифрой ТОГО ЖЕ режима.
 *
 * Флаг берётся у ядра (`DEBUG` из `@fluxus/core`), а не вычисляется здесь по
 * `NODE_ENV` заново: два источника правды о режиме разошлись бы молча, и строка
 * называла бы не тот режим, в котором assert'ы на самом деле включены.
 */
export function calibrationLine(): string {
  const build = DEBUG ? 'debug' : 'release';
  return `[bench] сборка ${build}, калибровка машины: ${machineUnitMs().toFixed(3)} мс на эталонную единицу работы`;
}
