/**
 * Адаптивный запас разметки ввода (NTR-7): детектор опоздания кадров и
 * контроллер, который этот запас двигает.
 *
 * Отдельным модулем, а не полями клиента, по той же причине, по которой отдельно
 * живёт кольцо своих кадров: величина решается маленьким автоматом со своими
 * порогами, и проверяется он синтетической последовательностью «отправлено —
 * применено», а не матчем.
 *
 * ## Сигнал: эхо `seq` в тиковой шкале (design D1)
 *
 * Клиент шлёт `seq` монотонно и видит в собственном снапшоте `seq` последнего
 * применённого кадра: его кладёт в компонент ввода `InputSystem` (TICK-4), а
 * своя сущность в своём снапшоте присутствует всегда (NET-15). Наблюдение — не
 * одно число, а ПАРА: тик, на который клиент пометил подтверждённый кадр (он
 * лежит в кольце своих кадров), и тик снапшота, в котором подтверждение пришло.
 *
 * Пара и делает сигнал измеримым. Кадр применяется РОВНО на том тике, которым
 * помечен (NTR-7), поэтому разность
 *
 *     behind = тик снапшота − тик подтверждённого кадра
 *
 * и есть длина серии, которую сервер прожил на повторе последнего кадра
 * (TICK-2): ноль — «мой кадр применяется на своём тике», `k` — «последние `k`
 * тиков слот прожил на predicted». Обе половины — величины СЕРВЕРНОЙ шкалы,
 * поэтому в разность не входит ничего, что различает часы сторон: ни дорога до
 * сервера, ни фаза рассылки, ни собственный запас оценки тика, ни лишний шаг
 * убежавшего вперёд клиентского таймера. Считать то же самое в отправках было бы
 * храповиком: разрыв «отправлено − применено» растёт ВМЕСТЕ с запасом, и подъём
 * не гасил бы собственную причину — запас уезжал бы в потолок на исправном
 * канале и не возвращался.
 *
 * Считается при этом не всякий повтор, а только тот, за который отвечает КАНАЛ.
 * Сервер живёт на повторе и там, где кадра на тик не было вовсе: игрок молчит и
 * источник ввода не даёт сэмпла (`InputSource` вправе вернуть `undefined`);
 * собственный шаг клиента отстал от серверного тика, и `resyncTick` подтянул
 * оценку ЧЕРЕЗ пропущенный номер — тик остался без кадра, хотя канал ни при чём.
 * Такие тики клиент знает сам, он их не размечал, — и в длину серии они не
 * входят: наблюдением служат ровно те тики серии, на которые кадр УХОДИЛ. Это и
 * есть «нет отправки — нет наблюдения» (design D1), доведённое до отдельного
 * тика. Без него детектор мерил бы длительность молчания и расхождение часов
 * вместо длины канала: на редком вводе запас полз бы в потолок при нулевой
 * задержке, а на медленных часах не спускался бы никогда — пропущенных
 * собственных номеров подъём не лечит, и чистого окна не набралось бы вовсе.
 *
 * Транспортный RTT сигналом быть не может — несущий канал вправе не уметь его
 * измерить, и метрика отклика от него зависеть MUST NOT (NTR-11); серверный
 * счётчик predicted потребовал бы нового сообщения, а набор закрыт (NTR-4).
 *
 * У тиковой шкалы есть и обратная сторона, и она сознательная: потеря СНАПШОТОВ
 * сигналом не является вовсе. Эхо приходит реже, но каждое приходит со своим
 * тиком, и `behind` от этого не растёт — рвущийся downlink не поднимает запас,
 * который лечит не его. Одиночная потеря кадра ввода среди доехавших тоже видна
 * лишь до следующего подтверждения: `behind` считает ТЕКУЩУЮ серию повторов, а
 * не их сумму. Раздельный счёт потерь ведёт сервер (NTR-11).
 *
 * Одной тиковой шкалы этой половине мало, и это не мелочь: второй порог (срок
 * эха, ниже) работает как раз там, где подтверждений НЕТ, а у оборванного
 * downlink их нет ровно так же, как у слишком короткого запаса. Поэтому срок
 * ждёт не только своего истечения, но и снапшота: пришедший снапшот и означает
 * «канал состояний жив, а моего кадра в нём нет». Без этого условия обрыв
 * downlink гнал бы запас в потолок — то есть сигналом потеря снапшотов
 * оказалась бы всё-таки, и ровно там, где запас не лечит ничего.
 *
 * Вторая сторона того же — спуск: подтверждения кончились, а последняя разность
 * осталась, и повторять её каждой отправкой значило бы набирать чистое окно на
 * наблюдении, которого уже нет. Поэтому протухшее наблюдение (подтверждений нет
 * дольше того же допуска) не двигает запас НИ В КАКУЮ сторону: нет наблюдения —
 * нет решения, ровно как «нет отправки — нет наблюдения» выше.
 *
 * ## Контроллер: подъём по доказательству, спуск по времени (design D2)
 *
 * Быстро вверх, медленно вниз. Подъём — на период рассылки (меньший шаг
 * наблюдением не разрешается: эхо приезжает не чаще снапшотов) и немедленно по
 * сигналу: размеченный тик, прожитый сервером на повторе, означает, что кадр к
 * своему тику не доехал — и был отброшен вместе с нажатиями, которые нёс (NTR-7:
 * фрейм на исполненный тик задним числом не применяется). Допуска на «короткую
 * серию» у сигнала нет, и это не жёсткость, а арифметика наблюдения: разность
 * видна только на тиках рассылки, то есть серия из одного-двух опозданий
 * заметна лишь тогда, когда кончается ровно на снапшоте, и допуск в несколько
 * тиков делал бы контроллер слепым к каналу, где опаздывает каждый двадцатый
 * кадр. На таком канале он сходился бы к НАИМЕНЬШЕМУ значению, при котором
 * серии редко длиннее допуска, — то есть к значению, где ввод теряется
 * постоянно, — а NTR-7 велит сделать «фрейм не успел» редким событием. Цена
 * нулевого допуска — на канале с разбросом запас стоит на тик-два выше, чем
 * стоял бы при допуске: это лишние 16–33 мс отклика против потерянных нажатий.
 *
 * Пока НИ ОДИН кадр под текущим значением не подтверждён, наблюдением служит
 * то, что снапшот несёт и без подтверждения, — свой тик. Снапшот, тик которого
 * уже за барьером, а подтверждённый кадр — ещё до него (или подтверждённого
 * кадра нет вовсе: `seq` нулевой либо чужой, `noEcho`), говорит, что кадры под
 * новым значением к своим тикам не доехали; серия таких тиков считается той же
 * разностью, что и у доказанного значения, только отсчитанной от барьера
 * (`behindOnChannel`). Так запас доходит от `inputDelay` до нужного за ЕДИНИЦЫ
 * секунд, а не за десяток, которых слоту не даёт порог молчания (NTR-6).
 * Подъёмы всё же идут реже с ростом запаса — каждый следующий ждёт, пока сервер
 * пройдёт барьер, помеченный на `lead` тиков вперёд, — поэтому время выхода
 * растёт квадратично по нужному запасу: окно приёма шире примерно сорока тиков
 * само по себе перестаёт укладываться в штатный порог молчания.
 *
 * Страховкой остаётся срок эха: подтверждение кадра приходит не позже, чем через
 * `lead + slack` тиков собственной разметки, где `slack` складывается из
 * периода рассылки (ожидание ближайшей рассылки, которая кадр подтвердит),
 * запаса оценки тика (`resyncTick` разрешает ей стоять на «период рассылки +
 * `inputDelay`» выше снапшотной) и ещё периода рассылки — допуска на то, что шаг
 * клиента и тик сервера идут разными таймерами. Просроченный срок означает то
 * же «канал длиннее запаса» и срабатывает там, куда разность не дотягивается:
 * снапшоты приходят, но ни один не отстоит от барьера дальше собственной
 * разметки клиента (`behindOnChannel` не считает тики за последним ушедшим
 * кадром).
 *
 * Отсюда же барьер: после каждой смены значения точкой отсчёта становится первый
 * кадр под НОВЫМ значением. Без него решение принималось бы по последствиям
 * прошлого — запас перелетал бы на целый круг, пока едет эхо.
 *
 * Спуск — на один тик за окно стабильности, то есть в разы медленнее подъёма:
 * недолёт стоит управления, перелёт — лишних тиков отклика (NTR-7). Спускаться
 * контроллер вправе только с ЧИСТОГО окна: `behind` обязан быть нулём всю его
 * длину. Значение, при котором сервер хоть иногда подставляет повтор, запасом «с
 * запасом» не является, и спуск с него уходил бы в заведомую потерю управления.
 *
 * Спуск обязан помнить, где канал уже ломался. Сигнал двоичный: узнать, что
 * значение мало́, можно только попробовав, и цена неудачной пробы — серия
 * повторов вместо ввода. Проба, повторяемая каждое окно стабильности, превращает
 * эту цену в постоянную: игрок терял бы управление раз в несколько секунд ровно
 * на исправном канале — то самое «штатное положение дел», которое NTR-7 велит
 * сделать редким событием. Поэтому значение, оказавшееся малым, запоминается, и
 * попытка спуститься к нему требует окна, которое удваивается с каждой
 * неудачей. Проба, наконец выстоявшая целое окно, память отменяет: канал стал
 * короче, и мерить его прошлым больше нечем.
 */
import type { Pacing } from '../protocol/messages.js';

/**
 * Интервал стабильности перед спуском на тик, секунды. Величина контроллера, а
 * не конфига матча: спека фиксирует границы и направление, а не темп.
 */
const SETTLE_SECONDS = 5;

/** Во сколько раз реже пробуется значение, только что оказавшееся малым. */
const PROBE_BACKOFF = 2;

/** Предел этого разрежения: проба остаётся редкой, но не исчезает. */
const PROBE_BACKOFF_LIMIT = 16;

/**
 * «Подтверждённого кадра нет» в тиковой шкале: раньше любого тика матча (тики
 * неотрицательны), поэтому в `behindOnChannel` серия отсчитывается от начала
 * собственной разметки.
 */
const NO_ECHO = -1;

export class LeadController {
  /** Нижняя граница и стартовое значение — `inputDelay` из `Welcome` (NTR-7). */
  private readonly floor: number;
  /** Верхняя граница: окно приёма за вычетом запаса оценки тика (NTR-7). */
  private readonly ceiling: number;
  /** Шаг подъёма — период рассылки в тиках. */
  private readonly step: number;
  /** Срок эха сверх `lead`: рассылка, запас оценки тика и допуск на часы. */
  private readonly slack: number;
  /** Окно стабильности в отправках, после которого запас спускается на тик. */
  private readonly settleWindow: number;
  /** Предел окна повторной пробы известного малым значения. */
  private readonly probeLimit: number;

  private value: number;
  /**
   * Тик подтверждённого кадра из последнего эха; `NO_ECHO` — снапшот был, а
   * своего кадра в нём нет; `undefined` — снапшотов с последней точки отсчёта
   * не приходило.
   */
  private echoMarked: number | undefined;
  /** Тик снапшота, в котором это подтверждение приехало. */
  private echoSnapshot = 0;
  /** Последняя наблюдённая отправка: по разрыву в ней видно пропущенные. */
  private lastSeq = -1;
  /** Тик последнего ушедшего кадра: дальше него разметки ещё нет. */
  private lastMarkedTick: number | undefined;
  /** Тик, с которого собственная разметка идёт без дыр: раньше него кадров нет. */
  private markedFrom: number | undefined;
  /** С последней смены точки отсчёта приехал снапшот: канал состояний жив. */
  private sawSnapshot = false;
  /** Отправок с последнего подтверждения: по нему видно протухшее наблюдение. */
  private sinceEcho = 0;
  /** Тик первого кадра под текущим значением; `undefined` — его ещё не было. */
  private barrierTick: number | undefined;
  /** Кадр, помеченный не раньше барьера, подтверждён: разности есть на чём стоять. */
  private proven = false;
  /** Отправки, наблюдавшие чистое эхо, с последней смены значения. */
  private onTime = 0;
  /** Наибольшее значение, оказавшееся малым; `floor − 1` — памяти нет. */
  private knownBad: number;
  /** Текущее значение получено спуском: на него сейчас идёт проба. */
  private probing = false;
  /** Текущее окно повторной пробы: удваивается с каждой неудачей. */
  private probeWindow: number;

  constructor(pacing: Pacing) {
    this.floor = pacing.inputDelay;
    const snapshotEvery =
      pacing.snapshotRate > 0 ? Math.floor(pacing.tickRate / pacing.snapshotRate) : 1;
    this.step = Math.max(1, snapshotEvery);
    this.slack = this.step + (this.step + this.floor) + this.step;
    // Потолок — окно приёма МИНУС собственный запас оценки тика. Кадр помечается
    // от оценки, а подтягивание нормой NTR-10 приводит её в отрезок «тик
    // снапшота + период рассылки + `inputDelay`» (`resyncTick`); между
    // снапшотами оценка идёт собственным темпом и уходит выше ровно на тот же
    // период — за который сервер продвигается на столько же, так что от ЖИВОГО
    // серверного тика превышение остаётся тем же. С запасом ровно в окно кадр
    // уезжал бы ЗА окно приёма и отбрасывался бы сервером — «ввод, теряемый уже не
    // каналом, а собственной разметкой», ради запрета которого NTR-7 и делает
    // окно потолком. Запас остаётся в границах `[inputDelay, inputWindow]`;
    // потолком служит та граница, за которой разметка начинает терять ввод.
    //
    // Инвариант `inputWindow ≥ inputDelay` проверяет сервер на сборке матча
    // (NTR-7), но приезжает `Welcome` с провода: потолок ниже пола дал бы
    // запас, который сам себя опускает под собственную границу.
    this.ceiling = Math.max(this.floor, pacing.inputWindow - this.step - this.floor);
    this.settleWindow = Math.max(1, SETTLE_SECONDS * pacing.tickRate);
    this.probeLimit = this.settleWindow * PROBE_BACKOFF_LIMIT;
    this.probeWindow = this.settleWindow;
    this.knownBad = this.floor - 1;
    this.value = this.floor;
  }

  /** Текущий запас в тиках: им клиент помечает кадр, им же публикуется метрика. */
  get lead(): number {
    return this.value;
  }

  /**
   * Подтверждение из применённого снапшота (NTR-11): `markedTick` — тик, которым
   * клиент пометил подтверждённый кадр (берётся из кольца своих кадров),
   * `snapshotTick` — тик снапшота, в котором подтверждение приехало.
   *
   * Берётся ПОСЛЕДНЕЕ пришедшее подтверждение, а не наибольшее: устаревшие
   * снапшоты клиент отбрасывает до этого места (NTR-2, NTR-16), а после
   * перемотки пара честно меньше прежней — мир вернулся в это состояние целиком.
   */
  applied(markedTick: number, snapshotTick: number): void {
    this.echoMarked = markedTick;
    this.echoSnapshot = snapshotTick;
    this.sinceEcho = 0;
    const barrier = this.barrierTick;
    if (barrier !== undefined && markedTick >= barrier) this.proven = true;
  }

  /**
   * Снапшот применён, а своего кадра в нём нет: `seq` в компоненте ввода либо
   * нулевой (сервер ещё ни одного кадра слота не применял и повторяет нулевой,
   * TICK-2), либо не из кольца — кадр прежней сессии (NTR-17) или вытесненный.
   *
   * Это тоже наблюдение, и ровно то, которого не хватало старту длинного
   * канала: тик снапшота — серверная величина, и снапшот, тик которого уже за
   * барьером, говорит, что сервер прошёл размеченные тики без единого нашего
   * кадра. Разность считается так же, как у подтверждения, только
   * подтверждённого кадра «нет» — он раньше любого размеченного тика.
   */
  noEcho(snapshotTick: number): void {
    this.echoMarked = NO_ECHO;
    this.echoSnapshot = snapshotTick;
    this.sinceEcho = 0;
  }

  /**
   * Снапшот приехал и применён (NTR-2) — независимо от того, подтверждает ли он
   * чей-нибудь кадр.
   *
   * Нужно это ровно сроку эха: до первого подтверждения «эха нет» одинаково
   * выглядит и на канале длиннее запаса, и на оборванном downlink, а лечит запас
   * только первое. Пришедший снапшот и разводит эти два случая.
   */
  snapshotApplied(): void {
    this.sawSnapshot = true;
  }

  /**
   * Смена эпохи (NTR-16): наблюдение начинается заново, значение остаётся.
   *
   * Пара тиков через перемотку не сравнима: номера тиков после неё идут заново,
   * и разность величин двух эпох не значит ничего. Сам запас при этом MUST NOT
   * сбрасываться — он свойство канала, а не ветви истории (NTR-7).
   */
  resync(): void {
    this.rebase();
  }

  /**
   * Живая отправка кадра вместе с тиком, которым он помечен: здесь и только
   * здесь решается судьба запаса.
   *
   * Отправка — единственная точка наблюдения, потому что молчание игрока
   * сигналом не является: нет отправки — нет наблюдения, и запас не двигается ни
   * вверх, ни вниз (design D1). Заморозку сюда не пускает вызывающий: кадры
   * замороженного мира сервер отбрасывает целиком (NET-11), и считать их
   * опозданием значило бы поднимать запас на паузе.
   */
  sent(seq: number, tick: number): void {
    // Пропуск в НОМЕРАХ означает отправки, которых контроллер не видел:
    // замороженный мир (`pushInput` их не показывает) — те кадры сервер отбросил
    // целиком, и счёт их повторами мерил бы длительность заморозки вместо длины
    // канала. Молчание источника ввода номера не тратит и ловится не здесь, а
    // дырой в разметке ниже.
    if (seq !== this.lastSeq + 1) this.rebase();
    this.lastSeq = seq;
    this.sinceEcho++;
    // Дыра в СОБСТВЕННОЙ разметке: тики между прошлой отправкой и этой кадра не
    // получили вовсе — молчал источник ввода либо отставший шаг клиента
    // перешагнул номер через `resyncTick`. Повтор на таких тиках каналом не
    // объясняется, и в серию он не войдёт: наблюдение начинается с этого тика.
    // Назад разметка тоже вправе шагнуть — `resyncTick` опускает оценку до
    // потолка, — и это такой же перезапуск: оставленная впереди точка отсчёта
    // ослепила бы наблюдение до тех пор, пока разметка её снова не догонит.
    const last = this.lastMarkedTick;
    if (last === undefined || tick > last + 1 || tick < last) this.markedFrom = tick;
    this.lastMarkedTick = tick;
    this.barrierTick ??= tick;

    if (!this.proven) {
      // Подтверждения под текущим значением ещё нет. Первый сигнал — срок:
      // просроченный срок — «кадр под этим запасом не доехал к своему тику», и
      // это единственный сигнал на канале, где не применяется ничего. Считается
      // он только при живом канале состояний: без снапшотов эха нет по причине,
      // которую запас не лечит (см. заголовок модуля).
      if (this.sawSnapshot && tick - this.barrierTick >= this.value + this.slack) {
        this.raise();
        return;
      }
      // Второй сигнал — эхо ПРЕЖНИХ кадров, и оно приходит раньше срока. Эхо
      // подтверждает кадр, помеченный ещё до барьера, но снапшот несёт тик
      // сервера: если сервер уже прошёл барьер, а подтверждённым остаётся кадр
      // из-за барьера, то кадры под новым значением к своим тикам не доехали, и
      // серия таких тиков — та же `behindOnChannel`, отсчитанная от барьера
      // (тики до него в неё не входят). Ждать срока значило бы держать слот на
      // повторе ещё «период рассылки + запас оценки + допуск на часы» тиков при
      // каждом подъёме и каждой неудачной пробе — при уже известном ответе.
      // Свежесть наблюдения — то же условие, что у доказанного значения ниже.
      if (this.sinceEcho <= this.slack && this.behindOnChannel() > 0) this.raise();
      return;
    }

    // Подтверждения перестали приходить вовсе: наблюдение протухло, и решать по
    // нему нельзя ни в какую сторону. Повторять последнюю разность до конца
    // матча значило бы спускать запас на оборванном downlink — то есть двигать
    // его потерей снапшотов, ради запрета которой и выбрана тиковая шкала.
    if (this.sinceEcho > this.slack) return;

    // Размеченный тик, прожитый сервером на повторе, — опоздавший кадр, и один
    // такой уже сигнал (см. заголовок модуля): подъём, а не сброс окна.
    if (this.behindOnChannel() > 0) {
      this.raise();
      return;
    }
    this.onTime++;
    if (this.onTime >= this.settleTarget()) this.lower();
  }

  /**
   * Длина серии повторов, за которую отвечает канал: сколько тиков из неё клиент
   * разметил САМ, а сервер всё равно прожил их на повторе.
   *
   * Серия — это тики `(тик подтверждённого кадра, тик снапшота]`. Из неё берутся
   * те, на которые кадр уходил: не раньше начала непрерывной разметки и не
   * позже последнего ушедшего кадра. Тик, размеченный клиентом и всё-таки
   * прожитый сервером на повторе, и означает «мой кадр не доехал к своему
   * тику»; тик, которого клиент не размечал, не означает ничего.
   */
  private behindOnChannel(): number {
    const marked = this.echoMarked;
    const last = this.lastMarkedTick;
    const from = this.markedFrom;
    if (marked === undefined || last === undefined || from === undefined) return 0;
    return Math.max(0, Math.min(this.echoSnapshot, last) - Math.max(marked, from - 1));
  }

  /**
   * Окно, которое обязана выстоять стабильность перед спуском. Обычное — для
   * шага в область, где канал ещё не ломался; растущее — для повторной пробы
   * значения, которое уже оказывалось малым.
   */
  private settleTarget(): number {
    return this.value - 1 <= this.knownBad ? this.probeWindow : this.settleWindow;
  }

  private lower(): void {
    // Значение, простоявшее целое чистое окно НЕ ВЫШЕ памяти о неудаче, эту
    // память опровергло: канал стал короче, и дальше спуск идёт обычным темпом.
    if (this.value <= this.knownBad) {
      this.knownBad = this.floor - 1;
      this.probeWindow = this.settleWindow;
    }
    if (this.value <= this.floor) {
      // На полу спускаться некуда: окно начинается заново, чтобы счётчик не рос
      // без предела.
      this.onTime = 0;
      return;
    }
    this.probing = true;
    this.retune(this.value - 1);
  }

  private raise(): void {
    // Не пережившая проверки проба — не «канал испортился», а «значение мало́»:
    // следующая попытка спуститься сюда обязана быть реже предыдущей.
    if (this.probing) {
      this.probeWindow = Math.min(this.probeLimit, this.probeWindow * PROBE_BACKOFF);
    }
    this.knownBad = Math.max(this.knownBad, this.value);
    // Проба возвращается ровно туда, откуда спустилась: то значение доставку
    // доказало, и шаг подъёма перелетел бы его на лишний тик отклика. Слепой
    // шаг на период рассылки остаётся там, где возвращаться некуда, — на старте
    // и на удлинившемся канале.
    const next = this.probing ? this.value + 1 : this.value + this.step;
    this.probing = false;
    this.retune(Math.min(this.ceiling, next));
  }

  /**
   * Новое значение вместе с новым барьером: следующее решение принимается по
   * кадрам, помеченным уже этим значением, а не по последствиям прошлого.
   */
  private retune(next: number): void {
    this.value = next;
    // Барьер не вычисляется, а НАБЛЮДАЕТСЯ: его ставит первый же кадр, ушедший
    // под новым значением. Кадр, на котором принято решение, помечен ещё
    // прежним, и считать срок от него значило бы считать его от разметки,
    // которой клиент больше не шлёт.
    this.rebase();
  }

  private rebase(): void {
    this.barrierTick = undefined;
    this.proven = false;
    this.onTime = 0;
    // Наблюдение начинается заново ЦЕЛИКОМ, а не одним счётчиком: накопленная
    // серия повторов и разметка, по которой она считалась, относятся к прошлому
    // значению, к прошлой эпохе или к отправкам, которых контроллер не видел.
    // Пережить барьер им значило бы решать по последствиям того, чего больше
    // нет.
    this.echoMarked = undefined;
    this.lastMarkedTick = undefined;
    this.markedFrom = undefined;
    this.sawSnapshot = false;
    this.sinceEcho = 0;
  }
}
