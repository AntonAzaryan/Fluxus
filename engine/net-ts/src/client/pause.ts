/**
 * Доставленное состояние паузы матча (`netcode-transport` NTR-20) на стороне
 * клиента: то, и только то, что сервер о паузе сообщил.
 *
 * Своим модулем, а не полем в `matchClient.ts`, по той же причине, по какой
 * пауза едет своим сообщением, а не битом ввода: с конвейером снапшотов и
 * событий у неё общего нет НИЧЕГО — она не входит в мир, не двигает эпоху и не
 * имеет курсора. Клиент её только принимает и отдаёт наружу.
 *
 * Выводить паузу из косвенных признаков — переставших приходить снапшотов,
 * замершего тика — потребителю нельзя (HUD-9): это картина сбоя сети, а не
 * паузы, и здесь такого источника нет по построению.
 */
import type { PauseMessage } from '../protocol/messages.js';

/**
 * Состояние паузы, доставленное клиенту. Это ровно сообщение `Pause` без типа
 * плюс номер отказа: третьей записи тех же полей рядом с проводной формой быть
 * не должно — она и есть то, что доставили.
 */
export interface DeliveredPause extends Omit<PauseMessage, 'type'> {
  /**
   * Номер отказа: растёт на каждом полученном отказе и ни на чём другом. Нужен
   * потребителю, который показывает причину ограниченное время (HUD-9): два
   * одинаковых отказа подряд по одному полю `denied` неразличимы, и второй не
   * перезапустил бы показ.
   */
  readonly deniedSeq: number;
}

/**
 * Приём сообщения `Pause` (NTR-20). Мира не касается вовсе — как и поток
 * событий: пауза невидима симуляции, эпоха от неё не растёт, а замороженное
 * состояние мира приезжает обычным снапшотом.
 *
 * Курсора у этого сообщения нет и не нужно: состояние паузы конфлатируемо —
 * доехавшее позже описывает матч точнее, — а отбрасывать «устаревшее» по
 * порядку прихода было бы нечем, номера у него нет. Отказ при этом не
 * конфлатируется молча: он считается номером.
 */
export function applyPause(
  previous: DeliveredPause | undefined,
  { type: _type, ...delivered }: PauseMessage,
): DeliveredPause {
  const seq = previous?.deniedSeq ?? 0;
  return { ...delivered, deniedSeq: delivered.denied === undefined ? seq : seq + 1 };
}

/**
 * Стоит ли пауза МАТЧА по доставленному (NTR-20).
 *
 * Отдельный факт от режима мира, и путать их нельзя: в заморозке сервер живых
 * тиков не исполняет и снапшотов не рассылает, поэтому режим последнего
 * применённого снапшота всю паузу описывает мир ДО неё — то есть `Running`.
 * Ничего не доставляли — паузы нет: выдумывать её из молчания нельзя.
 */
export function frozenByMatch(pause: DeliveredPause | undefined): boolean {
  return pause !== undefined && pause.state !== 'running';
}
