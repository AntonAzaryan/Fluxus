/**
 * Ось размещения авторитета (`net-session` SES-1) и наблюдаемость сессии (SES-9).
 *
 * Режим называет ровно одну величину — в каком процессе исполняется авторитетный
 * цикл. Он не предъявляется в сообщениях, не согласовывается в рантайме и не
 * выводится сторонами из поведения: это свойство сборки, и ни `MatchServer`, ни
 * `MatchClient` его не видят (SES-2). Ветвление по режиму внутри сервера или
 * клиента — дефект сборки, а не оптимизация.
 *
 * Публикуемые здесь величины живут по правилам счётчиков (NTR-11): в мир и в
 * канонический `inputs[]` не попадают, на симуляцию не влияют. Именно поэтому
 * утверждение «поменялась только сборка» проверяется тестом — канонические логи
 * матча в `listen` и в `dedicated` обязаны совпасть побитово.
 */

export type SessionMode = 'local' | 'listen' | 'dedicated';

/**
 * Фаза сессии. Разведена с фазой матча (`MatchPhase`) и фазой клиента
 * (`ClientPhase`) намеренно: те отвечают на вопрос «что с матчем», эта — «где
 * остановился участник», и без неё зависшее подключение отлаживается по
 * отсутствию снапшотов, а не по названному месту.
 */
export type SessionPhase = 'publishing' | 'lobby' | 'starting' | 'match' | 'ended';

export interface SessionInfo {
  readonly mode: SessionMode;
  /** Имя реализации рандеву (SES-3) — величина для отчёта, не для ветвления. */
  readonly rendezvous: string;
  phase: SessionPhase;
}

export function createSessionInfo(mode: SessionMode, rendezvous: string): SessionInfo {
  return { mode, rendezvous, phase: 'publishing' };
}
