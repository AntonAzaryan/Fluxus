/**
 * Рандеву за интерфейсом (`net-session` SES-3): как присоединяющийся узнаёт,
 * куда подключаться. Сборка матча не знает, какая реализация под интерфейсом, —
 * ровно как логика матча не знает, какой транспорт под `Transport` (NTR-2).
 *
 * Инвайт для сборки непрозрачен: он одно значение, которое игрок пересылает
 * целиком, а разбирает его только та реализация, что его выдала. Разложение на
 * поля заставило бы каждую реализацию договариваться о наборе, которого у
 * WebRTC не существует.
 *
 * Инфраструктура рандеву авторитетной не бывает: посредник сводит стороны,
 * байты матча через себя не пропускает и симуляции не исполняет. Граница
 * проведена здесь явно, потому что посредник, обрастающий игровой логикой, и
 * есть выделенный сервер, не названный так (SES-3).
 */
import type { Transport, TransportServer } from '../transport/transport.js';

/** Канал сессии. Их два, и оба живут своей фазой: лобби (SES-4) и матч (NTR-4). */
export type SessionChannel = 'lobby' | 'match';

export interface PublishedSession {
  /** Слушающая сторона канала — то, что уедет в `MatchHost` или `LobbyHost`. */
  readonly transports: TransportServer;
  /** Значение, которым присоединяющийся доберётся до этого канала. */
  readonly invite: string;
  close(): Promise<void>;
}

export interface Rendezvous {
  /** Имя реализации: попадает в `SessionInfo` (SES-9) и больше никуда. */
  readonly name: string;
  /** Сторона основателя: опубликовать канал и получить инвайт до него. */
  publish(channel: SessionChannel): Promise<PublishedSession>;
  /** Сторона присоединяющегося: превратить инвайт в транспорт. Дальше идёт обычный хендшейк. */
  resolve(invite: string): Promise<Transport>;
}

/** Отказ рандеву. Отдельный класс: «не разобрал инвайт» и «не достучался» чинятся по-разному, но оба до матча. */
export class RendezvousError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'RendezvousError';
  }
}
