/**
 * Свежий токен допуска для инвайта (`net-session` SES-5).
 *
 * Живёт среди реализаций рандеву, а не рядом с кодированием инвайта, потому что
 * это внешний источник случайности — такая же граница с внешним миром, как
 * сокет и системные часы. К ГПСЧ ядра (RNG-1) отношения не имеет и иметь не
 * может: детерминизм матча от токена не зависит, а зависел бы, живи он внутри
 * чистого цикла.
 *
 * Подменяемость нужна тестам: инвайт с предсказуемым токеном читается глазами.
 */
export function randomToken(): string {
  return globalThis.crypto.randomUUID().replaceAll('-', '');
}
