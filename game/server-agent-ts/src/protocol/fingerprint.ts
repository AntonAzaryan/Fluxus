/**
 * Отпечаток сертификата в одной форме (SRV-3).
 *
 * Живёт в словаре протокола, а не рядом с генерацией сертификата, по той же
 * причине, по которой словарь ничего не импортирует: приводить отпечаток к
 * одной форме приходится ОБЕИМ сторонам — агенту, который его называет, и
 * клиенту, который его закрепляет, — а клиент бывает страницей, где ни
 * `node:crypto`, ни файлов нет.
 */

/**
 * Одна форма отпечатка: нижний регистр, только шестнадцатеричные цифры.
 * TLS-стек Node отдаёт его через двоеточия и в верхнем регистре, агент считает
 * его сам из DER, — и сравнивать их можно, только приведя к одному виду.
 */
export function normalizeFingerprint(value: string): string {
  return value.replace(/[^0-9a-fA-F]/g, '').toLowerCase();
}
