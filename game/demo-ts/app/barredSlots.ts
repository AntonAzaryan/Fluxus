/**
 * Что запертый слот (`netcode-transport` NTR-19, `server-control` SRV-5) значит
 * для СТЕНДА: переезд запрета в следующий круг и диагноз пустой посадки.
 *
 * Обе вещи растут из одного: круг стартует, только когда все слоты ростера
 * заняты, а в запертый слот войти не может никто — `Hello` в него получает
 * названный отказ «НЕЗАВИСИМО от заявленной роли соединения» (NTR-19),
 * заполнитель его не предлагает (BOT-7), заместителя в него не сажают (BOT-14).
 * Значит, пока держится запрет, круг стоит в лобби, и это НОРМА, а не поломка.
 *
 * 1. `carryBarredSlots` — переезд. `MatchServer` у стенда свой на каждый круг
 *    (решение D3), а запирание отменяет только человек, поэтому запрет обязан
 *    переехать сам. И переезд НАЗЫВАЕТСЯ вслух: без этой строки круг стоял бы в
 *    лобби молча. Восстановление одно — `unbar` (SRV-5); недостаёт лишь того,
 *    чтобы оператор узнал, что его пора применить.
 *
 * 2. `seatingIsStandFailure` — диагноз. «Бот не занял ни одного слота, а матч
 *    всё ещё в лобби» стенд считает СВОИМ отказом (разошёлся формат кадра,
 *    версия, контент-пак) и валит им круг: `fail` не пишет строчку, а
 *    завершает раунд ненулевым кодом, то есть под агентом даёт `crashed` и
 *    постмортем (SRV-6). При запертом слоте этот вывод ложен — слот пуст
 *    потому, что так распорядился админ.
 *
 *    Судить об этом по ОТКАЗУ `slot-barred` в отчёте ботов нельзя, хотя это и
 *    выглядит естественным: заполнитель запертые слоты из предложения уже
 *    выкинул, значит такого отказа не приходит никогда, и «оговорка» не
 *    срабатывает. Живой путь мимо неё: круг переносит запрет, вернувшийся
 *    человек взводит дедлайн, бот предлагается на ЕГО слот, получает
 *    `slot-taken` — занятых ноль, фаза `lobby`, `slot-barred` никто не называл,
 *    и стенд роняет круг вместе с сидящим в нём человеком. Поэтому спрашивается
 *    СОСТОЯНИЕ РОСТЕРА: есть ли в нём запертый слот сейчас.
 */

/** Что переехало в новый круг и что сказать об этом оператору. */
export interface CarriedBars {
  /** Слоты, которые запирает новый круг: те же номера, что были заперты. */
  readonly slots: readonly number[];
  /** Строка отчёта стенда; пустая — переезжать нечему, и молчание тут верно. */
  readonly note: string;
}

/**
 * Запреты, переживающие круг: номера для нового хоста плюс строка отчёта.
 *
 * Слот вне ростера отбрасывается молча — ростер у всех кругов один (конфиг тот
 * же, D3), и такого номера в наборе не бывает; проверка стоит затем, чтобы
 * `host.bar` не получил индекс, которого нет.
 */
export function carryBarredSlots(
  barred: Iterable<number>,
  players: readonly string[],
): CarriedBars {
  const slots = [...barred].filter((slot) => slot >= 0 && slot < players.length).sort((a, b) => a - b);
  if (slots.length === 0) return { slots, note: '' };
  const named = slots.map((slot) => `"${players[slot] ?? String(slot)}"`).join(', ');
  return {
    slots,
    note:
      `\nзапертые слоты перенесены в этот круг: ${named} — ` +
      'вход в них закрыт, занять их некому, и круг не начнётся, пока запрет не снят (unbar, SRV-5)\n',
  };
}

/** Исход посадки ботов глазами стенда — ровно то, из чего он ставит диагноз. */
export interface SeatingOutcome {
  /** Сколько мест бот занял. Ноль — предмет диагноза; больше — сажать удалось. */
  readonly taken: number;
  /** Названные сервером причины отказов; пустая строка — отказа по месту не было. */
  readonly rejections: readonly string[];
  /** Матч всё ещё в лобби: круг не начался. */
  readonly lobby: boolean;
  /** Есть ли в ростере хоть один запертый слот ПРЯМО СЕЙЧАС (NTR-19). */
  readonly barred: boolean;
}

/**
 * Считать ли пустую посадку ОТКАЗОМ СТЕНДА (BOT-7) — тем, что валит круг и
 * требует человека, — или её объясняет запрет (NTR-19).
 *
 * Запрет объясняет её ЦЕЛИКОМ и безусловно: пока хоть один слот заперт, круг не
 * начнётся ни при какой посадке, и «в лобби, а мест не занято» перестаёт что-либо
 * говорить о формате кадра или версии сборки. Цена названа: настоящее
 * расхождение версий под запертым слотом стенд не диагностирует — зато оператор
 * получает строку переезда (`carryBarredSlots`), которая говорит, чего ждать.
 */
export function seatingIsStandFailure(outcome: SeatingOutcome): boolean {
  // Кто-то сел либо круг уже идёт — диагностировать нечего.
  if (outcome.taken > 0 || !outcome.lobby) return false;
  if (outcome.barred) return false;
  // Отказ `slot-barred` всё же оставлен поводом смолчать: запереть слот могли
  // между фильтром заполнителя и `Hello` бота, и тогда ростер уже чист, а отказ
  // ещё в пути. Один и тот же факт с двух сторон — гонка тут не должна решать.
  return !outcome.rejections.some((reason) => reason.includes('slot-barred'));
}
