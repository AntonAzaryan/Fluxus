/**
 * Сборка демо для десктоп-контейнера (`desktop-shell` DSK-4).
 *
 * От обычной отличается ровно одним: копии дерева контента внутри бандла нет.
 * В вебе `publicDir: content/` — то, чем оболочка раздаёт дерево (CONT-5), а в
 * контейнере дерево раздаёт сам контейнер, причём ЖИВОЕ: снимок, запечённый в
 * бандл, заслонил бы его собой, и правка документа переставала бы доезжать до
 * кадра (BLND-12) — при том что байты на диске уже другие.
 *
 * Кода демо это не касается ни строкой: приложение остаётся тем же
 * веб-приложением, а различие целиком в том, кто раздаёт файлы (DSK-1).
 */
import { defineConfig } from 'vite';
import base from './vite.config.js';

// База — функция от режима (туннель включается `--mode tunnel`, `tunnel.ts`);
// здесь режим просто пробрасывается: сборке контейнера туннель не грозит —
// плагин живёт только в dev (`apply: 'serve'`).
export default defineConfig((env) => {
  const resolved = base(env);
  return {
    ...resolved,
    publicDir: false,
    build: { ...resolved.build, outDir: 'dist-desktop' },
  };
});
