/**
 * Политика follow-цели демо: за КАКОЙ точкой камера ведёт наблюдение, пока
 * ведомая сущность выбыла из боя (`camera` CAM-2, CAM-5).
 *
 * Механизм — `CameraRig`: follow ведёт точку, поданную кадром, со сглаживанием
 * и порогом рывка. Точку выбирает сборка, и до сих пор она подавалась одна и та
 * же — интерполированная поза инстанса ведомой сущности. Для живого героя это
 * ровно то, что нужно; для выбывшего — нет, и в кадре это видно.
 *
 * Что именно видно. Провалившийся с кромки герой (`arena` ARENA-5, системы
 * сцены `FallStart`/`FallDeath`) продолжает лететь ГОРИЗОНТАЛЬНО мимо арены —
 * смерть наступает только по достижении глубины, а это сотни тиков. Камера,
 * ведущая его позу, уезжает с арены и упирается в границы панорамирования
 * (CAM-3): пол-кадра занимает пустота, а сам герой в кадр не попадает, потому
 * что летит далеко внизу — вертикаль follow не берёт вовсе (CAM-2). Дальше
 * труп лежит там, где упал, ещё шестьсот тиков до возрождения, и всё это время
 * игрок смотрит в никуда за краем арены.
 *
 * Решение — политика сборки, а не правка конвейера: пока ведомая сущность в
 * ВЫБЫВШЕМ состоянии, кадр подаёт ПОСЛЕДНЮЮ её точку в бою и держит её, пока
 * сущность не вернётся. Место гибели остаётся в кадре (игрок видит, где его
 * убили), камера не покидает арену, а возвращение к ожившему герою остаётся
 * обычным решением CAM-5: смещение цели больше порога — рывок, меньше —
 * сглаженный доезд.
 *
 * Выбывшие состояния — ДАННЫЕ сборки (`stateComponents` конфига Extractor'а,
 * CAM-6), а не догадка по позиции: смерть и провал сцена помечает своими
 * компонентами, они уже едут битами `EntityView.states` ради фиксации клипа
 * смерти (`rendering` REND-4), и второго определения «герой выбыл» здесь не
 * заводится.
 */
import { DEAD_COMPONENT, FALLING_COMPONENT, stateBit } from './sim.js';

/** Маска состояний, в которых сущность выбыла из боя (данные сборки). */
export const OUT_OF_PLAY_STATES = stateBit(DEAD_COMPONENT) | stateBit(FALLING_COMPONENT);

/** Точка follow, которую кадр подаёт конвейеру (CAM-2). */
export interface FollowPoint {
  readonly x: number;
  readonly y: number;
  /** Признак разрыва непрерывности доставки (REND-2); порог рывка — за CAM-5. */
  readonly snap: boolean;
}

/** Что кадр знает о ведомой сущности: поза её инстанса и доставленные состояния. */
export interface FollowSample {
  /** Интерполированная поза инстанса; `null` — инстанса в наборе нет. */
  readonly pose: { readonly x: number; readonly y: number } | null;
  /** Маска доставленных состояний (CAM-6); `undefined` — сущности в доставке нет. */
  readonly states: number | undefined;
  readonly snap: boolean;
}

/**
 * Память кадра о последней точке ведомой сущности В БОЮ. Объект, а не свободная
 * функция, потому что решение зависит от ПРОШЛЫХ кадров: точка гибели — та, что
 * была последней до выбывания.
 */
export class HeroFollowPoint {
  /** Кого помним: смена наблюдаемого (CAM-10) память обнуляет. */
  private subject: number | null = null;
  private restX = 0;
  private restY = 0;
  /** Есть ли запомненная точка боя — то есть видели ли мы сущность НЕ выбывшей. */
  private hasRest = false;

  /**
   * Точка этого кадра; `null` — вести некого (инстанса нет), и конвейер тогда
   * остаётся там, где стоял, ровно как прежде.
   */
  point(subject: number | null, sample: FollowSample): FollowPoint | null {
    if (subject !== this.subject) {
      this.subject = subject;
      this.hasRest = false;
    }
    if (subject === null || sample.pose === null) return null;
    const out = (sample.states ?? 0) & OUT_OF_PLAY_STATES;
    if (out === 0) {
      // В бою: ведём сущность и запоминаем, где она была последний раз в бою.
      this.restX = sample.pose.x;
      this.restY = sample.pose.y;
      this.hasRest = true;
      return { x: sample.pose.x, y: sample.pose.y, snap: sample.snap };
    }
    if (!this.hasRest) {
      // Сущность впервые увидена уже выбывшей (вход в идущий матч): места боя у
      // неё для нас нет, и выдумывать его не из чего — держим, где застали.
      this.restX = sample.pose.x;
      this.restY = sample.pose.y;
      this.hasRest = true;
    }
    // Стоячая точка разрыва не несёт: она не движется, и снапать нечего.
    return { x: this.restX, y: this.restY, snap: false };
  }
}
