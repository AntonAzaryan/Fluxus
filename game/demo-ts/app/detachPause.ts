/**
 * Политика стенда «разрыв замораживает матч» (`netcode-transport` NTR-20,
 * решение D6): слот, оставшийся после `Start` без живого соединения, стенд
 * вправе накрыть паузой матча и снять её, когда владелец вернулся реконнектом
 * (NTR-17).
 *
 * Здесь живёт ровно одна политика, и принадлежит она СБОРКЕ, ровно как посадка
 * бота-заместителя (`bot-player` BOT-14, `substitute.ts`): сервер матча даёт
 * механизм — серверное API паузы, — и о разрывах наружу не сообщает и не должен
 * (NTR-3). Наблюдение идёт снаружи: «есть ли у слота живое соединение»
 * (`MatchServer.slotAttached`), «идёт ли матч» и «в каком состоянии пауза».
 *
 * Своя ли это пауза — стенд помнит сам, и это не бухгалтерия ради бухгалтерии:
 * паузу мог поставить игрок (NTR-20), и снимать чужую заморозку, потому что
 * кто-то вернулся, значит распоряжаться чужим запросом. Поэтому снимается
 * только та, которую поставил этот наблюдатель, и только пока её никто не
 * трогал.
 *
 * Паузы перед заморозкой нет, в отличие от посадки заместителя: бот приезжает
 * в матч и занимает слот — операция дорогая и наблюдаемая игроками, — а
 * заморозка отменяется одним вызовом, и её цена для вернувшегося равна
 * объявленному отсчёту возобновления, то есть числу из документа матча.
 *
 * Заморозка на эпизод отвязки — ОДНА (поле `spent`): предельную её длительность
 * задаёт `pause.maxPauseMs` документа матча, и по её истечении сервер
 * возобновляет матч сам. Замораживать снова стенд не вправе — иначе владелец,
 * ушедший навсегда, держал бы матч и слот стенда вечно (см. `spent`).
 */

/** Состояние паузы матча глазами обвязки — те же три значения, что у сервера (NTR-20). */
export type StandPauseState = 'running' | 'frozen' | 'resuming';

export interface DetachPauseOptions {
  /** Ростер матча в порядке конфига: слот — индекс в списке (`tick-loop` TICK-5). */
  readonly players: readonly string[];
  /** Есть ли у слота живое соединение — публичное наблюдение за своим матчем (NTR-18). */
  readonly attached: (slot: number) => boolean;
  /**
   * Заперт ли слот админом (NTR-19). Запертого владельца ЖДАТЬ НЕЛЬЗЯ: его
   * `Hello` получает названный отказ, и вернуться он не может по определению.
   * Считай стенд такой слот «отвязанным» — и админ-операция «убрать игрока»
   * превращалась бы в заморозку всего матча до истечения `pause.maxPauseMs`, а в
   * документе без этого поля — навсегда. NTR-19 требует прямо обратного: «матч
   * продолжается — слот ведёт заместитель или predicted-фреймы».
   */
  readonly barred?: (slot: number) => boolean;
  /** Идёт ли матч: до `Start` и после конца замораживать нечего. */
  readonly running: () => boolean;
  /** Текущее состояние паузы матча (NTR-20). */
  readonly state: () => StandPauseState;
  /** Серверное API паузы: причина отказа либо `undefined`. */
  readonly pause: () => string | undefined;
  readonly resume: () => string | undefined;
  /**
   * Матч ПОКИНУТ всеми: замораживать незачем и нельзя. Заморозка останавливает
   * живые тики, а с ними и порог молчания (NTR-6) — то есть матч, из которого
   * ушли все, не кончился бы никогда, и сборка-основатель осталась бы занята им
   * навсегда. То же условие и по той же причине держит заместителя (BOT-14).
   *
   * Спрашивается на КАЖДОМ взгляде, а не только перед заморозкой: уже стоящую
   * паузу опустевший матч тоже обязан снять — обычный порядок событий именно
   * такой, сперва ушёл один и матч замёрз, потом ушёл второй.
   */
  readonly abandoned?: () => boolean;
  /** Куда сказать о заморозке и снятии: отчёт стенда — его собственный поток. */
  readonly report?: (message: string) => void;
}

export class DetachPause {
  private readonly options: DetachPauseOptions;
  /** Стоит ли сейчас ИМЕННО НАША пауза: чужую этот наблюдатель не снимает. */
  private own = false;
  /**
   * Заморозка этого эпизода отвязки уже израсходована: её сняли не мы —
   * сервер по истечении `pause.maxPauseMs` либо игрок, дождавшийся своего
   * права (NTR-20).
   *
   * Без этой отметки политика встала бы в цикл, который не кончается никогда:
   * `maxPauseMs` истекает → сервер возобновляет → следующий опрос видит тот же
   * слот без соединения → замораживает снова. Серверное API бюджетов игроков
   * не спрашивает (оно не игрок), поэтому упереться этому кругу не во что:
   * матч шёл бы живыми тиками единицы штук в минуту, порог молчания (NTR-6)
   * считается ИМИ и не наступил бы, матч не кончился бы, авто-рестарт не
   * сработал бы, а слот стенда остался бы занят навсегда.
   *
   * Отметка снимается возвращением ПОЛНОГО состава соединений — то есть концом
   * эпизода, а не таймером: одна заморозка на один разрыв, а её предельная
   * длительность и есть `maxPauseMs` документа матча. Дальше матч живёт по
   * своим правилам — доигрывается на predicted-кадрах и кончается порогом
   * молчания, ровно как политика `hold`.
   */
  private spent = false;
  private disposed = false;

  constructor(options: DetachPauseOptions) {
    this.options = options;
  }

  /** Наша ли пауза стоит — наблюдательный доступ для отчёта стенда и тестов. */
  get holding(): boolean {
    return this.own;
  }

  /**
   * Израсходована ли заморозка текущего эпизода отвязки: наблюдательный доступ
   * для отчёта стенда и тестов.
   */
  get exhausted(): boolean {
    return this.spent;
  }

  /**
   * Один взгляд на матч: слот без живого соединения замораживает его, полный
   * состав соединений — снимает.
   *
   * Опросом, а не подпиской, по той же причине, что у заместителя: сервер о
   * разрывах наружу не сообщает (NTR-3), а частота взгляда — дело того, кто
   * держит расписание.
   */
  poll(): void {
    if (this.disposed) return;
    if (!this.options.running()) {
      this.own = false;
      this.spent = false;
      return;
    }
    const missing = this.options.players.some(
      (_, slot) => !this.options.attached(slot) && this.options.barred?.(slot) !== true,
    );
    if (!missing) {
      // Состав полон — эпизод отвязки кончился: снимаем свою заморозку и
      // возвращаем право заморозить СЛЕДУЮЩИЙ разрыв.
      this.unfreeze();
      this.spent = false;
      return;
    }
    // Матч ПОКИНУЛИ, пока мы его держали: заморозку надо отпустить, а не только
    // не ставить. Условие проверяется на КАЖДОМ взгляде, а не однажды на входе,
    // потому что покидают матч не в тот же миг, когда рвётся первое соединение,
    // — обычно как раз наоборот: сперва один ушёл и матч замёрз, потом ушёл
    // второй. Держи мы паузу дальше, живых тиков не стало бы вовсе, порог
    // молчания (NTR-6) считается ИМИ, и матч не кончился бы до истечения
    // `pause.maxPauseMs` — а в документе без этого поля не кончился бы никогда.
    if (this.own && this.options.abandoned?.() === true) {
      this.unfreeze();
      this.spent = true;
      this.options.report?.('матч покинут всеми — заморозка снята, матч доигрывается сам');
      return;
    }
    // Слот всё ещё без соединения, а нашей паузы уже нет: её сняли без нас —
    // сервер по истечении максимальной длительности (NTR-20) либо игрок,
    // дождавшийся своего права. Второй раз в этом же эпизоде отвязки мы её не
    // поставим (см. `spent`).
    if (this.own && this.options.state() === 'running') {
      this.own = false;
      this.spent = true;
      this.options.report?.('пауза при разрыве снята не нами — матч доигрывается без заморозки');
    }
    this.freeze();
  }

  /** Снять свою заморозку и перестать наблюдать: матч сворачивается. */
  dispose(): void {
    this.disposed = true;
    if (this.own && this.options.state() === 'frozen') this.options.resume();
    this.own = false;
  }

  private freeze(): void {
    if (this.own || this.spent) return;
    if (this.options.state() !== 'running') return;
    // За паузу мог уйти последний человек: замороженный матч не кончится сам.
    if (this.options.abandoned?.() === true) return;
    const denied = this.options.pause();
    if (denied !== undefined) {
      // Отказ называется вслух: «стенд не заморозил матч» отлаживается по
      // причине, а не по эффекту (тот же довод, что у диагностики перемотки).
      this.options.report?.(`пауза при разрыве не поставлена: ${denied}`);
      return;
    }
    this.own = true;
    this.options.report?.('слот без соединения — матч заморожен до возврата владельца');
  }

  private unfreeze(): void {
    if (!this.own) return;
    // Паузы уже нет — её сняли без нас: снимать нечего, и держаться за неё
    // больше незачем. Без этой ветви `own` остался бы взведённым навсегда, и
    // следующий разрыв не заморозил бы матч вовсе.
    if (this.options.state() === 'running') {
      this.own = false;
      return;
    }
    // Возобновление уже объявлено — доводится до конца: второго снятия у
    // объявленного отсчёта нет (NTR-20).
    if (this.options.state() !== 'frozen') return;
    const denied = this.options.resume();
    if (denied !== undefined) {
      this.options.report?.(`пауза после возврата не снята: ${denied}`);
      return;
    }
    this.own = false;
    this.options.report?.('владелец вернулся — матч возобновляется');
  }
}
