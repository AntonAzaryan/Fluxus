/**
 * Политика завершения менеджера (`server-manager` MGR-4): что страница отвечает
 * контейнеру на запрос закрытия и что успевает сделать до ответа.
 *
 * Живёт она здесь, а не в `app/main.ts`, по той же причине, по которой здесь
 * живёт сама сессия: «при включённом переключателе закрытие менеджера SHALL
 * останавливать серверы локального агента И САМ АГЕНТ» — это утверждение о
 * поведении, и закрепляться оно обязано тестом, а не глазами по закрывающемуся
 * окну. В `app/` остаётся подписка на запрос: она уже монтирование, а не предмет.
 *
 * Контейнер о переключателе не знает и знать не должен — он исполняет явную
 * остановку объявленного сервиса, как всякую другую (DSK-7, решение D6).
 *
 * Порядок здесь и есть лекарство от гонки: сперва `stop-all` кадром по
 * управляющему каналу, затем явная остановка сервиса агента, и только потом
 * согласие на закрытие. Иначе сигнал уносил бы агента вместе с недоставленным
 * `stop-all`, и серверы пережили бы менеджер при тумблере «да».
 */
import { AGENT_SERVICE, type ManagerBridge } from './localAgent.js';
import type { ManagerSession, ManagerState } from './session.js';

/**
 * Что политике нужно от моста контейнера — ровно остановка сервиса (DSK-7).
 * Взято `Pick`'ом из контракта моста, а не описано здесь второй раз: направление
 * зависимости «приложение → контракт» то же, каким пользуется весь остальной
 * менеджер (DSK-2).
 */
export type CloseBridge = Pick<ManagerBridge, 'stopService'>;

/**
 * Что политике нужно от сессии: положение переключателя и её собственная
 * остановка серверов. Узкой формой, а не целой сессией, чтобы проверка политики
 * не требовала живого агента: остановку серверов закрепляет свой тест
 * (`session.closing()`), а здесь предмет — порядок и второй шаг.
 */
export interface ClosingSession {
  readonly state: Pick<ManagerState, 'killOnExit'>;
  closing: ManagerSession['closing'];
}

/**
 * Ответ на запрос закрытия (MGR-4). Возвращает `true` всегда: несохранённых
 * правок у менеджера нет, и держать окно ему нечем — а на молчание страницы у
 * контейнера есть свой крайний срок (`CLOSE_ANSWER_MS`).
 *
 * Моста может не быть вовсе (обычная вкладка браузера): сервиса агента без него
 * не существует, и останавливать остаётся только серверы.
 */
export async function closeManager(
  session: ClosingSession,
  bridge: CloseBridge | undefined,
): Promise<boolean> {
  if (session.state.killOnExit) {
    await session.closing();
    // Отказ остановки не держит окно: агент мог уже уйти сам, а закрытие
    // менеджера — не место для отказов (тот же выбор, что в `closing()`).
    await bridge?.stopService?.(AGENT_SERVICE).catch(() => undefined);
  }
  return true;
}
